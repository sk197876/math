(** Federer (1969), 3.4.7, p. 325: the
    zero and whole ideals require no positive-order
    divisor. These supporting endpoint proofs allow the
    Noetherian induction to choose a nonzero divisor
    only in a proper nonzero ideal. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
From Federer Require Import CommutativeIdealUP CommutativeFactorizationUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [commutative_ideal_unit_contains_one]: an
    ideal containing a unit is the whole ring,
    supporting the proper-ideal case of 3.4.7, p. 325. *)
Lemma commutative_ideal_unit_contains_one (A:comNzRingType) (I:set A)
    (hI:is_commutative_ideal I) x:
  I x ->is_commutative_unit x ->I 1.
Proof.
move=>hx [y hy];rewrite -hy;exact:(@commutative_ideal_mul A I hI y x hx).
Qed.

(** Source for [commutative_ideal_one_finite]: the whole
    ideal is generated by one, supporting 3.4.7, p. 325. *)
Lemma commutative_ideal_one_finite (A:comNzRingType) (I:set A):
  is_commutative_ideal I ->I 1 ->is_finitely_generated_commutative_ideal I.
Proof.
move=>hI hOne;exists [::1];constructor;first exact:hI.
- move=>x;change (x \in [::1] ->I x).
  rewrite in_cons in_nil orbF;move/eqP=>->;exact:hOne.
- move=>J hJ hGenerators x hx.
  have hJOne:J 1:=hGenerators 1 (mem_head 1 [::]).
  have hh:=@commutative_ideal_mul A J hJ x 1 hJOne.
  by rewrite mulr1 in hh.
Qed.

(** Source for [commutative_ideal_zero_finite]: the zero
    ideal is generated by the empty family, supporting
    3.4.7, p. 325. *)
Lemma commutative_ideal_zero_finite (A:comNzRingType) (I:set A):
  is_commutative_ideal I ->(forall x,I x ->x = 0) ->
  is_finitely_generated_commutative_ideal I.
Proof.
move=>hI hZero;exists [::];constructor;first exact:hI.
- move=>x;change (x \in [::] ->I x);by rewrite in_nil.
- move=>J hJ hEmpty x hx;rewrite (hZero x hx);exact:commutative_ideal_zero hJ.
Qed.
