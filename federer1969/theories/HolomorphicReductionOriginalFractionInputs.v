(** Source for [holomorphic_reduction_original_fraction_finite]: the
    original fraction extension is finite, 3.4.12, p. 339. *)
Theorem holomorphic_reduction_original_fraction_finite:
  is_finitely_generated_ring_submodule (setT:set [the lmodType M of ring_restricted_space phi L^o]).
Proof.
exact:(@holomorphic_reduction_fraction_field_finite R X NX hNX n e he omega hDual
  rotated hRotI hRotProper C pi hPi m hMN
  (fun j hJ=>(holomorphic_reduction_B_membership laws j g).1 (@hAllB j hJ))
  L inclusion hFraction M eta phi hCoefficient).
Qed.
(** Source for [holomorphic_reduction_original_fraction_generators]: the
    original remaining coordinate classes generate the whole extension,
    3.4.12, p. 339. *)
Theorem holomorphic_reduction_original_fraction_generators:
  is_generated_commutative_subring
    (fun y:L=>(exists i:'I_(n-m),y=inclusion (pi (gamma (ordinal_coordinate_tail_index hMN i)))) \/
      exists a:M,y=phi a) setT.
Proof.
exact:(@holomorphic_reduction_fraction_coordinate_generators R X NX hNX n e he omega hDual
  rotated hRotI hRotProper C pi hPi m hMN
  (fun j hJ=>(holomorphic_reduction_B_membership laws j g).1 (@hAllB j hJ))
  L inclusion hFraction M eta phi hCoefficient).
Qed.
