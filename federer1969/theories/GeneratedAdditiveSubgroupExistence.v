(** Federer (1969), 4.1.22, p. 379: existence of the
    independently specified subgroup generated by the prescribed
    simplex currents. The intersection is only an existence
    witness; consumers use the sealed value and abstract laws. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets.
From Federer Require Import TopologicalGroupUP GeneratedAdditiveSubgroupUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [generated_additive_subgroup_exists]: the
    additive subgroup generated by any prescribed family exists,
    supporting the definition in Federer 4.1.22, p. 379.
    Empty and repeated generators are allowed. *)
Theorem generated_additive_subgroup_exists (V:zmodType) (D:set V):
  exists G:set V,is_generated_additive_subgroup D G.
Proof.
pose G:set V:=[set x|forall H:set V,
  is_subgroup (fun a b:V=>a+b) (fun a=>-a) 0 H->D `<=` H->H x].
have hG:is_subgroup (fun a b:V=>a+b) (fun a=>-a) 0 G.
  constructor.
  - move=>H hH hD;exact:subgroup_unit hH.
  - move=>x y hx hy H hH hD.
    exact:(@TopologicalGroupUP.subgroup_mul V (fun a b:V=>a+b) (fun a=>-a) 0 H hH
      x y (@hx H hH hD) (@hy H hH hD)).
  - move=>x hx H hH hD.
    exact:(@TopologicalGroupUP.subgroup_inv V (fun a b:V=>a+b) (fun a=>-a) 0 H hH
      x (@hx H hH hD)).
exists G;constructor;first exact:hG.
- move=>x hx H hH hD;exact:hD x hx.
- move=>H hH hD x hx;exact:hx H hH hD.
Qed.
