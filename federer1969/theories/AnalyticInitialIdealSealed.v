(** Federer (1969), 3.4.11, p. 338:
    the original leading ideal remains behind its
    independently specified least-ideal interface. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets reals.
From Federer Require Import RealNormUP AnalyticGermRing AnalyticInitialPolynomialGermUP
  AnalyticInitialIdealExistence.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.
Module Type AnalyticInitialIdealSignature.
(** Source for [value]: the ideal generated by
    all original leading polynomial germs, 3.4.11, p. 338. *)
Parameter value:forall (R:realType) (X:lmodType R) (NX:X->R) (hNX:is_real_norm NX),
  set (@analytic_germ_ring R X NX hNX 0)->set (@analytic_germ_ring R X NX hNX 0).
(** Source for [laws]: the independent least-ideal
    property of the original leading ideal, 3.4.11, p. 338. *)
Parameter laws:forall (R:realType) (X:lmodType R) (NX:X->R) (hNX:is_real_norm NX)
  (I:set (@analytic_germ_ring R X NX hNX 0)),is_analytic_initial_ideal I (@value R X NX hNX I).
End AnalyticInitialIdealSignature.
Module AnalyticInitialIdeal:AnalyticInitialIdealSignature.
(** Source for [value]: private selection from proved
    leading-ideal existence, supporting 3.4.11, p. 338. *)
Definition value (R:realType) (X:lmodType R) (NX:X->R) (hNX:is_real_norm NX)
  (I:set (@analytic_germ_ring R X NX hNX 0)):=
  projT1 (cid (@analytic_initial_ideal_exists R X NX hNX I)).
(** Source for [laws]: the selected ideal satisfies
    its independent original generator laws, 3.4.11, p. 338. *)
Lemma laws (R:realType) (X:lmodType R) (NX:X->R) (hNX:is_real_norm NX)
  (I:set (@analytic_germ_ring R X NX hNX 0)):is_analytic_initial_ideal I (@value R X NX hNX I).
Proof. exact:(projT2 (cid (@analytic_initial_ideal_exists R X NX hNX I))). Qed.
End AnalyticInitialIdeal.
