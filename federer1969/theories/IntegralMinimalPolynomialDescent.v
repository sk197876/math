(** Source for [integral_minimal_polynomial_original_kernel]:
    the original P intersection I_g is
    generated by its original monic minimal
    polynomial, 3.4.8(10), p. 330. Integrality
    supplies a monic annihilator; the existing
    field kernel theorem and monic Gauss
    descent supply the original coefficients and
    exact original divisibility criterion. *)
Theorem integral_minimal_polynomial_original_kernel
  (A B:comNzRingType) (K:fieldType) (D:comNzRingType) (L:fieldType)
  (embedA:{rmorphism A->B}) (variableA:B) (source:B->nat->A)
  (embedK:{rmorphism K->D}) (variableK:D) (target:D->nat->K)
  (hA:is_commutative_polynomial_ring embedA variableA source)
  (hK:is_commutative_polynomial_ring embedK variableK target)
  (phi:{rmorphism A->K}) (hField:is_commutative_fraction_field phi)
  (hUFD:is_unique_factorization_commutative_domain A)
  (map:{rmorphism B->D}) (hMap:is_polynomial_coefficient_map source target phi map)
  (chi:{rmorphism A->L}) (psi:{rmorphism K->L}) (x:L)
  (E:{rmorphism B->L}) (F:{rmorphism D->L}):
  (forall a:A,chi a = psi (phi a)) ->
  is_commutative_polynomial_evaluation embedA variableA chi x E ->
  is_commutative_polynomial_evaluation embedK variableK psi x F ->
  is_integral_ring_element chi x ->exists (G:B) (H:D) k,
    is_minimal_field_polynomial target F H k /\
    map G = H /\is_monic_polynomial source G k /\
    (forall P:B,E P = 0 <->commutative_divides G P).
Proof.
move=>hTriangle hE hF hIntegral.
have hDiagram:=@polynomial_evaluation_coefficient_extension A B K D L
  embedA variableA source embedK variableK target hA hK phi map hMap chi psi x E F hTriangle hE hF.
have [W [r [hMonicW [hPositiveW hZeroW]]]]:=
  @integral_ring_element_monic_annihilator A B L embedA variableA source hA chi x E hE hIntegral.
have hMapDegree:=@polynomial_coefficient_map_degree A B K D source target
  phi map W r hMap (fraction_field_embedding_injective hField) hMonicW.1.
have hMapMonic:is_monic_polynomial target (map W) r.
  split;first exact:hMapDegree.
  by rewrite hMap hMonicW.2 rmorph1.
have hMapNonzero:=@polynomial_degree_implies_nonzero K D embedK variableK target hK
  (map W) r hMapDegree.
have hMapZero:F (map W) = 0 by rewrite -hDiagram.
have [H [k hH]]:=@minimal_field_polynomial_exists K D L embedK variableK target hK F
  (ex_intro _ (map W) (conj hMapNonzero hMapZero)).
have hDivides:commutative_divides H (map W):=(minimal_field_polynomial_kernel hH _).1 hMapZero.
have [G [hG [hMonicG _]]]:=@gauss_monic_divisor_original_coefficients A B K D
  embedA variableA source embedK variableK target hA hK phi hField hUFD map hMap W r H k
  hMonicW (minimal_field_polynomial_monic hH) hDivides.
have hPrimitive:is_primitive_polynomial source (@is_commutative_prime_element A) (@commutative_divides A) G.
  move=>p hPrime;exists k;rewrite hMonicG.2=>hDividesOne.
  exact:hPrime.2.1 ((commutative_divides_one_unit p).1 hDividesOne).
have hMapInjective:=@polynomial_coefficient_map_injective A B K D embedA variableA source target
  hA phi map hMap (fraction_field_embedding_injective hField).
have hZeroG:E G = 0 by rewrite hDiagram hG;exact:minimal_field_polynomial_vanishes hH.
exists G,H,k;split;first exact:hH.
split;first exact:hG.
split;first exact:hMonicG.
move=>P;split.
- move=>hZero.
  have hZeroMap:F (map P) = 0 by rewrite -hDiagram.
  have [Q hQ]:=(minimal_field_polynomial_kernel hH (map P)).1 hZeroMap.
  rewrite -hG in hQ.
  have [Q0 hQ0]:=@gauss_divisor_integrality A B K D embedA variableA source embedK variableK target
    hA hK phi hField hUFD map hMap G P Q hPrimitive hQ.
  exists Q0;apply:hMapInjective;by rewrite rmorphM -hQ0 -hQ.
- move=>[Q ->];by rewrite rmorphM hZeroG mulr0.
Qed.
