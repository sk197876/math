(** Source for [rees_subring_generated]: constants and
    the original finite ideal generators times the variable
    generate exactly the specified Rees subring, as in
    the cited Lemma 1, supporting 3.4.8(5), p. 328. *)
Theorem rees_subring_generated (A B:comNzRingType)
    (embed:{rmorphism A->B}) (variable:B) (coefficient:B->nat->A)
    (hP:is_commutative_polynomial_ring embed variable coefficient)
    (I:set A) (F:seq A):
  is_generated_commutative_ideal [set a:A|a \in F] I ->
  is_generated_commutative_subring
    [set P:B|(exists a:A,P=embed a) \/exists f:A,f \in F /\P=embed f*variable]
    (@ReesSubring.value A B coefficient I).
Proof.
move=>hI.
pose S:=@ReesSubring.value A B coefficient I.
have hS:=@ReesSubring.laws A B coefficient I.
pose power:=@CommutativeIdealPowers.value A I.
have hPowers n:=@commutative_ideal_power_is_ideal A I n.
have hIdeal:=generated_commutative_ideal_laws hI.
constructor.
- exact:(@rees_subring_is_subring A B embed variable coefficient hP I).
- move=>P [[a ->]|[f [hf ->]]];apply/(hS _)=>n.
  + rewrite (@polynomial_coefficient_constant A B embed variable coefficient hP).
    case:n=>[|n];first by rewrite (@commutative_ideal_power_zeroE A I).
    exact:commutative_ideal_zero (hPowers n.+1).
  + have hCoeff:=@polynomial_monomial_coefficient A B embed variable coefficient hP f 1%N n.
    rewrite expr1 in hCoeff;rewrite hCoeff.
    case:(eqVneq n 1%N)=>[->|hNe];last exact:commutative_ideal_zero (hPowers n).
    rewrite (@commutative_ideal_power_oneE A I hIdeal).
    exact:(@generated_commutative_ideal_contains A _ _ hI f hf).
- move=>T hT hGenerators.
  have hConstants a:T (embed a) by apply:hGenerators;left;by exists a.
  have hFirst:forall a:A,I a ->T (embed a*variable).
    have hJ:=@monomial_subring_coefficient_ideal A B embed variable T 1%N hT hConstants.
    have hContained:I `<=` (fun a:A=>T (embed a*variable^+1)).
      apply:(generated_commutative_ideal_minimal hI hJ)=>a ha.
      rewrite expr1;apply:hGenerators;right;exists a;by split.
    move=>a ha;have h:=hContained a ha;by rewrite expr1 in h.
  have hMonomials:forall n a,power n a ->T (embed a*variable^+n).
    elim=>[|n ih] a ha.
    + rewrite expr0 mulr1;exact:hConstants.
    + have hJ:=@monomial_subring_coefficient_ideal A B embed variable T n.+1 hT hConstants.
      have hContained:@CommutativeIdealProduct.value A I (power n) `<=`
          (fun a:A=>T (embed a*variable^+n.+1)).
        apply:commutative_ideal_product_minimal;first exact:hJ.
        move=>b c hb hc.
        have hBMonomial:T (embed b*variable^+1) by rewrite expr1;exact:hFirst b hb.
        have hProduct:=@commutative_subring_multiply B T hT (embed b*variable^+1) (embed c*variable^+n)
          hBMonomial (ih c hc).
        rewrite (@polynomial_monomial_multiply A B embed variable b c 1 n) add1n in hProduct.
        exact:hProduct.
      apply:hContained.
      by rewrite -(@commutative_ideal_power_successorE A I n).
  move=>P /(hS P) hCoefficients.
  have [N hN]:=@polynomial_coefficients_finite A B embed variable coefficient hP P.
  rewrite (@polynomial_finite_expression A B embed variable coefficient hP P N hN).
  apply:(commutative_subring_finite_sum hT)=>i _ _.
  exact:hMonomials i (coefficient P i) (hCoefficients i).
Qed.
