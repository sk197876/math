(** Supporting algebra for Federer (1969), 3.4.8(5),
    p. 328: the Rees subring is generated by the
    original constants and degree-one monomials of any
    ideal generators. No finite algebra-generation conclusion
    is assumed. Source: Bourbaki, Commutative Algebra (1972),
    Chapter III, section 3, no. 1, Lemma 1, p. 197. *)
From mathcomp Require Import all_boot all_order ssralg boolp classical_sets.
From Federer Require Import CommutativeIdealUP CommutativeSubringUP CommutativeSubringLaws
