(** Federer (1969), 3.4.7, p. 325: evaluation
    identifies the formal polynomial algebra with the
    subring generated by the original coefficients and
    selected variable. Injectivity is a separate analytic proof. *)
From mathcomp Require Import all_boot all_order ssralg boolp classical_sets.
From Federer Require Import CommutativePolynomialUP CommutativePolynomialEvaluationUP
  CommutativePolynomialEvaluationLaws CommutativeSubringUP CommutativeSubringLaws.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [polynomial_evaluation_image_generated]: the
    image of actual polynomial evaluation is exactly
    the least subring containing the original coefficient
    image and selected variable, supporting P in
    3.4.7, p. 325. *)
Theorem polynomial_evaluation_image_generated (A B C:comNzRingType)
    (embed:{rmorphism A->B}) (variable:B) (coefficient:B->nat->A)
    (hP:is_commutative_polynomial_ring embed variable coefficient)
    (phi:{rmorphism A->C}) (t:C) (E:{rmorphism B->C})
    (hE:is_commutative_polynomial_evaluation embed variable phi t E):
  is_generated_commutative_subring (fun x=>x = t \/exists a:A,x = phi a)
    (fun x=>exists P:B,x = E P).
Proof.
constructor.
- constructor.
  + exists 0;by rewrite rmorph0.
  + exists 1;by rewrite rmorph1.
  + move=>x y [P ->] [Q ->];exists (P+Q);by rewrite rmorphD.
  + move=>x [P ->];exists (-P);by rewrite rmorphN.
  + move=>x y [P ->] [Q ->];exists (P*Q);by rewrite rmorphM.
- move=>x [->|[a ->]].
  + exists variable;exact:esym (@polynomial_evaluation_variable A B C embed variable phi t E hE).
  + exists (embed a);exact:esym (@polynomial_evaluation_constants A B C embed variable phi t E hE a).
- move=>J hJ hGenerators x [P ->].
  have [N hN]:=@polynomial_coefficients_finite A B embed variable coefficient hP P.
  rewrite (@polynomial_evaluation_finite_expression A B C embed variable coefficient hP phi t E hE P N hN).
  apply:(commutative_subring_finite_sum hJ)=>i _ _.
  apply:(@commutative_subring_multiply C J hJ).
  + apply:hGenerators;right;by exists (coefficient P i).
  + apply:(commutative_subring_power hJ);apply:hGenerators;by left.
Qed.
