(** Federer (1969), 3.4.8(8), p. 329:
    the field generated by the original coefficient
    subring lies in the quotient's fraction field.
    State the extension equation before choosing its
    map; reuse the fraction-field laws of 3.4.7. *)
From mathcomp Require Import all_boot all_order all_algebra boolp.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.

(** Source for [is_fraction_field_extension]: the
    inclusion of the original coefficient subring
    extends to its fractions, supporting M inside L
    in 3.4.8(8), p. 329. The equation specifies
    the extension without a fraction representation. *)
Definition is_fraction_field_extension (A:comNzRingType) (L K:fieldType)
  (embed:{rmorphism A->L}) (f:{rmorphism A->K}) (extend:{rmorphism L->K}):Prop:=
  forall a:A,extend (embed a) = f a.
