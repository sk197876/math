(** Federer (1969), 3.4.12, p. 339, extending 3.4.7, p. 325: every
    original directional polynomial remainder belongs to
    the transverse module generated by 1, xi, ..., xi^(k-1).
    The actual divided fields and the proved division
    representation supply its coefficients. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets reals.
From Federer Require Import ScalarRestriction ComplexScalarSealed ComplexNormUP ComplexModulus HolomorphicLinear HolomorphicGermArithmeticRepresentatives HolomorphicGermOperationsUP Hom RealNormUP NormDifferentialUP NormOpenDomainLaws
  HolomorphicAtUP HolomorphicGermRepresentatives HolomorphicGermUP
  HolomorphicGermSealed HolomorphicGermRingLaws HolomorphicGermRing HolomorphicGermFiniteSum HolomorphicGermPowers
  HolomorphicPullbackRepresentative HolomorphicPullbackSealed HolomorphicPullbackRingMorphism
  RingScalarRestriction RingSubmoduleUP RingSubmoduleFiniteSums TransverseHolomorphicCoefficients
  ComplexWeierstrassTransverseUP ComplexWeierstrassTransversePullback ComplexWeierstrassDivisionUP ComplexWeierstrassCoefficientUP
  ComplexWeierstrassCoefficientExistence ComplexWeierstrassPolynomialHighCoefficients
  ComplexWeierstrassFiniteRemainderRepresentation.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.
Section RemainderModule.
Variable R:realType.
Variables X K:lmodType (ComplexScalars.C R).
Variables (NX:X->R) (NK:K->R).
Variables (hNX:is_complex_norm NX) (hNK:is_complex_norm NK).
Variable v:X.
Variable xi:Hom X (ComplexScalars.C R)^o.
Variables (inclusion:Hom K X) (projection:Hom X K).
Variable hSplit:is_complex_weierstrass_transverse_space NX NK v xi inclusion projection.
(** Source for [projection_at_origin]: the actual
    projection is analytic at zero, 3.4.7, p. 325. *)
Let projection_at_origin:=@complex_weierstrass_transverse_projection_holomorphic R X K NX NK hNX hNK
  v xi inclusion projection hSplit.
(** Source for [coefficient_ring]: the original transverse
    germ ring, centred at projection of zero, which
    is zero by linearity, 3.4.7, p. 325. *)
Let coefficient_ring:comNzRingType:=
  [the comNzRingType of (@holomorphic_germ_ring R K NK (complex_norm_real hNK) (projection 0))].
(** Source for [ambient_ring]: the original ambient
    germ ring in 3.4.7, p. 325. *)
Let ambient_ring:comNzRingType:=
  [the comNzRingType of (@holomorphic_germ_ring R X NX (complex_norm_real hNX) 0)].
(** Source for [transverse_embed]: the original pullback
    giving the scalar action, 3.4.7, p. 325. *)
Let transverse_embed:{rmorphism coefficient_ring->ambient_ring}:=
  @holomorphic_germ_ring_pullback R X K NX NK (complex_norm_real hNX) (complex_norm_real hNK) setT projection 0 projection_at_origin.

(** Source for [complex_weierstrass_remainder_in_transverse_module]:
    the remainder in 3.4.7, p. 325, lies
    in the actual finite power module. The only
    module premises are its independent closure and
    generator laws; neither remainder membership nor any
    Noetherian conclusion is supplied as a premise. *)
Theorem complex_weierstrass_remainder_in_transverse_module k
    (fXi:@holomorphic_representative_type R X NX (complex_norm_real hNX) 0)
    (M:set (ring_restricted_space transverse_embed ambient_ring^o))
    (rho:ambient_ring):
  @norm_bounded_linear R (restricted_space (ComplexScalars.embed R) X)
    (restricted_space (ComplexScalars.embed R) (ComplexScalars.C R)^o) NX (@complex_modulus R) (complex_hom_real xi) ->
  (forall x,holomorphic_representative_value fXi x = xi x) ->
  @is_ring_submodule coefficient_ring
    [the lmodType coefficient_ring of (ring_restricted_space transverse_embed ambient_ring^o)] M ->
  (forall i,(i<k)%N ->M ((holomorphic_germ fXi:ambient_ring)^+i)) ->
  @is_complex_directional_polynomial_germ R X NX (complex_norm_real hNX) k v rho ->M rho.
Proof.
move=>hXi hXiValues hM hGenerators hPolynomial.
have [r hR]:=@complex_weierstrass_split_coefficients_exist R X K NX hNX rho v inclusion.
have hHigh:=@complex_weierstrass_polynomial_high_coefficients R X K NX hNX k v inclusion rho r
  hPolynomial hR.
have [g [hGRho [U [haU [C [hC [_ hValues]]]]]]]:=@complex_weierstrass_finite_remainder_representation
  R X K NX NK hNX v xi inclusion projection k rho r hSplit hXi hR hHigh.
have hPower i:=@holomorphic_representative_power_exists R X NX (complex_norm_real hNX) 0 fXi i.
have [powers hPowers]:=choice hPower.
have hCoefficient i:exists c:@holomorphic_representative_type R K NK (complex_norm_real hNK) (projection 0),
    forall z,holomorphic_representative_value c z = C i (inclusion z).
  exact:(@transverse_holomorphic_coefficient_representative R X K NX NK hNX hNK
    v xi inclusion projection (C i) U hSplit haU (hC i)).
have [coefficients hCoefficients]:=choice hCoefficient.
pose pullback i:=@holomorphic_pullback_representative R X K NX NK (complex_norm_real hNX) (complex_norm_real hNK) setT
  projection 0 projection_at_origin (coefficients i).
pose terms (i:'I_k):=@holomorphic_multiply_representatives R X NX (complex_norm_real hNX) 0 (powers i) (pullback i).
have hTerm i:(holomorphic_germ (terms i):ambient_ring) =
    transverse_embed (holomorphic_germ (coefficients i))*(holomorphic_germ fXi:ambient_ring)^+i.
  rewrite /terms -(@holomorphic_germ_multiply_equation _ _ _ _ _ _ _ _ (@HolomorphicGerms.laws R X NX (complex_norm_real hNX) 0)).
  have hPullback:(holomorphic_germ (pullback i):ambient_ring) =
      transverse_embed (holomorphic_germ (coefficients i)).
    exact:esym (@HolomorphicPullback.laws R X K NX NK (complex_norm_real hNX) (complex_norm_real hNK) setT projection 0
      projection_at_origin (coefficients i)).
  change ((holomorphic_germ (powers i):ambient_ring)*holomorphic_germ (pullback i) =
    transverse_embed (holomorphic_germ (coefficients i))*(holomorphic_germ fXi:ambient_ring)^+i).
  by rewrite hPullback (hPowers i).2 mulrC.
have hTermMembership i:M (holomorphic_germ (terms i):ambient_ring).
  rewrite hTerm.
  exact:(@ring_submodule_scale coefficient_ring
    [the lmodType coefficient_ring of (ring_restricted_space transverse_embed ambient_ring^o)]
    M hM (holomorphic_germ (coefficients i)) ((holomorphic_germ fXi:ambient_ring)^+i)
    (hGenerators i (ltn_ord i))).
pose F:=map terms (enum 'I_k).
have hFiniteValues x:holomorphic_representative_value g x =
    \sum_(term<-F) holomorphic_representative_value term x.
  rewrite hValues /F big_map -big_enum.
  apply:eq_bigr=>i _.
  change ((xi x)^+i*C i (inclusion (projection x)) =
    holomorphic_representative_value (powers i) x*holomorphic_representative_value (pullback i) x).
  by rewrite (hPowers i).1 hXiValues /pullback /= (hCoefficients i).
have hGermSum:=@holomorphic_germ_finite_sum_equation R X NX (complex_norm_real hNX) 0 F g hFiniteValues.
rewrite -hGRho hGermSum.
apply:(@ring_submodule_mapped_sum coefficient_ring
  [the lmodType coefficient_ring of (ring_restricted_space transverse_embed ambient_ring^o)]
  M hM (@holomorphic_representative_type R X NX (complex_norm_real hNX) 0) F
  (fun term=>(holomorphic_germ term:ambient_ring)))=>term.
rewrite /F;move/mapP=>[i _ ->];exact:hTermMembership i.
Qed.
End RemainderModule.
