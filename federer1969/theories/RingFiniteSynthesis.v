(** Federer (1969), 3.4.7, p. 325: the
    span of the original finite power family is the
    image of a finite free module. Finite sums prove
    this existence statement; the module retains its independent
    least-submodule definition. *)
From HB Require Import structures.
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets functions.
From Federer Require Import RingSubmoduleUP RingSubmoduleLinear.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [ring_finite_synthesis]: the finite
    scalar-coordinate map onto the module generated by
    the powers of xi, supporting 3.4.7, p. 325. *)
Definition ring_finite_synthesis (A:nzRingType) (V:lmodType A) n
    (e:'I_n->V) (c:{ffun 'I_n->A^o}):V:=\sum_(i<n) c i*:e i.

(** Source for [ring_finite_synthesis_linear]: finite
    linear combinations depend linearly on their coefficients,
    supporting 3.4.7, p. 325. *)
Lemma ring_finite_synthesis_linear (A:nzRingType) (V:lmodType A) n (e:'I_n->V):
  linear (@ring_finite_synthesis A V n e).
Proof.
move=>a c d;rewrite /ring_finite_synthesis scaler_sumr -big_split.
apply:eq_bigr=>i _;by rewrite !ffunE scalerDl scalerA.
Qed.
HB.instance Definition _ (A:nzRingType) (V:lmodType A) n (e:'I_n->V):=
  GRing.isLinear.Build A {ffun 'I_n->A^o} V *:%R
    (@ring_finite_synthesis A V n e) (@ring_finite_synthesis_linear A V n e).

(** Source for [ring_finite_synthesis_generator]: each
    original generator lies in the image of the finite
    coordinate map, supporting 3.4.7, p. 325. *)
Lemma ring_finite_synthesis_generator (A:nzRingType) (V:lmodType A) n
    (e:'I_n->V) j:
  ring_finite_synthesis e [ffun i=>if i==j then (1:A) else 0] = e j.
Proof.
rewrite /ring_finite_synthesis (bigD1 j) //= ffunE eqxx scale1r.
under eq_bigr do rewrite ffunE.
have hZero:(\sum_(i<n|i!=j) (if i==j then (1:A) else 0)*:e i) = 0.
  apply:big1=>i hij;by rewrite (negbTE hij) scale0r.
by rewrite hZero addr0.
Qed.

(** Source for [ring_submodule_finite_sum]: submodules
    contain finite linear combinations of their elements,
    supporting the finite power span in 3.4.7, p. 325. *)
Lemma ring_submodule_finite_sum (A:nzRingType) (V:lmodType A) (M:set V)
    (hM:is_ring_submodule M) n (e:'I_n->V) (c:{ffun 'I_n->A^o}):
  (forall i,M (e i)) ->M (ring_finite_synthesis e c).
Proof.
move=>hE;rewrite /ring_finite_synthesis.
apply:(big_ind M).
- exact:ring_submodule_zero hM.
- move=>x y hx hy;exact:(@ring_submodule_add A V M hM x y hx hy).
- move=>i _;exact:(@ring_submodule_scale A V M hM (c i) (e i) (hE i)).
Qed.
