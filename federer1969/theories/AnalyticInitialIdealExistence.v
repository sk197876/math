(** Federer (1969), 3.4.11, p. 338:
    the leading polynomial germs generate an actual
    ideal. Reuse the existing least-ideal existence theorem;
    no representation by analytic combinations is exposed. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets reals.
From Federer Require Import RealNormUP AnalyticGermRing CommutativeIdealUP CommutativeIdealSealed
  AnalyticInitialPolynomialGermUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [analytic_initial_ideal_exists]: existence
    of the ideal generated by the original leading
    homogeneous polynomials in 3.4.11, p. 338.
    Its independent least-ideal laws precede this witness. *)
Theorem analytic_initial_ideal_exists (R:realType) (X:lmodType R)
    (NX:X->R) (hNX:is_real_norm NX)
    (I:set (@analytic_germ_ring R X NX hNX 0)):
  exists J,is_analytic_initial_ideal I J.
Proof.
exists (@GeneratedCommutativeIdeal.value
  [the comNzRingType of (@analytic_germ_ring R X NX hNX 0)]
  (analytic_initial_polynomial_generators I)).
exact:GeneratedCommutativeIdeal.laws.
Qed.
