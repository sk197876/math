(** Federer (1969), 3.4.7, p. 325: the transverse
    module generated by the first k powers consists of
    actual polynomial values with no coefficients of degree
    k or higher. The image and its closure are supporting
    witnesses, rather than additional analytic hypotheses. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
From Federer Require Import RingScalarRestriction RingSubmoduleUP CommutativePolynomialUP
  CommutativePolynomialBasicLaws PolynomialCoefficientDivision CommutativePolynomialEvaluationUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.
Section BoundedImage.
Variables A B C:comNzRingType.
Variable embed:{rmorphism A->B}.
Variable variable:B.
Variable coefficient:B->nat->A.
Hypothesis hP:is_commutative_polynomial_ring embed variable coefficient.
Variable phi:{rmorphism A->C}.
Variable t:C.
Variable J:{rmorphism B->C}.
Hypothesis hJ:is_commutative_polynomial_evaluation embed variable phi t J.
Variable k:nat.
Local Notation V:=[the lmodType A of (ring_restricted_space phi C^o)].

(** Source for [bounded_polynomial_image_submodule]: actual
    polynomial values of degree below k form a transverse
    submodule, supporting the remainder argument of 3.4.7,
    p. 325. No remainder membership is assumed. *)
Theorem bounded_polynomial_image_submodule:
  is_ring_submodule (fun x:V=>exists P:B,
    (forall i,(k<=i)%N ->coefficient P i = 0) /\x = J P).
Proof.
constructor.
- exists 0;split;first by move=>i _;exact:(@polynomial_coefficient_zero A B embed variable coefficient hP i).
  by rewrite rmorph0.
- move=>x y [P [hPBound ->]] [Q [hQBound ->]].
  exists (P+Q);split.
  + move=>i hi;by rewrite (@polynomial_coefficient_add A B embed variable coefficient hP)
      hPBound // hQBound // addr0.
  + by rewrite rmorphD.
- move=>x [P [hBound ->]];exists (-P);split.
  + move=>i hi;by rewrite (@polynomial_coefficient_opp A B embed variable coefficient hP)
      hBound // oppr0.
  + by rewrite rmorphN.
- move=>a x [P [hBound ->]];exists (embed a*P);split.
  + move=>i hi;by rewrite (@polynomial_coefficient_scalar_multiply A B embed variable coefficient hP)
      hBound // mulr0.
  + change (phi a*J P = J (embed a*P)).
    by rewrite rmorphM (@polynomial_evaluation_constants A B C embed variable phi t J hJ).
Qed.

(** Source for [bounded_polynomial_image_contains_power]: each
    original power below k lies in the actual bounded
    polynomial image, supporting 3.4.7, p. 325. *)
Lemma bounded_polynomial_image_contains_power i:
  (i<k)%N ->exists P:B,
    (forall j,(k<=j)%N ->coefficient P j = 0) /\t^+i = J P.
Proof.
move=>hi;exists (variable^+i);split.
- move=>j hj;rewrite (@polynomial_power_coefficient A B embed variable coefficient hP).
  have hNe:(j==i) = false.
    apply/negP=>/eqP h;move:hi;by rewrite -h (leq_gtF hj).
  by rewrite hNe.
- by rewrite rmorphXn (@polynomial_evaluation_variable A B C embed variable phi t J hJ).
Qed.
End BoundedImage.
