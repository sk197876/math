(** Federer (1969), 3.4.8(11), p. 334:
    Phi=chi times Delta lies in the
    larger ideal and outside the original prime
    ideal. Its generated enlargement lies between
    the two original ideals. The existing sealed
    least-ideal interface supplies the enlargement. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
From Federer Require Import CommutativeIdealUP CommutativeIdealSealed.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [prime_ideal_product_cut]:
    the original enlarged K generated by
    I_g and Phi in 3.4.8(11), p. 334.
    Every containment and the nontrivial enlargement
    follow from the original ideal and prime laws. *)
Theorem prime_ideal_product_cut (A:comNzRingType) (I J:set A) chi delta:
  is_prime_commutative_ideal I ->is_commutative_ideal J ->I `<=` J ->
  J chi ->~I chi ->~I delta ->
  exists K:set A,is_generated_commutative_ideal (I `|` [set phi|phi = chi*delta]) K /\
    I `<=` K /\ K `<=` J /\ K (chi*delta) /\ ~I (chi*delta).
Proof.
move=>hPrime hJ hIJ hChi hNotChi hNotDelta.
pose K:=@GeneratedCommutativeIdeal.value A (I `|` [set phi|phi = chi*delta]).
have hK:=@GeneratedCommutativeIdeal.laws A (I `|` [set phi|phi = chi*delta]).
have hPhi:J (chi*delta).
  rewrite mulrC;exact:(commutative_ideal_mul hJ delta hChi).
exists K;split;first exact:hK.
split.
- move=>phi hI;apply:(generated_commutative_ideal_contains hK);by left.
- split.
  + apply:(generated_commutative_ideal_minimal hK hJ)=>phi [hI|->].
    * exact:hIJ phi hI.
    * exact:hPhi.
  + split.
    * apply:(generated_commutative_ideal_contains hK);by right.
    * move=>hProduct;have [hIChi|hIDelta]:=hPrime.2.2 chi delta hProduct.
      -- exact:hNotChi hIChi.
      -- exact:hNotDelta hIDelta.
Qed.
