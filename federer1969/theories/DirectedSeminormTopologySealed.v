(** Federer (1969), 4.1.1, p. 344: an opaque topology determined
    by the derivative-seminorm neighbourhood laws. Its construction
    proves existence and remains outside the downstream interface. *)
From mathcomp Require Import all_boot all_algebra boolp classical_sets reals.
From Federer Require Import DirectedSeminormFamilyUP DirectedSeminormTopologyExistence.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.

Module Type DirectedSeminormTopologySignature.
(** Source for [opens]: the abstract topology generated by the
    directed seminorm family, supporting Federer 4.1.1, p. 344. *)
Parameter opens : forall (R : realType) (E : lmodType R) (I : Type)
  (p : I -> E -> R), is_directed_seminorm_family p -> set (set E).
(** Source for [laws]: the proved independent neighbourhood laws
    for the topology of Federer 4.1.1, p. 344. *)
Parameter laws : forall (R : realType) (E : lmodType R) (I : Type)
  (p : I -> E -> R) (hp : is_directed_seminorm_family p),
  is_seminorm_family_topology p (@opens R E I p hp).
End DirectedSeminormTopologySignature.

Module DirectedSeminormTopology : DirectedSeminormTopologySignature.
(** Source for [opens]: private choice of the proved topology
    witness supporting Federer 4.1.1, p. 344. *)
Definition opens (R : realType) (E : lmodType R) (I : Type)
    (p : I -> E -> R) (hp : is_directed_seminorm_family p) : set (set E) :=
  projT1 (cid (directed_seminorm_topology_exists hp)).
(** Source for [laws]: the opaque witness satisfies exactly the
    independent seminorm topology laws, Federer 4.1.1, p. 344. *)
Lemma laws (R : realType) (E : lmodType R) (I : Type)
    (p : I -> E -> R) (hp : is_directed_seminorm_family p) :
  is_seminorm_family_topology p (@opens R E I p hp).
Proof. exact: (projT2 (cid (directed_seminorm_topology_exists hp))). Qed.
End DirectedSeminormTopology.
