(** Federer (1969), 3.4.7, p. 325: existence
    and uniqueness of the submodule specified by its generators.
    The intersection construction proves existence only. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
From Federer Require Import RingSubmoduleUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [generated_ring_submodule_exists]: the
    module generated by the original powers of xi in
    3.4.7, p. 325. This supporting existence proof
    intersects the submodules containing the given family. *)
Theorem generated_ring_submodule_exists (A:nzRingType) (V:lmodType A) (F:set V):
  exists M:set V,is_generated_ring_submodule F M.
Proof.
pose M:set V:=fun x=>forall N:set V,is_ring_submodule N ->F `<=` N ->N x.
exists M;constructor.
- constructor.
  + move=>N hN hFN;exact:ring_submodule_zero hN.
  + move=>x y hx hy N hN hFN.
    exact:(@ring_submodule_add A V N hN x y (hx N hN hFN) (hy N hN hFN)).
  + move=>x hx N hN hFN;exact:(@ring_submodule_opp A V N hN x (hx N hN hFN)).
  + move=>a x hx N hN hFN.
    exact:(@ring_submodule_scale A V N hN a x (hx N hN hFN)).
- move=>x hx N hN hFN;exact:hFN x hx.
- move=>N hN hFN x hx;exact:hx N hN hFN.
Qed.

(** Source for [generated_ring_submodule_unique]: the
    original generator laws determine the module uniquely,
    supporting 3.4.7, p. 325. *)
Lemma generated_ring_submodule_unique (A:nzRingType) (V:lmodType A) (F M N:set V):
  is_generated_ring_submodule F M ->is_generated_ring_submodule F N ->M = N.
Proof.
move=>hM hN;apply/seteqP;split.
- exact:(generated_ring_submodule_minimal hM (generated_ring_submodule_laws hN)
    (generated_ring_submodule_contains hN)).
- exact:(generated_ring_submodule_minimal hN (generated_ring_submodule_laws hM)
    (generated_ring_submodule_contains hM)).
Qed.
