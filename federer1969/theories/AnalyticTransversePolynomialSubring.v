(** Federer (1969), 3.4.7, p. 325: the
    original subring P is a simple transcendental
    extension of the transverse analytic germ ring.
    A faithful polynomial model supplies its abstract carrier;
    its image is exactly the original generated subring. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets reals.
From Federer Require Import Hom RealNormUP AnalyticGermRepresentatives AnalyticGermUP AnalyticGermRing
  WeierstrassTransverseUP WeierstrassTransversePullback AnalyticTransversePolynomialInjection
  CommutativePolynomialUP CommutativePolynomialSealed CommutativePolynomialEvaluationUP
  CommutativePolynomialEvaluationSealed CommutativeSubringUP PolynomialEvaluationImage
  CommutativeFactorizationUP GaussPolynomialFactorization.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Section Subring.
Variable R:realType.
Variables X K:lmodType R.
Variable NX:X->R.
Variable NK:K->R.
Hypothesis hNX:is_real_norm NX.
Hypothesis hNK:is_real_norm NK.
Variable v:X.
Variable xi:Hom X R^o.
Variable inclusion:Hom K X.
Variable projection:Hom X K.
Hypothesis hSplit:is_weierstrass_transverse_space NX NK v xi inclusion projection.
Variable fXi:@analytic_representative_type R X NX hNX 0.
Local Notation G:=[the comNzRingType of (@analytic_germ_ring R X NX hNX 0)].
Local Notation A:=[the comNzRingType of (@analytic_germ_ring R K NK hNK (projection 0))].
Local Notation E:=(@weierstrass_transverse_ring_pullback R X K NX NK hNX hNK
  v xi inclusion projection hSplit).
Local Notation Gamma:=(analytic_germ fXi:G).

(** Source for [analytic_transverse_polynomial_subring_exists]:
    the actual subring generated by xi and the
    original transverse pullback has a faithful polynomial
    model, proving the simple transcendental extension
    assertion in 3.4.7, p. 325. *)
Theorem analytic_transverse_polynomial_subring_exists:
  (forall x,analytic_representative_value fXi x = xi x) ->
  exists (B:comNzRingType) (embed:{rmorphism A->B}) (variable:B) (coefficient:B->nat->A)
    (J:{rmorphism B->G}),
    is_commutative_polynomial_ring embed variable coefficient /\
    is_commutative_polynomial_evaluation embed variable E Gamma J /\injective J /\
    is_generated_commutative_subring (fun x=>x = Gamma \/exists a:A,x = E a)
      (fun x=>exists P:B,x = J P).
Proof.
move=>hXi.
pose B:=@CommutativePolynomial.space A.
pose embed:=@CommutativePolynomial.embed A.
pose variable:=@CommutativePolynomial.variable A.
pose coefficient:=@CommutativePolynomial.coefficient A.
have hP:=@CommutativePolynomial.laws A.
pose J:=@CommutativePolynomialEvaluation.map A B G embed variable coefficient hP E Gamma.
have hJ:=@CommutativePolynomialEvaluation.laws A B G embed variable coefficient hP E Gamma.
exists B,embed,variable,coefficient,J;split;first exact:hP.
split;first exact:hJ.
split.
- exact:(@analytic_transverse_polynomial_evaluation_injective R X K NX NK hNX hNK
    v xi inclusion projection hSplit fXi B embed variable coefficient hP J hJ hXi).
- exact:(@polynomial_evaluation_image_generated A B G embed variable coefficient hP E Gamma J hJ).
Qed.

(** Source for [analytic_transverse_polynomial_subring_factorization]:
    the actual polynomial model of P has unique
    prime factorization whenever the original transverse
    coefficient ring does, the dimension-induction step
    used in 3.4.7, p. 325. *)
Theorem analytic_transverse_polynomial_subring_factorization (B:comNzRingType)
    (embed:{rmorphism A->B}) (variable:B) (coefficient:B->nat->A):
  is_commutative_polynomial_ring embed variable coefficient ->
  is_unique_factorization_commutative_domain A ->is_unique_factorization_commutative_domain B.
Proof. move=>hP;exact:(@gauss_polynomial_prime_factorization A B embed variable coefficient hP). Qed.
End Subring.
