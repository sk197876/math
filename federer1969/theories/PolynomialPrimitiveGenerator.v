(** Supporting algebra for Federer (1969), 3.4.8(8),
    p. 330: exact correspondence between the
    original generated-ring statement and polynomial
    surjectivity. Nonzero original scalar multiples
    preserve the generated ring. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
From Federer Require Import CommutativeSubringUP CommutativePolynomialUP
  CommutativePolynomialEvaluationUP PolynomialEvaluationImage.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [polynomial_surjection_primitive_generator]:
    L is the ring generated by M and
    the original element exactly when its
    original polynomial evaluation maps onto L,
    the statement in 3.4.8(8), p. 330. *)
Theorem polynomial_surjection_primitive_generator (K B L:comNzRingType)
  (embed:{rmorphism K->B}) (variable:B) (coefficient:B->nat->K)
  (hP:is_commutative_polynomial_ring embed variable coefficient)
  (phi:{rmorphism K->L}) (z:L) (E:{rmorphism B->L}):
  is_commutative_polynomial_evaluation embed variable phi z E ->
  ((forall y:L,exists P:B,E P = y) <->
    is_generated_commutative_subring (fun y:L=>y = z \/exists a:K,y = phi a) setT).
Proof.
move=>hE.
have hImage:=@polynomial_evaluation_image_generated K B L embed variable coefficient hP phi z E hE.
split.
- move=>hOnto.
  have hSets:(fun y:L=>exists P:B,y = E P) = setT.
    apply:funext=>y;apply:propext;split=>_;last by have [P hP0]:=hOnto y;exists P;exact:esym hP0.
    exact:I.
  by rewrite -hSets.
- move=>hGenerated.
  have hAll:=generated_commutative_subring_minimal hGenerated
    (generated_commutative_subring_laws hImage) (generated_commutative_subring_contains hImage).
  move=>y;have [P hP0]:=hAll y I;exists P;exact:esym hP0.
Qed.

(** Source for [primitive_generator_nonzero_scaling]: multiplying
    an original primitive element by a
    nonzero original coefficient preserves ring
    generation, supporting the cone of failing
    directions in 3.4.8(8), p. 330. *)
Theorem primitive_generator_nonzero_scaling (K L:fieldType) (phi:{rmorphism K->L}) (z:L) (t:K):
  t<>0 ->is_generated_commutative_subring (fun y:L=>y = z \/exists a:K,y = phi a) setT ->
  is_generated_commutative_subring (fun y:L=>y = phi t*z \/exists a:K,y = phi a) setT.
Proof.
move=>hT hGenerated;constructor.
- constructor;by [].
- by move=>y _.
- move=>J hJ hNewGenerators;apply:(generated_commutative_subring_minimal hGenerated hJ).
  move=>y [->|[a ->]];last by apply:hNewGenerators;right;exists a.
  have hTNonzero:t!=0 by apply/eqP;exact:hT.
  have hScaled:J (phi t*z) by apply:hNewGenerators;by left.
  have hInverse:J (phi (t^-1)) by apply:hNewGenerators;right;by exists (t^-1).
  have hProduct:=@commutative_subring_multiply L J hJ (phi (t^-1)) (phi t*z) hInverse hScaled.
  by rewrite mulrA -rmorphM (mulVf hTNonzero) rmorph1 mul1r in hProduct.
Qed.
