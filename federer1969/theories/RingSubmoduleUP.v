(** Federer (1969), 3.4.7, p. 325: the submodule
    M intersect I is finitely generated over the transverse
    Noetherian ring. These algebraic laws precede the finite-module
    proof; neither finite generation nor a geometric conclusion
    is included in the submodule definition. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [is_ring_submodule]: the transverse module
    in 3.4.7, p. 325, is closed under addition,
    negatives and multiplication by scalars and contains zero.
    This supporting specification applies to any ring module. *)
Record is_ring_submodule (A:nzRingType) (V:lmodType A) (M:set V):Prop:={
  (** Source for [ring_submodule_zero]: the zero law for
      the module used in 3.4.7, p. 325. *)
  ring_submodule_zero:M 0;
  (** Source for [ring_submodule_add]: additive closure in
      the module used in 3.4.7, p. 325. *)
  ring_submodule_add:forall x y,M x ->M y ->M (x+y);
  (** Source for [ring_submodule_opp]: additive inverses in
      the module used in 3.4.7, p. 325. *)
  ring_submodule_opp:forall x,M x ->M (-x);
  (** Source for [ring_submodule_scale]: scalar closure in
      the module used in 3.4.7, p. 325. *)
  ring_submodule_scale:forall a x,M x ->M (a*:x)
}.

(** Source for [is_generated_ring_submodule]: the submodule
    generated by the powers of xi in 3.4.7,
    p. 325, specified by its least-submodule property.
    A finite-sum representation is not part of the definition. *)
Record is_generated_ring_submodule (A:nzRingType) (V:lmodType A)
    (F M:set V):Prop:={
  (** Source for [generated_ring_submodule_laws]: the
      generated module is a submodule, 3.4.7, p. 325. *)
  generated_ring_submodule_laws:is_ring_submodule M;
  (** Source for [generated_ring_submodule_contains]: the
      original generators belong to it, 3.4.7, p. 325. *)
  generated_ring_submodule_contains:F `<=` M;
  (** Source for [generated_ring_submodule_minimal]: the
      least-submodule property used in 3.4.7, p. 325. *)
  generated_ring_submodule_minimal:forall N:set V,
    is_ring_submodule N ->F `<=` N ->M `<=` N
}.

(** Source for [is_finitely_generated_ring_submodule]:
    finite generation of M intersect I in 3.4.7,
    p. 325. The generator list may be empty or have repetitions. *)
Definition is_finitely_generated_ring_submodule (A:nzRingType) (V:lmodType A)
    (M:set V):Prop:=
  exists F:seq V,is_generated_ring_submodule [set x|x \in F] M.
