(** Federer (1969), 3.4.7, p. 325: two-generator
    ideal combinations supporting the Bezout step in the
    field polynomial argument. The existing least-ideal laws
    precede this local finite-sum existence proof. *)
From mathcomp Require Import all_boot all_order ssralg boolp classical_sets ring.
From Federer Require Import CommutativeIdealUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [commutative_two_generator_combinations]: every
    member of the ideal generated by two original
    elements is their actual linear combination, supporting
    the Gauss argument in 3.4.7, p. 325. *)
Theorem commutative_two_generator_combinations (A:comNzRingType) (P Q:A) (I:set A):
  is_generated_commutative_ideal (fun x=>x = P \/x = Q) I ->
  forall x,I x ->exists a b:A,x = a*P+b*Q.
Proof.
move=>hI.
pose J:set A:=fun x=>exists a b:A,x = a*P+b*Q.
have hJ:is_commutative_ideal J.
  constructor.
  - exists 0,0;ring.
  - move=>x y [a [b hx]] [c [d hy]];exists (a+c),(b+d);rewrite hx hy;ring.
  - move=>x [a [b hx]];exists (-a),(-b);rewrite hx;ring.
  - move=>c x [a [b hx]];exists (c*a),(c*b);rewrite hx;ring.
have hGenerators:(fun x=>x = P \/x = Q) `<=` J.
  move=>x [->|->].
  - exists 1,0;ring.
  - exists 0,1;ring.
exact:(@generated_commutative_ideal_minimal A (fun x=>x = P \/x = Q) I hI J hJ hGenerators).
Qed.
