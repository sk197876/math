(** Supporting algebra for Federer (1969), 3.4.8(8),
    pp. 329–330: the field generated by an
    original algebraic element has the same original
    polynomial image. Reuse the sealed subfield and
    the existing lift of a ring homomorphism.
    Source: Bourbaki, Algebra II (1990), Chapter V,
    section 2, no. 3, p. V.11, and
    section 3, no. 1, Theorem 1(c), p. V.16. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
From Federer Require Import CommutativePolynomialUP CommutativePolynomialEvaluationUP
  CommutativeSubringRealisationUP CommutativeSubringLiftExistence
  CommutativeSubfieldRealisationSealed AlgebraicPolynomialSubfield.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.

(** Source for [algebraic_simple_field_witness]: the
    actual simple subfield and its original
    coefficient inclusion, the cited Theorem 1(c),
    p. V.16, supporting 3.4.8(8), pp. 329–330.
    Its inclusion image is exactly the original
    polynomial image; every selected map remains local. *)
Theorem algebraic_simple_field_witness (K:fieldType) (B:comNzRingType) (L:fieldType)
  (embed:{rmorphism K->B}) (variable:B) (coefficient:B->nat->K)
  (hP:is_commutative_polynomial_ring embed variable coefficient)
  (phi:{rmorphism K->L}) (x:L) (E:{rmorphism B->L}):
  is_commutative_polynomial_evaluation embed variable phi x E ->
  (exists H:B,H<>0 /\E H = 0) ->
  exists (F:fieldType) (include:{rmorphism F->L}) (scalar:{rmorphism K->F}) (z:F),
    is_commutative_subring_realisation (fun y:L=>exists P:B,y = E P) include /\
    (forall a:K,include (scalar a) = phi a) /\include z = x.
Proof.
move=>hE hAlgebraic.
pose S:set L:=fun y=>exists P:B,y = E P.
have hS:=@algebraic_polynomial_image_subfield K B L embed variable coefficient hP phi x E hE hAlgebraic.
pose F:=@CommutativeSubfieldRealisation.space L S hS.
pose include:=@CommutativeSubfieldRealisation.inclusion L S hS.
have hF:=@CommutativeSubfieldRealisation.laws L S hS.
have hScalars a:S (phi a).
  exists (embed a);exact:esym (polynomial_evaluation_constants hE a).
have [scalar hScalar]:=@commutative_subring_ring_lift_exists K L F S include hF phi hScalars.
have hX:S x by exists variable;exact:esym (polynomial_evaluation_variable hE).
have [z hZ]:=(commutative_subring_inclusion_image hF x).1 hX.
exists F,include,scalar,z;by split;last split.
Qed.
