(** Federer (1969), 2.7.16, example (3), printed p. 137: "Letting X be the
    vectorsubspace of Hom(V, V) generated by G, we shall prove first that
    every Haar measure gamma of the additive group of X is chi covariant,
    where chi(g) = |det(g|W)|^{-m} |det g|^{m-n} whenever g in G", by means
    of the isomorphism X ~ Hom(W, W) x Hom(Z, V) and (2): "left
    multiplication by g in G maps phi x psi onto |det(g|W)|^{-m} phi x |det
    g|^{m-n} psi = chi(g) . (phi x psi)". Here X is subspace_preserving_maps
    of StabiliserHomSpace.v with the inner product of Hom(V, V) (1.7.9, p.
    35, HomSpaceTopology.v) restricted to X (InnerProductRestriction.v); its
    topology is the relative topology of Hom(V, V)
    (preserving_val_continuous, preserving_continuous_into), and its
    additive group is a locally compact Hausdorff group
    (preserving_additive_lch_group). The group G acts on X by A(g, f) = g o
    f (stabiliser_action). The covariance identity of 2.7.1, p. 122, mu(u o
    A_g) = chi(g) mu(u) for u in K(X), holds for every Haar integral mu of X
    (preserving_haar_integral_covariant), and every Haar measure of X is a
    chi covariant measure (preserving_haar_measure_covariant). The factor is
    |det(f |-> g o f)|^{-1} (FiniteHaarLinear.v), and det(f |-> g o f) =
    det(g|W)^m (det g)^{n-m} (StabiliserHomSpace.v); the product phi x psi
    of Haar measures of Hom(W, W) and Hom(Z, V) is not formed. The same
    argument gives, for right composition f |-> f o g, the factor |det
    g|^{-n} |det(g|W)|^{n-m} (preserving_haar_integral_right), since det(f
    |-> f o g) = (det g)^m det(wedge^1 g|W')^{n-m} and det g = det(g|W)
    det(wedge^1 g|W'). *)
