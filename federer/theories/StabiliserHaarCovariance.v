(** Source for [preserving_val_norm]: the inclusion of X into Hom(V, V)
    preserves the norm of the inner product of 1.7.9, p. 35, restricted
    to X; supporting "X the vectorsubspace of Hom(V, V)", Federer
    2.7.16, p. 137, as a topological subspace. Supporting lemma. *)
Lemma preserving_val_norm (f : X) : `|(subspace_val f : H)| = `|f|.
Proof.
rewrite !inner_norm_topologyE; symmetry; apply: inner_norm_value.
  exact: inner_norm_nonnegative.
by rewrite inner_norm_sqr.
Qed.

(** Source for [preserving_val_continuous]: the inclusion of X into
    Hom(V, V) is continuous, Federer 2.7.16, p. 137. Supporting
    lemma. *)
Lemma preserving_val_continuous : continuous (fun f : X => (subspace_val f : H)).
Proof.
move=> f; apply/(@cvgrPdist_lt _ _ _ (nbhs f) (nbhs_filter f))=> eps heps.
apply: (filterS _ (nbhsx_ballx f _ heps))=> g; rewrite -ball_normE /= => hg.
have -> : (subspace_val f : H) - subspace_val g = subspace_val (f - g) by rewrite linearB.
by rewrite preserving_val_norm.
Qed.

(** Source for [preserving_continuous_into]: a map into X is
    continuous if its composition with the inclusion into Hom(V, V) is,
    since the inclusion preserves the norm; X carries the relative
    topology, Federer 2.7.16, p. 137. Supporting lemma. *)
Lemma preserving_continuous_into (T : topologicalType) (F : T -> X) :
  continuous (fun t => (subspace_val (F t) : H)) -> continuous F.
Proof.
move=> hF t; apply/(@cvgrPdist_lt _ _ _ (nbhs t) (nbhs_filter t))=> eps heps.
have := (proj1 (@cvgrPdist_lt _ H _ (nbhs t) (nbhs_filter t) (fun s => (subspace_val (F s) : H))
  (subspace_val (F t)))) (hF t) eps heps.
apply: filterS=> s hs.
by rewrite -preserving_val_norm linearB.
Qed.

(** Source for [preserving_basis_exists]: X has a finite base,
    Federer 2.7.16, p. 137 (the base of Hom(W, W) x Hom(Z, V) under xi).
    Supporting lemma. *)
Lemma preserving_basis_exists :
  exists N (c : 'I_N -> subspace_space Xs), is_basis c.
Proof.
have [w hw] := hW.
have [e [heb hew]] := adapted_basis_exists hb hw.
by eexists; eexists; exact: (preserving_left_basisP hw heb hew).
Qed.

(** Source for [preserving_additive_lch_group]: the additive group of
    X is a locally compact Hausdorff topological group, "Haar measure
    gamma of the additive group of X", Federer 2.7.16, p. 137, in the
    sense of 2.7.1, p. 121. Direct formalisation. *)
Theorem preserving_additive_lch_group :
  is_locally_compact_hausdorff_group (fun f g : X => f + g) (fun f => - f) 0.
Proof.
have [N [c hc]] := preserving_basis_exists.
split.
- split; first by split; [exact: addrA|exact: add0r|exact: addNr].
  + exact: add_continuous.
  + exact: oppr_continuous.
- exact: inner_space_hausdorff.
- exact: (inner_space_locally_compact hc).
Qed.

(** Source for [stabiliser_preserving]: g[W] c W for g in G, so that
    g o f belongs to X for f in X, Federer 2.7.16, p. 137. Supporting
    lemma. *)
Lemma stabiliser_preserving (g : S) : preserving_pred W (stabiliser_val g).
Proof. exact: (subspace_stabiliser_invariant (set_valP g)). Qed.

(** Source for [stabiliser_action]: the action A(g, f) = g o f of G on
    X, "left multiplication by g in G", Federer 2.7.16, p. 137, curried
    as in 2.7.1, p. 121. Definition. *)
Definition stabiliser_action (g : S) (f : X) : X := preserving_left_composition (stabiliser_preserving g) f.

(** Source for [stabiliser_actionE]: A(g, f) = g o f, Federer 2.7.16,
    p. 137. Supporting lemma. *)
Lemma stabiliser_actionE (g : S) (f : X) :
  subspace_val (stabiliser_action g f) = hom_comp (stabiliser_val g) (subspace_val f).
Proof. by []. Qed.

(** Source for [stabiliser_character]: "chi(g) = |det(g|W)|^{-m}
    |det g|^{m-n} whenever g in G", Federer 2.7.16, p. 137, with
    m - n = -(n - m). Definition. *)
Definition stabiliser_character (g : S) : R :=
  `|stabiliser_restriction_det hW g| ^- m * `|stabiliser_det g| ^- (n - m).

(** Source for [stabiliser_restriction_det_basis]: det(g|W) computed
    with the restriction preserving_restriction of
    StabiliserHomSpace.v, Federer 2.7.16, p. 137. Supporting lemma. *)
Lemma stabiliser_restriction_det_basis (w : 'I_m -> subspace_space W) (hw : is_basis w) (g : S) :
  det h2 hw (preserving_restriction (stabiliser_preserving g)) = stabiliser_restriction_det hW g.
Proof.
rewrite (stabiliser_restriction_detE hW hw); apply: det_ext=> x.
by apply: subspace_val_injective.
Qed.

(** Source for [stabiliser_det_basis]: det g may be computed with any
    base of V, Federer 1.3.4, p. 16; supporting 2.7.16, p. 137.
    Supporting lemma. *)
Lemma stabiliser_det_basis k (e : 'I_k -> V) (he : is_basis e) (g : S) :
  det h2 he (hom_as_linear (stabiliser_val g)) = stabiliser_det g.
Proof. exact: det_basis_any. Qed.

(** Source for [preserving_left_det]: "left multiplication by g in G
    maps phi x psi onto |det(g|W)|^{-m} phi x |det g|^{m-n} psi",
    Federer 2.7.16, p. 137: the determinant of f |-> g o f on X is
    det(g|W)^m (det g)^{n-m}. Supporting theorem. *)
Theorem preserving_left_det (w : 'I_m -> subspace_space W) (hw : is_basis w)
    (e : 'I_(m + (n - m)) -> V) (heb : is_basis e) (hew : forall i, e (lshift (n - m) i) = subspace_val (w i))
    (g : S) :
  det h2 (preserving_left_basisP hw heb hew) (preserving_left_composition (stabiliser_preserving g)) =
    stabiliser_restriction_det hW g ^+ m * stabiliser_det g ^+ (n - m).
Proof.
by rewrite preserving_left_composition_det stabiliser_restriction_det_basis stabiliser_det_basis.
Qed.

(** Source for [stabiliser_restriction_annihilator_det]: "det(wedge^1 g)
    = det(g) = det(g|W) det(wedge^1 g|W')", Federer 2.7.16, p. 138, for
    g in G. Direct formalisation. *)
Theorem stabiliser_restriction_annihilator_det (w : 'I_m -> subspace_space W) (hw : is_basis w)
    (e : 'I_(m + (n - m)) -> V) (heb : is_basis e) (hew : forall i, e (lshift (n - m) i) = subspace_val (w i))
    (g : S) :
  stabiliser_det g =
    stabiliser_restriction_det hW g * det h2 (annihilator_basisP hw heb hew)
      (annihilator_restriction (stabiliser_preserving g)).
Proof.
by rewrite -(stabiliser_det_basis heb) (restriction_annihilator_det hw heb hew (stabiliser_preserving g))
  stabiliser_restriction_det_basis.
Qed.

(** Source for [preserving_right_det]: |det(f |-> f o g)| =
    |det g|^n |det(g|W)|^{m-n} on X, the computation behind "the
    commutative diagram in (2)", Federer 2.7.16, p. 138: the
    determinant is (det g)^m det(wedge^1 g|W')^{n-m}, and
    det(wedge^1 g|W') = det g / det(g|W). Supporting theorem. *)
Theorem preserving_right_det (w : 'I_m -> subspace_space W) (hw : is_basis w)
    (e : 'I_(m + (n - m)) -> V) (heb : is_basis e) (hew : forall i, e (lshift (n - m) i) = subspace_val (w i))
    (g : S) :
  `|det h2 (preserving_right_basisP hw heb hew) (preserving_right_composition (stabiliser_preserving g))| *
    `|stabiliser_restriction_det hW g| ^+ (n - m) = `|stabiliser_det g| ^+ n.
Proof.
have hmn := subspace_dimension_le hb hw.
rewrite (preserving_right_composition_det hw heb hew) (dual_map_det h2 heb) stabiliser_det_basis.
rewrite normrM !normrX -mulrA -exprMn -normrM.
rewrite (mulrC (det _ _ _) (stabiliser_restriction_det hW g)).
rewrite -(stabiliser_restriction_annihilator_det hw heb hew) -exprD.
by rewrite subnKC.
Qed.

(** Source for [preserving_haar_integral_covariant]: "every Haar
    measure gamma of the additive group of X is chi covariant",
    Federer 2.7.16, p. 137, for the integral: every left Haar integral
    mu of the additive group of X satisfies mu(u o A_g) = chi(g) mu(u)
    whenever u in K(X), g in G, the identity of 2.7.1, p. 122. Direct
    formalisation. *)
Theorem preserving_haar_integral_covariant (mu : (X -> R) -> R) :
  is_left_haar_integral (fun f g : X => f + g) mu ->
  is_covariant_integral stabiliser_action stabiliser_character mu.
Proof.
move=> hmu; split; first exact: (covariant_integral_daniell (nonzero_invariant_integral_invariant hmu)).
move=> u g hu.
have [w hw] := hW.
have [e [heb hew]] := adapted_basis_exists hb hw.
have hdet := preserving_left_det hw heb hew g.
have hT : det h2 (preserving_left_basisP hw heb hew)
    (preserving_left_composition (stabiliser_preserving g)) != 0.
  rewrite hdet mulf_neq0 // expf_neq0 //; first exact: stabiliser_restriction_det_nonzero.
  exact: stabiliser_det_nonzero.
have := @finite_haar_integral_linear R (subspace_space Xs) _ hX _ _
  (preserving_left_basisP hw heb hew) mu _ hmu hT u hu.
rewrite hdet normrM !normrX invfM => ->.
by [].
Qed.

(** Source for [preserving_haar_measure_covariant]: "every Haar measure
    gamma of the additive group of X is chi covariant", Federer 2.7.16,
    p. 137, in the sense of 2.7.1, p. 122: gamma is the K(X) regular
    measure associated with a monotone Daniell integral satisfying the
    covariance identity. Direct formalisation. *)
Theorem preserving_haar_measure_covariant (gamma : set X -> \bar R) :
  is_left_haar_measure (fun f g : X => f + g) gamma ->
  is_covariant_measure stabiliser_action stabiliser_character gamma.
Proof.
move=> [mu [hmu hm hi hr]]; exists mu; split=> //.
- exact: nonzero_invariant_integral_monotone hmu.
- exact: covariant_integral_law (preserving_haar_integral_covariant hmu).
Qed.

(** Source for [preserving_haar_integral_right]: for g in G and a left
    Haar integral mu of the additive group of X,
    mu(u o (f |-> f o g)) = |det g|^{-n} |det(g|W)|^{n-m} mu(u) whenever
    u in K(X); for g^{-1} in place of g this is the right covariance of
    gamma over G used in "the commutative diagram in (2) now implies",
    Federer 2.7.16, p. 138. Supporting theorem. *)
Theorem preserving_haar_integral_right (mu : (X -> R) -> R) (g : S) :
  is_left_haar_integral (fun f g : X => f + g) mu ->
  forall u, KX u -> mu (u \o (fun f : X => preserving_right_composition (stabiliser_preserving g) f : X)) =
    `|stabiliser_det g| ^- n * `|stabiliser_restriction_det hW g| ^+ (n - m) * mu u.
Proof.
move=> hmu u hu.
have [w hw] := hW.
have [e [heb hew]] := adapted_basis_exists hb hw.
have hdet := preserving_right_det hw heb hew g.
have hd0 : `|stabiliser_restriction_det hW g| ^+ (n - m) != 0.
  by rewrite expf_neq0 // normr_eq0 stabiliser_restriction_det_nonzero.
have hn0 : `|stabiliser_det g| ^+ n != 0 by rewrite expf_neq0 // normr_eq0 stabiliser_det_nonzero.
have hT : det h2 (preserving_right_basisP hw heb hew)
    (preserving_right_composition (stabiliser_preserving g)) != 0.
  by rewrite -normr_eq0; apply: contra hn0=> /eqP h0; rewrite -hdet h0 mul0r.
have := @finite_haar_integral_linear R (subspace_space Xs) _ hX _ _
  (preserving_right_basisP hw heb hew) mu _ hmu hT u hu.
move=> ->; congr (_ * _).
have hD : `|det h2 (preserving_right_basisP hw heb hew)
    (preserving_right_composition (stabiliser_preserving g))| =
    `|stabiliser_det g| ^+ n / `|stabiliser_restriction_det hW g| ^+ (n - m).
  by rewrite -hdet mulfK.
by rewrite hD invf_div mulrC.
Qed.

End PreservingSpace.

