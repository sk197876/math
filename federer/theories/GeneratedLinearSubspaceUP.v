(** Federer (1969), 4.1.22, p. 379: the real polyhedral
    space is generated by the integral polyhedral subgroup.
    State the algebraic span by its independent least-subspace
    property. No topological closure is imposed. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets.
From Federer Require Import ModuleQuotient.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope classical_set_scope.

(** Source for [is_generated_linear_subspace]: the least
    vector subspace containing the original generators,
    Federer 4.1.22, p. 379. Its construction is separate. *)
Record is_generated_linear_subspace (K:fieldType) (V:lmodType K)
    (D:set V) (S:subspace V):Prop:={
  (** Source: the generating subgroup is contained in its
      real span, Federer 4.1.22, p. 379. *)
  generated_linear_subspace_contains:D `<=` S;
  (** Source: generation means the least such vector space,
      Federer 4.1.22, p. 379. *)
  generated_linear_subspace_least:forall W:subspace V,
    D `<=` W->S `<=` W
}.

(** Source for [generated_linear_subspace_unique_membership]:
    the original least-subspace laws determine membership
    uniquely, supporting Federer 4.1.22, p. 379. *)
Theorem generated_linear_subspace_unique_membership (K:fieldType)
    (V:lmodType K) (D:set V) (S W:subspace V):
  is_generated_linear_subspace D S->is_generated_linear_subspace D W->
  forall x,S x<->W x.
Proof.
move=>hS hW x;split.
- exact:(@generated_linear_subspace_least K V D S hS W
    (@generated_linear_subspace_contains K V D W hW) x).
- exact:(@generated_linear_subspace_least K V D W hW S
    (@generated_linear_subspace_contains K V D S hS) x).
Qed.
