(** Federer (1969), 2.2.8, p. 64: a nested sequence of nonempty closed sets
    whose diameters tend to zero has exactly one common point in a complete
    metric space. The proof forms the filter generated by the closed sets
    and applies the abstract Cauchy completeness law. No compactness or
    external intersection theorem is used. *)
From mathcomp Require Import all_boot all_order all_algebra
  classical_sets reals topology.
From Federer Require Import CompleteMetricUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import Order.TTheory GRing.Theory Num.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [closed_shrinking_metric_intersection]: supporting existence
    theorem for Federer 2.2.8, p. 64, applied to E(n1,...,nk). The
    decreasing diameter condition is expressed by arbitrary positive errors. *)
Theorem closed_shrinking_metric_intersection (R : realType) (T : metricType R)
    (hT : is_complete_metric_space T) (C : nat -> set T) :
  (forall n, C n !=set0) -> (forall n, closed (C n)) ->
  (forall n m, (n <= m)%N -> C m `<=` C n) ->
  (forall e : R, 0 < e -> exists n, forall x y,
    C n x -> C n y -> mdist x y < e) ->
  exists x, forall n, C n x.
Proof.
move=> hne hclosed hnested hsmall.
pose F := filter_from (@setT nat) C.
have FF : Filter F.
  apply: filter_from_filter; first by exists 0%N.
  move=> n m _ _; exists (maxn n m)=> // x hx; split.
  - exact: hnested n (maxn n m) (leq_maxl _ _) x hx.
  - exact: hnested m (maxn n m) (leq_maxr _ _) x hx.
have PF : ProperFilter F.
  apply: filter_from_proper FF _=> n _; exact: hne.
have hca : cauchy F.
  apply: cauchy_exP=> e he.
  have [n hn] := hsmall e he; have [a ha] := hne n.
  exists a; exists n=> // y hy.
  rewrite ballEmdist /=; exact: hn a y ha hy.
have [x hx] := hT F PF hca; exists x=> n.
have hFC : F (C n) by exists n.
exact: (@closed_cvg T T F PF idfun (C n) (hclosed n) hFC x (cvg_trans cvg_id hx)).
Qed.

(** Source for [shrinking_metric_intersection_unique]: Federer
    2.2.8, p. 64, uniqueness of the branch point: distinct
    points cannot belong to sets with arbitrarily small diameter.
    This part needs neither closedness nor completeness. *)
Lemma shrinking_metric_intersection_unique (R : realType) (T : metricType R)
    (C : nat -> set T) :
  (forall e : R, 0 < e -> exists n, forall x y,
    C n x -> C n y -> mdist x y < e) ->
  forall x y, (forall n, C n x) -> (forall n, C n y) -> x = y.
Proof.
move=> hsmall x y hx hy; case: (eqVneq x y)=> [//|hxy]; exfalso.
have hd : 0 < mdist x y by rewrite mdist_gt0.
have [n hn] := hsmall _ hd.
by have := hn x y (hx n) (hy n); rewrite ltxx.
Qed.
