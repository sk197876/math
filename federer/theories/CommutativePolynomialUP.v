(** Federer (1969), 3.4.7, p. 325: the
    subring generated by the transverse ring and xi
    is a simple transcendental extension. These finite
    coefficient laws specify that polynomial algebra before
    its existence or the Gauss lemma is proved. *)
From mathcomp Require Import all_boot all_order ssralg boolp.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.

(** Source for [is_commutative_polynomial_ring]: independent
    coefficient laws for the polynomial extension in
    3.4.7, p. 325. Finite support and
    coefficient uniqueness, together with the constant,
    variable and arithmetic laws, determine the usual
    finite polynomial expressions. No domain or
    factorization conclusion is included. *)
Record is_commutative_polynomial_ring (A B:comNzRingType)
    (embed:{rmorphism A->B}) (variable:B) (coefficient:B->nat->A):Prop:={
  (** Source for [polynomial_coefficient_zero]: the zero
      coefficients of the polynomial extension in 3.4.7, p. 325. *)
  polynomial_coefficient_zero:forall i,coefficient 0 i = 0;
  (** Source for [polynomial_coefficient_add]: coefficient
      addition in the extension of 3.4.7, p. 325. *)
  polynomial_coefficient_add:forall P Q i,
    coefficient (P+Q) i = coefficient P i+coefficient Q i;
  (** Source for [polynomial_coefficient_opp]: coefficient
      negation in the extension of 3.4.7, p. 325. *)
  polynomial_coefficient_opp:forall P i,coefficient (-P) i = -coefficient P i;
  (** Source for [polynomial_coefficient_multiply]: finite
      coefficient convolution in the extension used by
      the Gauss lemma, 3.4.7, p. 325. *)
  polynomial_coefficient_multiply:forall P Q k,coefficient (P*Q) k =
    \sum_(i<k.+1) coefficient P i*coefficient Q (k-i)%N;
  (** Source for [polynomial_coefficient_constant]: original
      scalars are constant polynomials, 3.4.7, p. 325. *)
  polynomial_coefficient_constant:forall a i,
    coefficient (embed a) i = if i==0%N then a else 0;
  (** Source for [polynomial_coefficient_variable]: the
      original polynomial variable has coefficient one
      in degree one and zero elsewhere, 3.4.7, p. 325. *)
  polynomial_coefficient_variable:forall i,
    coefficient variable i = if i==1%N then 1 else 0;
  (** Source for [polynomial_coefficients_finite]: every
      polynomial has finitely many nonzero coefficients,
      supporting the extension in 3.4.7, p. 325. *)
  polynomial_coefficients_finite:forall P,exists N,
    forall i,(N<=i)%N ->coefficient P i = 0;
  (** Source for [polynomial_coefficients_unique]: coefficient
      equality detects polynomial equality, the transcendence
      property needed in 3.4.7, p. 325. *)
  polynomial_coefficients_unique:forall P Q,
    (forall i,coefficient P i = coefficient Q i) ->P = Q
}.
