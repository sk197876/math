(** Source for [primitive_field_original_bounded_representative]:
    the original coefficient module generated by
    1,zeta,...,zeta^(k-1) represents every original
    fraction after clearing an original coefficient
    denominator, 3.4.8(10), pp. 330–331.
    Neither bounded representatives nor inverses are
    assumptions. The existing monic division theorem
    reduces the already proved original representatives. *)
Theorem primitive_field_original_bounded_representative (A B:comNzRingType) (L M:fieldType)
  (embed:{rmorphism A->B}) (variable:B) (coefficient:B->nat->A)
  (hP:is_commutative_polynomial_ring embed variable coefficient)
  (hDomain:is_commutative_integral_domain A)
  (chi:{rmorphism A->L}) (eta:{rmorphism A->M}) (phi:{rmorphism M->L})
  (z:L) (E:{rmorphism B->L}) (W:B) k:
  is_coefficient_fraction_field chi eta phi ->
  is_commutative_polynomial_evaluation embed variable chi z E ->
  is_generated_commutative_subring (fun y:L=>y = z \/exists a:M,y = phi a) setT ->
  is_monic_polynomial coefficient W k ->E W = 0 ->forall x:L,
  exists (delta:A) (P:B),eta delta<>0 /\
    (forall i,(k<=i)%N ->coefficient P i = 0) /\chi delta*x = E P.
Proof.
move=>hCoefficient hE hGenerated hW hZero x.
pose identity:{rmorphism L->L}:=GRing.RMorphism.clone L L idfun _.
have hIdentity:=field_identity_fraction_laws L.
have hOriginal:is_coefficient_fraction_field (GRing.RMorphism.clone A L (identity \o chi) _) eta phi.
  constructor.
  - move=>a;change (phi (eta a) = chi a).
    exact:coefficient_fraction_scalar_triangle hCoefficient a.
  - move=>y;have [a [b [hB hValue]]]:=coefficient_fraction_representation hCoefficient y.
    exists a,b;split;[exact:hB|exact:hValue].
have [delta [P [hDelta hPValue]]]:=@primitive_field_original_coefficient_representative
  A B L L M embed variable coefficient hP chi identity eta phi z E hIdentity hOriginal hE hGenerated x.
have hBounded:=@monic_polynomial_evaluation_bounded_image A B L embed variable coefficient
  hP hDomain E W k hW.1 hW.2 hZero (chi delta*x).
have [Q [hSupport hValue]]:=hBounded.1 (ex_intro _ P hPValue).
exists delta,Q;split;first exact:hDelta.
by split.
Qed.
