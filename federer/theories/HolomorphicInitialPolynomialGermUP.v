(** Federer (1969), 3.4.12, p. 339, extending 3.4.11, p. 338:
    independent membership laws for the original germs
    generated by first nonzero homogeneous Taylor polynomials.
    The specification states the actual normalized polynomial
    and its representative, without tangent or dimension claims. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets reals.
From Federer Require Import ScalarRestriction ComplexScalarSealed RealNormUP HolomorphicGermUP HolomorphicGermRepresentatives
  HolomorphicGermRing HolomorphicInitialPolynomialUP CommutativeIdealUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [is_initial_polynomial_germ]: the germ
    of the first nonzero normalized homogeneous polynomial
    of an original holomorphic germ in 3.4.11,
    p. 338. Representatives agree with that actual
    polynomial everywhere; no zero-set assertion is included. *)
Definition is_initial_polynomial_germ (R:realType) (X:lmodType (ComplexScalars.C R))
    (NX:X->R) (hNX:@is_real_norm R (restricted_space (ComplexScalars.embed R) X) NX)
    (alpha beta:holomorphic_germ_space hNX (0:X)):Prop:=
  exists k (P:X->ComplexScalars.C R) (f:@holomorphic_representative_type R X NX hNX 0),
    is_initial_holomorphic_germ_polynomial alpha k P /\
    (forall x,holomorphic_representative_value f x= P x) /\holomorphic_germ f=beta.

(** Source for [holomorphic_initial_polynomial_generators]: the
    original family of all leading polynomial germs
    from the ideal in 3.4.11, p. 338.
    Every generator retains its original source germ. *)
Definition holomorphic_initial_polynomial_generators (R:realType) (X:lmodType (ComplexScalars.C R))
    (NX:X->R) (hNX:@is_real_norm R (restricted_space (ComplexScalars.embed R) X) NX)
    (I:set (@holomorphic_germ_ring R X NX hNX 0)):
    set (@holomorphic_germ_ring R X NX hNX 0):=
  [set beta|exists alpha,I alpha /\is_initial_polynomial_germ alpha beta].

(** Source for [is_holomorphic_initial_ideal]: the least
    ideal containing precisely these original leading germs,
    as used in 3.4.11, p. 338. Existence
    is supplied by the existing sealed generated-ideal
    interface; no depth comparison is a defining law. *)
Definition is_holomorphic_initial_ideal (R:realType) (X:lmodType (ComplexScalars.C R))
    (NX:X->R) (hNX:@is_real_norm R (restricted_space (ComplexScalars.embed R) X) NX)
    (I J:set (@holomorphic_germ_ring R X NX hNX 0)):Prop:=
  is_generated_commutative_ideal (holomorphic_initial_polynomial_generators I) J.
