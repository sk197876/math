(** Supporting algebra for Federer (1969), 3.4.8(5), p. 328:
    an original coefficient-linear functional sends powers of the
    scalar-generated ideal into the corresponding original scalar
    powers. Use least-ideal laws and multiplier loci. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
From Federer Require Import RingScalarRestriction CommutativeIdealUP
  CommutativeIdealPowersSealed CommutativeIdealPowersLaws
  CommutativeIdealProductSealed CommutativeIdealProductLaws LinearMultiplierIdeal.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [linear_functional_scalar_ideal_powers]: supporting
    original coefficient filtration for Federer 3.4.8(5), p. 328.
    If J is the ideal generated by phi(I), every multiple of a J^q
    element has functional value in I^q. Only original linearity
    is assumed; the functional is not a ring homomorphism. *)
Theorem linear_functional_scalar_ideal_powers (A C:comNzRingType) (phi:{rmorphism A->C})
    (L:{linear [the lmodType A of ring_restricted_space phi C^o]->A^o})
    (I:set A) (J:set C):
  is_generated_commutative_ideal (phi @` I) J ->
  forall q z,@CommutativeIdealPowers.value C J q z ->
    forall c:C,@CommutativeIdealPowers.value A I q (L (c*z)).
Proof.
move=>hGenerated.
pose P:=@CommutativeIdealPowers.value A I.
pose Q:=@CommutativeIdealPowers.value C J.
pose T q:=linear_multiplier_locus L (P q).
have hT q:is_commutative_ideal (T q).
  exact:(@linear_multiplier_locus_is_ideal A C phi L (P q)
    (@commutative_ideal_power_is_ideal A I q)).
have hContain q:Q q `<=` T q.
  elim:q=>[|q ih];first by move=>z _ c;rewrite /P commutative_ideal_power_zeroE.
  rewrite /Q commutative_ideal_power_successorE.
  apply:commutative_ideal_product_minimal;first exact:hT q.+1.
  move=>x y hX hY;rewrite [x*y]mulrC.
  apply:(@generated_commutative_ideal_minimal C (phi @` I) J hGenerated
    (fun x=>T q.+1 (y*x))
    (@commutative_ideal_multiplier_preimage C (T q.+1) y (hT q.+1)) _ x hX).
  move=>z [a hA <-] c.
  change (P q.+1 (L (c*(y*phi a)))).
  rewrite [y*phi a]mulrC mulrCA.
  have hScalar:L (phi a*(c*y)) = a*L (c*y).
    change (L (a*:(c*y:[the lmodType A of ring_restricted_space phi C^o])) = a*:L (c*y)).
    exact:linearZ.
  rewrite hScalar /P commutative_ideal_power_successorE.
  exact:(@commutative_ideal_product_contains A I (P q) a (L (c*y)) hA (ih y hY c)).
move=>q z hZ c;exact:hContain q z hZ c.
Qed.
