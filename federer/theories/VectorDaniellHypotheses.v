Section Conjugate.
Variable R : realType.
Variable E : lmodType R.
Variable N : E -> R.
Hypothesis hN : is_real_norm N.

(** Source for [is_separable_normed_space]: hypothesis (1) of Federer
    2.5.12, p. 102: the normed space E is separable, so some countable
    set is dense for the norm metric. *)
Definition is_separable_normed_space : Prop :=
  exists D : set (real_norm_metric_space hN), countable D /\ dense D.

(** Source for [dual_space]: the space E* of hypothesis (2) of Federer
    2.5.12, p. 102, of all nu continuous linear maps of E into R. *)
Definition dual_space : set (E -> R) :=
  [set alpha | scalar alpha /\
    continuous (alpha : real_norm_metric_space hN -> real_line_metric R)].

(** Source for [dual_norm]: the norm nu* dual to nu in hypothesis (2)
    of Federer 2.5.12, p. 102, nu*(alpha) = sup{<y, alpha> : nu(y) = 1}. *)
Definition dual_norm (alpha : E -> R) : R := sup [set alpha y | y in [set y | N y = 1]].

(** Source for [weak_factor]: the real line as the factor of the product
    topology on the real valued functions on E, Federer 2.5.12(2),
    p. 103. *)
Definition weak_factor (_ : E) : topologicalType := [the topologicalType of real_line_metric R].

(** Source for [weak_function_space]: the real valued functions on E
    with the topology of pointwise convergence, whose subbasic open sets
    are the sets {alpha : a < <z, alpha> < b} of hypothesis (2) of
    Federer 2.5.12, p. 103. *)
Definition weak_function_space := prod_topology weak_factor.

(** Source for [weak_dual_space]: E* with the weak topology of
    hypothesis (2) of Federer 2.5.12, p. 103, the subspace topology
    induced from the pointwise topology on all real functions on E. *)
Definition weak_dual_space := set_type (dual_space : set weak_function_space).
HB.instance Definition _ := Topological.copy weak_dual_space
  (set_type (dual_space : set weak_function_space)).

(** Source for [weak_dual_evaluation_continuous]: the evaluation at a
    point z of E is continuous on E* for the weak topology, so that the
    generating sets {alpha : a < <z, alpha> < b} of Federer 2.5.12,
    p. 103, are open. *)
Lemma weak_dual_evaluation_continuous (z : E) :
  continuous (fun alpha : weak_dual_space => (val alpha z : real_line_metric R)).
Proof.
have h1 : continuous (val : weak_dual_space -> weak_function_space).
  exact: initial_continuous.
have h2 : continuous (mathcomp_extra.proj z : prod_topology weak_factor -> weak_factor z).
  exact: proj_continuous.
move=> alpha; have h := continuous_comp (h1 alpha) (h2 (val alpha)).
exact: h.
Qed.

End Conjugate.

Section Data.
Variable R : realType.
Variable X : choiceType.
Variable E : lmodType R.
Variable N : E -> R.
Hypothesis hN : is_real_norm N.
Variable L : set (X -> R).
Variable Q : set (X -> E).
Variable T : (X -> E) -> R.

(** Source for [has_lattice_unit_series]: hypothesis (3) of Federer
    2.5.12, p. 103: L+ contains a countable set K with
    sum_{f in K} f(x) >= 1 whenever x in X. The set K is written as a
    sequence; for nonempty L this is equivalent, because a nonempty
    countable set is the range of a sequence, K is nonempty when X is
    nonempty, and the zero function serves when X is empty. *)
Definition has_lattice_unit_series : Prop :=
  exists K : nat -> X -> R, is_positive_lattice_series_cover L setT K.

(** Source for [is_vector_function_space]: the clause of hypothesis (4)
    of Federer 2.5.12, p. 103, that Q is a vector space of functions
    mapping X into E, with the pointwise operations. *)
Record is_vector_function_space : Prop := {
  (** Source for [vector_function_space_zero]: the zero map belongs to
      the vector space Q of Federer 2.5.12, p. 103. *)
  vector_function_space_zero : Q (fun _ => 0);
  (** Source for [vector_function_space_add]: closure of Q under
      pointwise addition, Federer 2.5.12, p. 103. *)
  vector_function_space_add : forall w v, Q w -> Q v -> Q (fun x => w x + v x);
  (** Source for [vector_function_space_scale]: closure of Q under real
      multiples, Federer 2.5.12, p. 103. *)
  vector_function_space_scale : forall c w, Q w -> Q (fun x => c *: w x)
}.

(** Source for [is_vector_lattice_module]: the three displayed clauses
    of hypothesis (4) of Federer 2.5.12, p. 103, relating L, Q, E and E*. *)
Record is_vector_lattice_module : Prop := {
  (** Source for [vector_lattice_module_product]: f in L and y in E
      imply f . y in Q, Federer 2.5.12(4), p. 103. *)
  vector_lattice_module_product : forall f y, L f -> Q (fun x => f x *: y);
  (** Source for [vector_lattice_module_pairing]: w in Q and alpha in
      E* imply alpha o w in L, Federer 2.5.12(4), p. 103. *)
  vector_lattice_module_pairing : forall w alpha, Q w -> dual_space hN alpha ->
    L (fun x => alpha (w x));
  (** Source for [vector_lattice_module_norm]: w in Q implies
      nu o w in L, Federer 2.5.12(4), p. 103. *)
  vector_lattice_module_norm : forall w, Q w -> L (fun x => N (w x));
  (** Source for [vector_lattice_module_split]: for w in Q and f in L+
      with nu o w >= f there is xi in Q with nu o xi = f and
      (nu o w) . xi = f . w, Federer 2.5.12(4), p. 103. *)
  vector_lattice_module_split : forall w f, Q w -> positive_function_lattice L f ->
    function_le f (fun x => N (w x)) ->
    exists xi, Q xi /\ (forall x, N (xi x) = f x) /\ (forall x, N (w x) *: xi x = f x *: w x)
}.

(** Source for [variation_integral]: the function lambda of hypothesis
    (5) of Federer 2.5.12, p. 103,
    lambda(f) = sup T(Q cap {w : nu o w <= f}), called the variation
    integral corresponding to T on p. 103. *)
Definition variation_integral (f : X -> R) : R :=
  sup [set T w | w in Q `&` [set w | function_le (fun x => N (w x)) f]].

(** Source for [is_vector_variation_functional]: hypothesis (5) of
    Federer 2.5.12, p. 103: T is linear on Q, lambda is finite on L+, and
    nu o xi_n decreasing to zero implies T(xi_n) -> 0. Finiteness of the
    supremum is stated as the existence of an upper bound. *)
Record is_vector_variation_functional : Prop := {
  (** Source for [vector_variation_additive]: additivity of the linear
      map T on Q, Federer 2.5.12(5), p. 103. *)
  vector_variation_additive : forall w v, Q w -> Q v -> T (fun x => w x + v x) = T w + T v;
  (** Source for [vector_variation_homogeneous]: homogeneity of the
      linear map T on Q, Federer 2.5.12(5), p. 103. *)
  vector_variation_homogeneous : forall c w, Q w -> T (fun x => c *: w x) = c * T w;
  (** Source for [vector_variation_bounded]: the condition
      lambda(f) < oo for f in L+, Federer 2.5.12(5), p. 103. *)
  vector_variation_bounded : forall f, positive_function_lattice L f ->
    exists b : R, forall w, Q w -> function_le (fun x => N (w x)) f -> T w <= b;
  (** Source for [vector_variation_continuous]: the condition that
      nu o xi_n decreasing to 0 as n -> oo implies T(xi_n) -> 0,
      Federer 2.5.12(5), p. 103. *)
  vector_variation_continuous : forall xi : nat -> X -> E, (forall n, Q (xi n)) ->
    (forall x, extended_decreases_to (fun n => (N (xi n x))%:E) (0 : R)%:E) ->
    extended_order_limit (fun n => (T (xi n))%:E) (0 : R)%:E
}.

End Data.
