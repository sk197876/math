(** Federer (1969), 2.5.12, pp. 102–103: the hypotheses (1)–(5) of the
    vector valued representation theorem. The vector space E is an lmodType
    over the reals normed by nu, a real norm in the sense of 1.10.5 as used
    in 2.3.8; separability means that some countable subset is dense for the
    norm metric. The conjugate space E* consists of the nu continuous linear
    maps of E into R, normed by nu*(alpha) = sup{<y, alpha> : nu(y) = 1},
    and carries the weak topology generated by the sets {alpha : a < <z,
    alpha> < b}; it is modelled as the subspace of the product topology on
    the real valued functions on E, which is generated by exactly these
    sets. The countable subset K of L+ of hypothesis (3) is written as a
    sequence, so that the series cover predicate of 2.5.3 expresses the
    condition sum_{f in K} f(x) >= 1. The vector space Q of maps of X into E
    is closed under the pointwise operations; the three clauses of (4), the
    linearity of T and the two conditions of (5) are recorded as predicates,
    and the variation integral lambda(f) = sup T(Q cap {w : nu o w <= f}) is
    a real supremum. *)
