(** Federer (1969), 4.1.1, pp. 344–345; Menne (2016),
    Definition 2.13 and Remarks 2.14–2.17, p. 996: distinguish
    the locally convex inductive limit from the literal final
    topology. These definitions specify the former by all finite
    seminorms continuous on every fixed-support step. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets reals.
From Federer Require Import Hom RealNormUP DirectedSeminormFamilyUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.

Section InductiveSeminormSpecification.
Variable R:realType.
Variable E:lmodType R.
Variable J:Type.
Variable W:J->lmodType R.
Variable I:J->Type.
Variable p:forall j,I j->W j->R.
Variable inc:forall j,Hom (W j) E.

(** Source for [is_step_compatible_seminorm]: a seminorm is
    continuous on each fixed-support step exactly when it has
    a finite stepwise bound, supporting the locally convex
    topology in Menne (2016), Definition 2.13, p. 996, and the
    distribution bound of Federer 4.1.1, p. 345. *)
Definition is_step_compatible_seminorm (q:E->R) :=
  is_real_seminorm q /\ forall j,exists i C,0<=C /\
    forall w,q (@inc j w)<=C * @p j i w.

(** Source for [compatible_seminorm_index]: the independent
    family of all compatible seminorms, supporting Menne (2016),
    Definition 2.13 and Remark 2.17, p. 996. Membership is a
    proved property of a supplied seminorm, not an existence axiom. *)
Record compatible_seminorm_index := CompatibleSeminorm {
  (** Source for [compatible_seminorm_value]: the supplied
      finite seminorm, supporting the locally convex comparison
      with Federer 4.1.1, p. 344. *)
  compatible_seminorm_value:E->R;
  (** Source for [compatible_seminorm_laws]: its actual stepwise
      continuity bounds, supporting Menne (2016), p. 996. *)
  compatible_seminorm_laws:is_step_compatible_seminorm compatible_seminorm_value
}.

(** Source for [is_inductive_limit_open_topology]: the topology
    generated by all compatible seminorms specifies the locally
    convex inductive limit of Menne (2016), Definition 2.13,
    p. 996. It is kept distinct from Federer's topological final
    topology, 4.1.1, p. 344. *)
Definition is_inductive_limit_open_topology (O:set (set E)) :=
  is_seminorm_family_topology
    (fun q:compatible_seminorm_index=>compatible_seminorm_value q) O.
End InductiveSeminormSpecification.
