(** Federer (1969), 2.7.16, example (3), printed pp. 137–138: "Letting X be
    the vectorsubspace of Hom(V, V) generated by G ... we choose a subspace
    Z of V so that V = W (+) Z and construct a left G action preserving
    isomorphism xi: X ~ Hom(W, W) x Hom(Z, V), xi(f) = (f|W, f|Z) whenever f
    in X", "left multiplication by g in G maps phi x psi onto
    |det(g|W)|^{-m} phi x |det g|^{m-n} psi", and "det(wedge^1 g) = det(g) =
    det(g|W) det(wedge^1 g|W')", where W' = wedge^1 V cap {u : u|W = 0}.
    Here X is the subspace subspace_preserving_maps of the maps f with f[W]
    c W; it is the subspace generated by G
    (subspace_preserving_maps_generated): G is contained in it, and every
    rank one member x |-> e_k*(x) e_i of X is the difference of the members
    1_V + (x |-> e_k*(x) e_i) and 1_V of G. With a base e of V adapted to W
    (e_1, ..., e_m a base of W, the remaining q = n - m members spanning Z),
    X has the base of the rank one maps x |-> e_k*(x) e_i with i <= m or k >
    m (preserving_family_basis). Grouped as the m copies {x |-> e_k*(x) w :
    w in W}, k <= m, of W and the q copies {x |-> e_k*(x) v : v in V}, k >
    m, of V, this is the base of Hom(W, W) x Hom(Z, V) under xi, and f |-> g
    o f acts on the copies as g|W and as g, so that its determinant is
    det(g|W)^m (det g)^q (preserving_left_composition_det). Grouped as the m
    copies {x |-> omega(x) e_i : omega in wedge^1 V}, i <= m, of wedge^1 V =
    Hom(V, R) and the q copies {x |-> omega(x) e_i : omega in W'}, i > m, of
    W', the same base shows that f |-> f o g acts as wedge^1 g and as
    wedge^1 g|W', with determinant (det wedge^1 g)^m det(wedge^1 g|W')^q
    (preserving_right_composition_det); this replaces the transport of gamma
    by wedge^1 to the space X' of Federer's proof. Finally, wedge^1 g maps
    W' into W' and induces wedge^1(g|W) on wedge^1 V / W' ~ wedge^1 W,
    whence det g = det(g|W) det(wedge^1 g|W') (restriction_annihilator_det,
