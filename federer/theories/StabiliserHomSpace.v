(** Source for [rank_one_coordinateE]: the coefficients of the rank one
    maps x |-> e_k'*(x) e_i', Federer 1.4.5, p. 21; supporting 2.7.16,
    p. 137. Supporting lemma. *)
Lemma rank_one_coordinateE k i k' i' :
  rank_one_coordinate k i (hom_with_coefficient (e i') (es k')) = ((k == k') && (i' == i))%:R.
Proof.
rewrite /= /rank_one_coordinate_fun hom_with_coefficientE dual_basisE (linZ (hom_linear _)) dual_basisE.
by case: (k == k'); case: (i' == i)=> /=; rewrite ?scaler0 ?scale0r //; exact: mulr1.
Qed.

(** Source for [rank_one_expansion]: f = sum_{k,i} e_i*(f(e_k))
    (x |-> e_k*(x) e_i), Federer 1.4.5, p. 21; supporting the base of X
    in 2.7.16, p. 137. Supporting lemma. *)
Lemma rank_one_expansion (f : Hom V V) :
  f = \sum_k \sum_i rank_one_coordinate k i f *: hom_with_coefficient (e i) (es k).
Proof.
rewrite [LHS](finite_Hom_coefficients heb f); apply: eq_bigr=> k _.
rewrite [in LHS](basis_vector_expansion heb (f (e k))).
transitivity (coefficient_map V (es k) (\sum_i (es i (f (e k)) : R) *: e i)); first by [].
rewrite linear_sum; apply: eq_bigr=> i _.
by rewrite linearZ.
Qed.

(** Source for [preserving_family_basis]: a family of members of X
    which are distinct rank one maps x |-> e_k*(x) e_i and include every
    pair (k, i) for which some member of X has a nonzero coefficient is
    a base of X, Federer 1.1.2, p. 10, and 1.4.5, p. 21; supporting the
    isomorphism X ~ Hom(W, W) x Hom(Z, V) of 2.7.16, p. 137.
    Supporting lemma. *)
Lemma preserving_family_basis (I : finType) (F : I -> X) (tau : I -> 'I_(m + q) * 'I_(m + q)) :
  (forall x, subspace_val (F x) = hom_with_coefficient (e (tau x).2) (es (tau x).1)) ->
  injective tau ->
  (forall k i, (exists x, tau x = (k, i)) \/ (forall f : X, rank_one_coordinate k i (subspace_val f) = 0)) ->
  is_basis (fun j : 'I_#|{: I}| => F (enum_val j)).
Proof.
move=> hF ht hcov; apply: enumerated_family_basis.
  move=> c hc y.
  pose phi := linear_comp (rank_one_coordinate (tau y).1 (tau y).2) (subspace_inclusion Xs).
  have h0 := congr1 phi hc.
  rewrite linear0 linear_sum in h0.
  have h1 : \sum_x c x *: phi (F x) = \sum_x c x * (x == y)%:R.
    apply: eq_bigr=> x _; rewrite /phi /= hF.
    have -> := rank_one_coordinateE (tau y).1 (tau y).2 (tau x).1 (tau x).2.
    congr (_ * _%:R); rewrite -(inj_eq ht).
    by case: (tau x)=> a1 a2; case: (tau y)=> b1 b2 /=; rewrite xpair_eqE eq_sym.
  have h2 : \sum_x c x *: phi (F x) = 0.
    by rewrite -[RHS]h0; apply: eq_bigr=> x _; rewrite linearZ.
  have h3 : \sum_x c x * (x == y)%:R = c y.
    rewrite (bigD1 y) //= eqxx mulr1 big1 ?addr0 // => x hx.
    by rewrite (negbTE hx) mulr0.
  by rewrite -h3 -h1 h2.
move=> f.
pose P (v : Hom V V) := exists a : I -> R, v = \sum_x a x *: subspace_val (F x).
have hP0 : P 0 by exists (fun _ => 0); rewrite big1 // => x _; rewrite scale0r.
have hPD u v : P u -> P v -> P (u + v).
  move=> [a ->] [a' ->]; exists (fun x => a x + a' x).
  by rewrite -big_split; apply: eq_bigr=> x _; rewrite scalerDl.
have hP1 (x : I) (r : R) : P (r *: subspace_val (F x)).
  exists (fun y => if y == x then r else 0).
  rewrite (bigD1 x) //= eqxx big1 ?addr0 // => y hy.
  by rewrite (negbTE hy) scale0r.
have hPf : P (subspace_val f).
  rewrite (rank_one_expansion (subspace_val f)).
  apply: big_ind=> // k _; apply: big_ind=> // i _.
  case: (hcov k i)=> [[x hx]|hz]; last by rewrite hz scale0r.
  by have := hP1 x (rank_one_coordinate k i (subspace_val f)); rewrite hF hx.
have [a ha] := hPf; exists a; apply: subspace_val_injective.
rewrite ha linear_sum; apply: eq_bigr=> x _.
by rewrite linearZ.
Qed.

