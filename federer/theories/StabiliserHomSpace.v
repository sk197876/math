    p. 138. Definition of the function. *)
Definition subspace_dual_extension_fun (u : Hom (subspace_space W) R^o) : Hom V R^o :=
  \sum_i (u (w i) : R) *: es (lshift q i).

(** Source for [subspace_dual_extension_linear]: the extension is
