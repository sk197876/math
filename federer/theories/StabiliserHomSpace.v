(** Source for [preserving_pred]: f[W] c W, the defining condition of
    the members of the vectorspace X of Federer 2.7.16, p. 137.
    Definition. *)
Definition preserving_pred (f : Hom V V) : Prop := forall x, W x -> W (f x).

(** Source for [preserving_zero]: 0 belongs to X, Federer 2.7.16,
    p. 137. Supporting lemma. *)
Lemma preserving_zero : preserving_pred 0.
Proof. by move=> x _; rewrite hom_zeroE; exact: subspace_zero. Qed.

(** Source for [preserving_add]: X is closed under addition, Federer
    2.7.16, p. 137. Supporting lemma. *)
Lemma preserving_add f g : preserving_pred f -> preserving_pred g -> preserving_pred (f + g).
Proof. by move=> hf hg x hx; rewrite hom_addE; apply: subspace_add; [exact: hf|exact: hg]. Qed.

(** Source for [preserving_scale]: X is closed under multiplication by
    scalars, Federer 2.7.16, p. 137. Supporting lemma. *)
Lemma preserving_scale a f : preserving_pred f -> preserving_pred (a *: f).
Proof. by move=> hf x hx; rewrite hom_scaleE; apply: subspace_scale; exact: hf. Qed.

(** Source for [subspace_preserving_maps]: "X the vectorsubspace of
    Hom(V, V) generated by G", Federer 2.7.16, p. 137, given as the
