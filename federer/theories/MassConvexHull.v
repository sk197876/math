Section Hull.
Variable R : realType.
Hypothesis h2 : (1+1 : R) != 0.
Variable V : lmodType R.
Variable B : V -> V -> R.
Hypothesis hB : is_inner_product B.
Variable n : nat.
Variable e : 'I_n -> V.
Hypothesis he : is_basis e.
Variable m : nat.
Hypothesis hm : (0 < m)%N.
Local Notation E := (exterior_power V m).
Local Notation BE := (@exterior_inner_form R h2 V B hB m).
Local Notation hE := (@exterior_inner_productP R h2 V B hB m).
Local Notation M := (inner_metric_space hE).
Local Notation S := (@simple_unit_ball R h2 V B hB m).
Local Notation C := (@subconvex_combinations R E S).
Local Notation P := (@pairing_bilinear R V R^o m).
Variable kappa : A_m V R^o m -> R.
Hypothesis hk : forall phi, is_comass h2 hB phi (kappa phi).

(** Source for [simple_subconvex_compact]: Federer 1.8.1,
    p. 38, supporting compactness of the finite-combination set
    generated by S. It includes zero and degrees above the dimension. *)
Lemma simple_subconvex_compact : compact (C : set M).
Proof.
have hs := @simple_unit_ball_compact R h2 V B hB n e he m hm.
have hb := finite_ordinal_basis (@finite_e_lambda_basis R n V e he h2 m).
exact: (@subconvex_combinations_compact R E BE hE S hs _ _ hb).
Qed.

(** Source for [mass_unit_ball_iff_subconvex]: Federer 1.8.1,
    p. 38, equality of the mass unit ball with finite convex
    combinations of S. The separating covector is gamma(x-c), where
    c is nearest to an excluded point x in the compact convex set C. *)
Theorem mass_unit_ball_iff_subconvex x d : is_mass kappa x d ->
  (d <= 1 <-> C x).
Proof.
move=> hd; split; last first.
- move=> hx; exact (@subconvex_mass_bound R h2 V B hB m hm kappa hk x d hx hd).
move=> hd1; apply: contrapT => hnot.
have hn : C !=set0 by exists 0; exact: subconvex_combinations_zero.
have [c hc] := @compact_inner_nearest_exists R E BE hE x C hn simple_subconvex_compact.
have hconv : is_inner_convex C := @subconvex_combinations_convex R E S.
pose phi := inner_exterior_form h2 hB (x-c).
have hupper : kappa phi <= pairing c phi.
  apply: (@comass_least_upper_bound R h2 V B hB m phi (kappa phi) (hk phi)
    (pairing c phi)) => y hy.
  have hyC : C y := subconvex_combinations_include hy.
  have hv := @inner_nearest_convex_variational R E BE hE C hconv x c hc y hyC.
  rewrite (inner_symmetric hE) in hv.
  change (is_true (pairing (y-c) phi <= 0)) in hv.
  by rewrite (bilBl P) subr_le0 in hv.
have hr : x-c != 0.
  apply/eqP=> hz; apply: hnot.
  have hxc : x=c by apply/eqP; rewrite -subr_eq0 hz.
  rewrite hxc; exact: inner_nearest_member_law hc.
have hpos : 0 < BE (x-c) (x-c) by rewrite (inner_positive hE).
change (is_true (0 < pairing (x-c) phi)) in hpos.
rewrite (bilBl P) subr_gt0 in hpos.
have hb := @mass_comass_pairing_bound R h2 V B hB m hm kappa hk x d hd phi.
have hkc : 0 <= kappa phi := comass_nonnegative hm (hk phi).
have hmul := ler_wpM2r hkc hd1; rewrite mul1r in hmul.
have heval := le_trans (ler_norm (pairing x phi)) (le_trans hb hmul).
have hbad := lt_le_trans hpos (le_trans heval hupper).
by rewrite ltxx in hbad.
Qed.

(** Source for [mass_unit_ball_convex_hull]: Federer 1.8.1,
    p. 38, the hull assertion stated by its universal laws:
    the mass unit ball is exactly the least convex superset of S. *)
Theorem mass_unit_ball_convex_hull (mu : E -> R)
    (hmu : forall x, is_mass kappa x (mu x)) :
  is_convex_hull S [set x | mu x <= 1].
Proof.
have heq : [set x | mu x <= 1] = C.
  apply: funext => x; apply: propext; exact: mass_unit_ball_iff_subconvex (hmu x).
rewrite heq; apply: subconvex_hull_laws; exact: simple_unit_ball_zero.
Qed.
End Hull.
