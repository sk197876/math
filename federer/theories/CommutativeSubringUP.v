(** Federer (1969), 3.4.7, p. 325: the
    subring generated by the transverse coefficients and xi.
    Independent closure and least-subring laws precede its
    identification as a polynomial image. *)
From mathcomp Require Import all_boot all_order ssralg boolp classical_sets.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [is_commutative_subring]: a subring contains
    zero and one and is closed under the
    original ring operations, supporting the subring P
    in 3.4.7, p. 325. *)
Record is_commutative_subring (A:comNzRingType) (S:set A):Prop:={
  (** Source for [commutative_subring_zero]: zero belongs
      to P, supporting 3.4.7, p. 325. *)
  commutative_subring_zero:S 0;
  (** Source for [commutative_subring_one]: one belongs
      to P, supporting 3.4.7, p. 325. *)
  commutative_subring_one:S 1;
  (** Source for [commutative_subring_add]: P is closed
      under addition, supporting 3.4.7, p. 325. *)
  commutative_subring_add:forall x y,S x ->S y ->S (x+y);
  (** Source for [commutative_subring_opp]: P is closed
      under negation, supporting 3.4.7, p. 325. *)
  commutative_subring_opp:forall x,S x ->S (-x);
  (** Source for [commutative_subring_multiply]: P is closed
      under multiplication, supporting 3.4.7, p. 325. *)
  commutative_subring_multiply:forall x y,S x ->S y ->S (x*y)
}.

(** Source for [is_generated_commutative_subring]: the original
    generated subring is the least subring containing
    the original generators, as used in 3.4.7, p. 325. *)
Record is_generated_commutative_subring (A:comNzRingType) (F S:set A):Prop:={
  (** Source for [generated_commutative_subring_laws]: the
      generated set is a subring, supporting 3.4.7, p. 325. *)
  generated_commutative_subring_laws:is_commutative_subring S;
  (** Source for [generated_commutative_subring_contains]: it
      contains the original generators, supporting 3.4.7, p. 325. *)
  generated_commutative_subring_contains:F `<=` S;
  (** Source for [generated_commutative_subring_minimal]: every
      original subring containing the generators contains P,
      supporting 3.4.7, p. 325. *)
  generated_commutative_subring_minimal:forall J:set A,
    is_commutative_subring J ->F `<=` J ->S `<=` J
}.
