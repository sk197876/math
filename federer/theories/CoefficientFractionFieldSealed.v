(** Federer (1969), 3.4.8(8), p. 329:
    the coefficient field remains opaque behind
    its independently specified scalar and fraction
    laws. Choice selects proved existence witnesses. *)
From mathcomp Require Import all_boot all_order all_algebra boolp.
From Federer Require Import CoefficientFractionFieldUP CoefficientFractionFieldExistence.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Module Type CoefficientFractionFieldSignature.
(** Source for [space]: the original subfield
    generated by the coefficient image, 3.4.8(8), p. 329. *)
Parameter space:forall (A:comNzRingType) (L:fieldType),{rmorphism A->L}->fieldType.
(** Source for [scalar]: the original coefficient
    map into M, 3.4.8(8), p. 329. *)
Parameter scalar:forall (A:comNzRingType) (L:fieldType) (original:{rmorphism A->L}),
  {rmorphism A->@space A L original}.
(** Source for [inclusion]: the inclusion of
    M into the original L, 3.4.8(8), p. 329. *)
Parameter inclusion:forall (A:comNzRingType) (L:fieldType) (original:{rmorphism A->L}),
  {rmorphism @space A L original->L}.
(** Source for [laws]: the original scalar
    triangle and exact coefficient fraction representation,
    3.4.8(8), pp. 329–330. *)
Parameter laws:forall (A:comNzRingType) (L:fieldType) (original:{rmorphism A->L}),
  is_coefficient_fraction_field original (@scalar A L original) (@inclusion A L original).
End CoefficientFractionFieldSignature.
Module CoefficientFractionField:CoefficientFractionFieldSignature.
(** Source for [space]: a hidden field
    witness for 3.4.8(8), p. 329. *)
Definition space (A:comNzRingType) (L:fieldType) (original:{rmorphism A->L}):fieldType:=
  projT1 (cid (coefficient_fraction_field_exists original)).
(** Source for [scalar]: the corresponding hidden
    coefficient map, 3.4.8(8), p. 329. *)
Definition scalar (A:comNzRingType) (L:fieldType) (original:{rmorphism A->L}):
    {rmorphism A->@space A L original}:=
  projT1 (cid (projT2 (cid (coefficient_fraction_field_exists original)))).
(** Source for [inclusion]: the corresponding hidden
    inclusion, 3.4.8(8), p. 329. *)
Definition inclusion (A:comNzRingType) (L:fieldType) (original:{rmorphism A->L}):
    {rmorphism @space A L original->L}:=
  projT1 (cid (projT2 (cid (projT2 (cid (coefficient_fraction_field_exists original)))))).
(** Source for [laws]: the selected objects
    satisfy the independent original laws of
    3.4.8(8), pp. 329–330. *)
Lemma laws (A:comNzRingType) (L:fieldType) (original:{rmorphism A->L}):
  is_coefficient_fraction_field original (@scalar A L original) (@inclusion A L original).
Proof.
exact:(projT2 (cid (projT2 (cid (projT2 (cid (coefficient_fraction_field_exists original))))))).
Qed.
End CoefficientFractionField.
