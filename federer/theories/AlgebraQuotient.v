Definition quotient_one : quotient_algebra_space := pi (alg_one A).

(** Source for [quotient_mulE]: Federer (1969), 1.3.1, p. 13, opening
    quotient-algebra paragraph. In words: The exterior algebra is the
    quotient of the tensor algebra by the two-sided ideal generated by
    squares of vectors. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma quotient_mulE x y : quotient_mul (pi x) (pi y) = pi (alg_mul A x y).
Proof. apply: ideal_product_compatible; exact: quotient_projection_surjective. Qed.

(** Source for [quotient_mul_bilinear]: Federer (1969), 1.3.1, p. 13,
    opening quotient-algebra paragraph. In words: The exterior algebra is
    the quotient of the tensor algebra by the two-sided ideal generated by
    squares of vectors. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma quotient_mul_bilinear : bilinear quotient_mul.
Proof.
split=> [y a x x'|x a y y'].
  rewrite -[x]quotient_projection_surjective -[x']quotient_projection_surjective
    -[y]quotient_projection_surjective -linearP !quotient_mulE.
  by rewrite (bilDl (alg_bilinear A)) (bilZl (alg_bilinear A)) linearP.
rewrite -[x]quotient_projection_surjective -[y]quotient_projection_surjective
  -[y']quotient_projection_surjective -linearP !quotient_mulE.
by rewrite (bilDr (alg_bilinear A)) (bilZr (alg_bilinear A)) linearP.
Qed.

