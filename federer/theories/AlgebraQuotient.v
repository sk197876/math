Section QuotientGrading.
Variable G : grading A.
Hypothesis ideal_homogeneous : forall n x, I x -> I (grade G n x).

(** Source for [quotient_grade_projection]: Federer (1969), 1.3.1, p. 13,
    homogeneous ideal and component-quotient displays. In words: The
    square-generated ideal is homogeneous and begins in degree two, so the
    quotient inherits its grading and each component is the corresponding
    component quotient. Definition or construction used to formalise this
    passage. *)
Definition quotient_grade_projection n : {linear A -> quotient_algebra_space} :=
  linear_comp (GRing.Linear.clone _ _ _ _ pi _) (grade G n).

(** Source for [quotient_grade_killed]: Federer (1969), 1.3.1, p. 13,
    homogeneous ideal and component-quotient displays. In words: The
    square-generated ideal is homogeneous and begins in degree two, so the
    quotient inherits its grading and each component is the corresponding
    component quotient. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma quotient_grade_killed n x : I x -> quotient_grade_projection n x = 0.
Proof. move=> hx; apply/ideal_projection_zero; exact: ideal_homogeneous hx. Qed.

(** Source for [quotient_grade]: Federer (1969), 1.3.1, p. 13, homogeneous
    ideal and component-quotient displays. In words: The square-generated
    ideal is homogeneous and begins in degree two, so the quotient inherits
    its grading and each component is the corresponding component quotient.
    Definition or construction used to formalise this passage. *)
Definition quotient_grade n : {linear quotient_algebra_space -> quotient_algebra_space} :=
  GRing.Linear.clone _ _ _ _
    (quotient_lift (f := quotient_grade_projection n) (quotient_grade_killed n)) _.

(** Source for [quotient_gradeE]: Federer (1969), 1.3.1, p. 13, homogeneous
    ideal and component-quotient displays. In words: The square-generated
    ideal is homogeneous and begins in degree two, so the quotient inherits
    its grading and each component is the corresponding component quotient.
    Supporting lemma for this passage; not separately stated in the book. *)
Lemma quotient_gradeE n x : quotient_grade n (pi x) = pi (grade G n x).
Proof. exact: quotient_liftE. Qed.

(** Source for [quotient_grade_orthogonal]: Federer (1969), 1.3.1, p. 13,
    homogeneous ideal and component-quotient displays. In words: The
    square-generated ideal is homogeneous and begins in degree two, so the
    quotient inherits its grading and each component is the corresponding
    component quotient. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma quotient_grade_orthogonal m n x :
  quotient_grade m (quotient_grade n x) =
    if m == n then quotient_grade n x else 0.
Proof.
rewrite -[x]quotient_projection_surjective !quotient_gradeE grade_orthogonal.
by case: ifP => _; rewrite ?linear0.
Qed.

(** Source for [quotient_grade_finite]: Federer (1969), 1.3.1, p. 13,
    homogeneous ideal and component-quotient displays. In words: The
    square-generated ideal is homogeneous and begins in degree two, so the
    quotient inherits its grading and each component is the corresponding
    component quotient. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma quotient_grade_finite x : exists N, x = \sum_(i < N) quotient_grade i x.
Proof.
have [N hN] := grade_finite G (repr x); exists N.
rewrite -{1}[x]quotient_projection_surjective hN linear_sum /=.
apply: eq_bigr => i _.
by rewrite -quotient_gradeE quotient_projection_surjective.
Qed.

(** Source for [quotient_grading]: Federer (1969), 1.3.1, p. 13, opening
    quotient-algebra paragraph. In words: The exterior algebra is the
    quotient of the tensor algebra by the two-sided ideal generated by
    squares of vectors. Definition or construction used to formalise this
    passage. *)
Definition quotient_grading : grading quotient_algebra_space :=
  @Grading K _ quotient_grade quotient_grade_orthogonal quotient_grade_finite.

(** Source for [quotient_projection_graded]: Federer (1969), 1.3.1, p. 13,
    homogeneous ideal and component-quotient displays. In words: The
    square-generated ideal is homogeneous and begins in degree two, so the
    quotient inherits its grading and each component is the corresponding
    component quotient. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma quotient_projection_graded : preserves_grading G quotient_grading pi.
Proof.
move=> n x hx; change (quotient_grade n (pi x) = pi x).
rewrite quotient_gradeE.
by rewrite hx.
Qed.

(** Source for [quotient_homogeneous_representative]: Federer (1969), 1.3.1,
    p. 13, homogeneous ideal and component-quotient displays. In words: The
    square-generated ideal is homogeneous and begins in degree two, so the
    quotient inherits its grading and each component is the corresponding
    component quotient. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma quotient_homogeneous_representative n x :
  homogeneous quotient_grading n x ->
  exists y, homogeneous G n y /\ pi y = x.
Proof.
move=> hx; exists (grade G n (repr x)); split; first exact: homogeneous_grade.
by rewrite -quotient_gradeE quotient_projection_surjective.
Qed.

Hypothesis product_graded : graded_product G (alg_mul A).

(** Source for [quotient_mul_graded]: Federer (1969), 1.3.1, p. 13,
    homogeneous ideal and component-quotient displays. In words: The
    square-generated ideal is homogeneous and begins in degree two, so the
    quotient inherits its grading and each component is the corresponding
    component quotient. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma quotient_mul_graded : graded_product quotient_grading quotient_mul.
Proof.
move=> m n x y hx hy.
have [u [hu <-]] := quotient_homogeneous_representative hx.
have [v [hv <-]] := quotient_homogeneous_representative hy.
change (quotient_grade (m + n) (quotient_mul (pi u) (pi v)) =
  quotient_mul (pi u) (pi v)).
rewrite quotient_mulE quotient_gradeE.
by rewrite (product_graded hu hv).
Qed.

(** Source for [quotient_graded_algebra]: Federer (1969), 1.3.1, p. 13,
    homogeneous ideal and component-quotient displays. In words: The
