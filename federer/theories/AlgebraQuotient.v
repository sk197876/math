Definition quotient_algebra : algebra K :=
  @Algebra K (GRing.Lmodule.clone K quotient_algebra_space _) quotient_mul
    quotient_one quotient_mul_bilinear quotient_mul_assoc
    quotient_mul_unitl quotient_mul_unitr.

(** Source for [quotient_algebra_projection]: Federer (1969), 1.3.1, p. 13,
