(** Infrastructure for Federer 1.3.1, first paragraph: two-sided ideals and
    quotient algebras. No basis or finite-dimensionality is assumed. *)
(** Source for [two_sided_ideal]: Federer (1969), 1.3.1, p. 13, opening
    quotient-algebra paragraph. In words: The exterior algebra is the
    quotient of the tensor algebra by the two-sided ideal generated by
    squares of vectors. Definition or construction used to formalise this
    passage. *)
Record two_sided_ideal (K : fieldType) (A : algebra K) := TwoSidedIdeal {
  ideal_subspace :> subspace A;
  ideal_mull : forall x y, ideal_subspace y -> ideal_subspace (alg_mul A x y);
  ideal_mulr : forall x y, ideal_subspace x -> ideal_subspace (alg_mul A x y)
}.

Section QuotientAlgebra.
Variable K : fieldType.
Variable A : algebra K.
Variable I : two_sided_ideal A.
Local Notation pi := (quotient_projection I).

(** Source for [quotient_algebra_space]: Federer (1969), 1.3.1, p. 13,
    opening quotient-algebra paragraph. In words: The exterior algebra is
    the quotient of the tensor algebra by the two-sided ideal generated by
    squares of vectors. Definition or construction used to formalise this
    passage. *)
Definition quotient_algebra_space := module_quotient I.
HB.instance Definition _ := GRing.Lmodule.copy quotient_algebra_space
  (module_quotient I).

(** Source for [ideal_projection_zero]: Federer (1969), 1.3.1, p. 13,
    opening quotient-algebra paragraph. In words: The exterior algebra is
    the quotient of the tensor algebra by the two-sided ideal generated by
    squares of vectors. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma ideal_projection_zero x : pi x = 0 <-> I x.
Proof.
rewrite -(linear0 pi); split.
  by move/quotient_projection_eq; rewrite subr0.
by move=> hx; apply/quotient_projection_eq; rewrite subr0.
Qed.

(** Source for [ideal_product_compatible]: Federer (1969), 1.3.1, p. 13,
    opening quotient-algebra paragraph. In words: The exterior algebra is
    the quotient of the tensor algebra by the two-sided ideal generated by
    squares of vectors. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma ideal_product_compatible x y x' y' :
  pi x = pi x' -> pi y = pi y' ->
  pi (alg_mul A x y) = pi (alg_mul A x' y').
Proof.
move/quotient_projection_eq=> hx; move/quotient_projection_eq=> hy.
apply: eq_trans (_ : pi (alg_mul A x' y) = _).
  apply/quotient_projection_eq; rewrite -(bilBl (alg_bilinear A)).
  exact: ideal_mulr hx.
apply/quotient_projection_eq; rewrite -(bilBr (alg_bilinear A)).
exact: ideal_mull hy.
Qed.

(** Source for [quotient_mul]: Federer (1969), 1.3.1, p. 13, opening
