(** Source for [analytic_reduction_original_primitive_haar_null]:
    for almost every original q in Q_m,
    L is generated by M and the
    image of omega_m q^-1, exactly the
    intermediate conclusion of 3.4.8(8), p. 330.
    The original quotient, coefficient field,
    coordinates and rotation group all remain. *)
Theorem analytic_reduction_original_primitive_haar_null (mu:set H->\bar R):
  is_left_haar_measure mulH mu ->
  mu [set q:H|~is_generated_commutative_subring
    (fun y:L=>y = inclusion (pi (@analytic_orthogonal_germ_map R X B hB n e he
      (invO (set_val q)) (gamma m))) \/exists a:M,y = phi a) setT] = 0%:E.
Proof.
move=>hMu.
pose bad:=fun v:R_n R (n-m)=>~is_generated_commutative_subring
  (fun y:L=>y = \sum_i phi (eta (realPrefix (v i)))*
    inclusion (pi (gamma (ordinal_coordinate_tail_index hMN i))) \/exists a:M,y = phi a) setT.
have hDirectionNull:=(@analytic_reduction_primitive_suffix_nullity R X B hB n e he hON omega hDual
  I hI hProper g C pi hPi m hMN hAllB L inclusion hFraction M eta phi hCoefficient).2.
have hSphereSets:[set v:R_n R (n-m)|inner_norm (@euclidean_inner_productP R (n-m)) v = 1 /\bad v] =
    [set v:R_n R (n-m)|bad v /\inner_norm (@euclidean_inner_productP R (n-m)) v = 1].
  apply:funext=>v;apply:propext;by split=>[[]|[]].
have hSphereNull:@hausdorff_measure R (inner_metric_space (@euclidean_inner_productP R (n-m))) (n-m-1)
    [set v|inner_norm (@euclidean_inner_productP R (n-m)) v = 1 /\bad v] = 0%:E.
  rewrite hSphereSets;exact:hDirectionNull.
have hHaarNull:=@analytic_suffix_sphere_haar_coordinate_null R X B hB n e he hON omega hDual m hMN
  mulO invO unitO hO mulH invH unitH hH mu bad hMu hSphereNull.
have hSets:[set q:H|bad [ffun i=>omega (ordinal_coordinate_tail_index hMN i)
      (orthogonal_element_map (set_val q) (e m))]] =
    [set q:H|~is_generated_commutative_subring
      (fun y:L=>y = inclusion (pi (@analytic_orthogonal_germ_map R X B hB n e he
        (invO (set_val q)) (gamma m))) \/exists a:M,y = phi a) setT].
  apply:funext=>q.
  change (bad [ffun i=>omega (ordinal_coordinate_tail_index hMN i)
    (orthogonal_element_map (set_val q) (e m))] =
    ~is_generated_commutative_subring
      (fun y:L=>y = inclusion (pi (@analytic_orthogonal_germ_map R X B hB n e he
        (invO (set_val q)) (gamma m))) \/exists a:M,y = phi a) setT).
  rewrite /bad.
  have hInverse:=(@orthogonal_element_inv R X B hB n e he mulO invO unitO hO (set_val q)).2.
  have hCoordinate:=@orthogonal_primitive_field_coordinate R X B hB n e he hON omega hDual
    C pi L M inclusion m hMN eta phi hCoefficient (set_val q) (invO (set_val q)) hInverse (set_valP q).
  have hSum:(\sum_i phi (eta (realPrefix ([ffun i=>omega (ordinal_coordinate_tail_index hMN i)
      (orthogonal_element_map (set_val q) (e m))] i)))*
      inclusion (pi (gamma (ordinal_coordinate_tail_index hMN i)))) =
      inclusion (pi (@analytic_orthogonal_germ_map R X B hB n e he (invO (set_val q)) (gamma m))).
    rewrite hCoordinate;apply:eq_bigr=>i _;by rewrite ffunE.
  by rewrite hSum.
by rewrite -hSets.
Qed.
End PrimitiveHaar.
