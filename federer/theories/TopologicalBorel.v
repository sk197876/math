(** Federer (1969), 2.2.1, p. 60: Borel sets of a topological space are the
    family generated by its open sets. General topology is background;
    generated-family mathematics uses the local sealed specification. Source
    editions: BorelFamilyUP.v. *)
From mathcomp Require Import all_boot boolp classical_sets cardinality topology.
From Federer Require Import BorelFamilyUP BorelFamilyBasic GeneratedBorel.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope classical_set_scope.

(** Source for [open_family_within_whole]: supporting domain
    proof for the definition in Federer 2.2.1, p. 60: every
    open set is a subset of the underlying space. *)
Lemma open_family_within_whole (T : topologicalType) :
  forall A : set T, open A -> A `<=` setT.
Proof. by move=> A _ x _. Qed.

(** Source for [borel_set]: Federer 2.2.1, p. 60, definition of a Borel set
    associated with the topology The generated family is sealed. *)
Definition borel_set (T : topologicalType) : set (set T) :=
  generated_borel_family (@open_family_within_whole T).

(** Source for [borel_sets_specification]: Federer 2.2.1,
    p. 60: Borel sets form the smallest Borel family containing
    the open sets. This exposes the abstract generation laws. *)
Lemma borel_sets_specification (T : topologicalType) :
  is_generated_borel_family setT (@open T) (@borel_set T).
Proof. exact: generated_borel_family_specification. Qed.

(** Source for [borel_sets_family]: Federer 2.2.1, p. 60,
    the Borel sets satisfy the Borel-family closure laws. *)
Lemma borel_sets_family (T : topologicalType) :
  is_borel_family setT (@borel_set T).
Proof. exact: generated_borel_family_laws (borel_sets_specification T). Qed.

(** Source for [open_borel_set]: Federer 2.2.1, p. 60,
    every open generator is a Borel set. *)
Lemma open_borel_set (T : topologicalType) (A : set T) : open A -> borel_set A.
Proof. exact: (@generated_borel_family_contains _ setT (@open T) _ (borel_sets_specification T) A). Qed.

(** Source for [borel_set_complement]: Federer 2.2.1(1),
    pp. 59-60, the complement of a Borel set is Borel. *)
Lemma borel_set_complement (T : topologicalType) (A : set T) :
  borel_set A -> borel_set (~` A).
Proof.
move=> hA; have h := @borel_family_complement _ setT _ (borel_sets_family T) A hA.
by rewrite setTD in h.
Qed.

(** Source for [closed_borel_set]: Federer 2.2.1, p. 60,
    supporting closed-set membership: closed sets are complements
    of open sets and hence belong to the generated Borel family. *)
Lemma closed_borel_set (T : topologicalType) (A : set T) : closed A -> borel_set A.
Proof.
move=> hA; have h := borel_set_complement (open_borel_set (closed_openC hA)).
by rewrite setCK in h.
Qed.

(** Source for [borel_set_countable_union]: Federer 2.2.1(2),
    pp. 59-60, indexed countable unions of Borel sets are Borel. *)
Lemma borel_set_countable_union (T : topologicalType) (J : choiceType)
    (D : set J) (F : J -> set T) :
  countable D -> (forall j, D j -> borel_set (F j)) -> borel_set (\bigcup_(j in D) F j).
Proof. exact: (@borel_family_indexed_union _ J setT _ (borel_sets_family T) D F). Qed.

(** Source for [borel_set_countable_intersection]: Federer
    2.2.1(3), pp. 59-60, nonempty countable intersections of
    Borel sets are Borel. *)
Lemma borel_set_countable_intersection (T : topologicalType) (J : choiceType)
    (D : set J) (F : J -> set T) : countable D -> (exists j, D j) ->
  (forall j, D j -> borel_set (F j)) -> borel_set (\bigcap_(j in D) F j).
Proof. exact: (@borel_family_indexed_intersection _ J setT _ (borel_sets_family T) D F). Qed.

(** Source for [borel_set_difference]: Federer 2.2.1(1),(3),
    pp. 59-60, supporting difference closure, used for the sets
    V_i minus B in 2.2.2(2), p. 61. *)
Lemma borel_set_difference (T : topologicalType) (A B : set T) :
  borel_set A -> borel_set B -> borel_set (A `\` B).
Proof. exact: (@borel_family_difference _ setT _ (borel_sets_family T) A B). Qed.
