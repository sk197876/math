(** Federer (1969), 4.1.22, p. 379: seal the generated
    additive subgroup after proving existence. Only its original
    containment, subgroup and minimality laws are public. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
From Federer Require Import GeneratedAdditiveSubgroupUP
  GeneratedAdditiveSubgroupExistence.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.

Module Type GeneratedAdditiveSubgroupSignature.
(** Source: the additive subgroup generated by the prescribed
    simplex family, Federer 4.1.22, p. 379. *)
Parameter value:forall (V:zmodType),set V->set V.
(** Source: its independent least-subgroup laws,
    Federer 4.1.22, p. 379. *)
Parameter laws:forall (V:zmodType) (D:set V),
  is_generated_additive_subgroup D (@value V D).
End GeneratedAdditiveSubgroupSignature.

Module GeneratedAdditiveSubgroup:GeneratedAdditiveSubgroupSignature.
(** Source: hide the proved existence witness behind the
    original laws, supporting Federer 4.1.22, p. 379. *)
Definition value (V:zmodType) (D:set V):set V:=
  projT1 (cid (@generated_additive_subgroup_exists V D)).
(** Source: the opaque value satisfies the original independent
    specification, supporting Federer 4.1.22, p. 379. *)
Lemma laws (V:zmodType) (D:set V):
  is_generated_additive_subgroup D (@value V D).
Proof. exact:(projT2 (cid (@generated_additive_subgroup_exists V D))). Qed.
End GeneratedAdditiveSubgroup.
