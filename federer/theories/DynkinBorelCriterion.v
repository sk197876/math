(** Supporting the section-volume measurability argument for Federer (1969),
    2.10.46, p. 204: a family closed under whole sets, nested differences
    and disjoint countable unions contains the Borel family generated by any
    intersection- stable subfamily that it contains. This pi-lambda argument
    is an auxiliary proof route for the generated Borel family of 2.2.1, pp.
    59–60, not a verbatim book theorem. The minimal intermediate family is
    used only inside the opaque proof; no chosen implementation is exposed.
    Source context: DynkinFamilyUP.v. *)
From mathcomp Require Import all_boot boolp classical_sets cardinality.
From Federer Require Import DynkinFamilyUP BorelFamilyUP BorelFamilyRedundancy
  CountableFamilySequence SetSequenceDisjointification.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope classical_set_scope.

(** Source for [intersection_closed_dynkin_borel]: supporting
    Borel-family consequence for 2.10.46, p. 204.
    Disjointification as in 2.1.3, p. 55, converts
    sequence-union closure to arbitrary countable-union closure. *)
Lemma intersection_closed_dynkin_borel (X : choiceType) (F : set (set X)) :
  is_dynkin_family F -> (forall A B, F A -> F B -> F (A `&` B)) ->
  is_borel_family setT F.
Proof.
move=> hF hi.
have hc := dynkin_family_complement hF.
have hu A B : F A -> F B -> F (A `|` B).
  move=> hA hB; have h := hc _ (hi _ _ (hc _ hA) (hc _ hB)).
  by rewrite setCI !setCK in h.
have hseq (A : nat -> set X) : (forall n, F (A n)) -> F (\bigcup_n A n).
  move=> hA.
  have hp n : F (set_sequence_prefix A n).
    elim: n=> [|n ih]; first by rewrite set_sequence_prefix_zero; exact: dynkin_family_empty hF.
    rewrite set_sequence_prefix_succ; exact: hu ih (hA n).
  have hd n : F (set_sequence_disjointify A n).
    rewrite /set_sequence_disjointify setDE; exact: hi _ _ (hA n) (hc _ (hp n)).
  have h := dynkin_family_disjoint_union hF hd (@set_sequence_disjointify_disjoint X A).
  by rewrite set_sequence_disjointify_union in h.
apply: (@borel_family_of_union X setT F (dynkin_family_empty hF)).
- by move=> A _; exact: subsetT.
- by move=> A hA; rewrite setTD; exact: hc.
- move=> G hG hGc.
  have [A [hA he]] := @countable_family_as_sequence X _ G (fun A=>A) hGc.
  rewrite -he; apply: hseq=> n; have [hz|[B [hB hb]]] := hA n.
  + rewrite hz; exact: dynkin_family_empty hF.
  + rewrite hb; exact: hG.
Qed.

(** Source for [dynkin_generated_borel_inclusion]: supporting
    pi-lambda generation theorem for 2.10.46, p. 204,
    using the abstract least-family laws of 2.2.1,
    pp. 59–60. The generator family need not itself
    contain the whole set or the empty set. *)
Theorem dynkin_generated_borel_inclusion (X : choiceType)
    (P B F : set (set X)) :
  is_generated_borel_family setT P B ->
  (forall A C, P A -> P C -> P (A `&` C)) ->
  is_dynkin_family F -> P `<=` F -> B `<=` F.
Proof.
move=> hB hpi hF hPF.
pose D := [set A | forall G : set (set X), is_dynkin_family G -> P `<=` G -> G A].
have hD : is_dynkin_family D.
  constructor.
  - move=> G hG hPG; exact: dynkin_family_whole hG.
  - move=> A C hA hC hAC G hG hPG.
    exact (@dynkin_family_nested_difference X G hG A C (hA G hG hPG) (hC G hG hPG) hAC).
  - move=> A hA hd G hG hPG.
    exact (@dynkin_family_disjoint_union X G hG A (fun n=>hA n G hG hPG) hd).
have hPD : P `<=` D by move=> A hA G hG hPG; exact: hPG.
have hfirst A : P A -> forall C, D C -> D (A `&` C).
  move=> hA C hC.
  have htest := dynkin_intersection_test_family hD (hPD A hA).
  have hgen : P `<=` [set E | D E /\ D (A `&` E)].
    move=> E hE; split; first exact: hPD.
    exact: hPD _ (hpi A E hA hE).
  exact: (hC _ htest hgen).2.
have hi A C : D A -> D C -> D (A `&` C).
  move=> hA hC.
  have htest := dynkin_intersection_test_family hD hA.
  have hgen : P `<=` [set E | D E /\ D (A `&` E)].
    move=> E hE; split; first exact: hPD.
    rewrite setIC; exact: hfirst E hE A hA.
  exact: (hC _ htest hgen).2.
have hBD : B `<=` D := generated_borel_family_least hB (intersection_closed_dynkin_borel hD hi) hPD.
move=> A hA; exact: (hBD A hA) F hF hPF.
Qed.
