(** Federer (1969), 4.1.22, p. 379: the integral
    polyhedral chains form the additive subgroup generated by
    the prescribed oriented simplexes. Specify generated subgroup
    by containment and minimality, using the existing subgroup
    predicate; do not define it by a chosen word construction. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets.
From Federer Require Import TopologicalGroupUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [is_generated_additive_subgroup]: the least
    additive subgroup containing the original generators in
    Federer 4.1.22, p. 379. This specification is independent
    of both its existence witness and any chosen carrier. *)
Record is_generated_additive_subgroup (V:zmodType) (D G:set V):Prop:={
  (** Source: the generated set is an additive subgroup,
      Federer 4.1.22, p. 379. *)
  generated_additive_subgroup_subgroup:
    is_subgroup (fun x y:V=>x+y) (fun x=>-x) 0 G;
  (** Source: it contains every prescribed simplex,
      Federer 4.1.22, p. 379. *)
  generated_additive_subgroup_contains:D `<=` G;
  (** Source: generation means the least such subgroup,
      Federer 4.1.22, p. 379. *)
  generated_additive_subgroup_least:forall H:set V,
    is_subgroup (fun x y:V=>x+y) (fun x=>-x) 0 H->
    D `<=` H->G `<=` H
}.

(** Source for [generated_additive_subgroup_unique_membership]:
    uniqueness of the generated subgroup from its original
    least-subgroup specification, supporting Federer 4.1.22,
    p. 379. No existence construction is inspected. *)
Theorem generated_additive_subgroup_unique_membership (V:zmodType)
    (D G H:set V):
  is_generated_additive_subgroup D G->is_generated_additive_subgroup D H->
  forall x,G x<->H x.
Proof.
move=>hG hH x;split.
- exact:(generated_additive_subgroup_least hG
    (generated_additive_subgroup_subgroup hH)
    (generated_additive_subgroup_contains hH)).
- exact:(generated_additive_subgroup_least hH
    (generated_additive_subgroup_subgroup hG)
    (generated_additive_subgroup_contains hG)).
Qed.
