(** Federer (1969), 3.4.12, p. 339, extending 3.4.11, p. 338:
    the original leading ideal remains behind its
    independently specified least-ideal interface. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets reals.
From Federer Require Import ScalarRestriction ComplexScalarSealed RealNormUP HolomorphicGermRing HolomorphicInitialPolynomialGermUP
  HolomorphicInitialIdealExistence.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.
Module Type HolomorphicInitialIdealSignature.
(** Source for [value]: the ideal generated by
    all original leading polynomial germs, 3.4.11, p. 338. *)
Parameter value:forall (R:realType) (X:lmodType (ComplexScalars.C R)) (NX:X->R) (hNX:@is_real_norm R (restricted_space (ComplexScalars.embed R) X) NX),
  set (@holomorphic_germ_ring R X NX hNX 0)->set (@holomorphic_germ_ring R X NX hNX 0).
(** Source for [laws]: the independent least-ideal
    property of the original leading ideal, 3.4.11, p. 338. *)
Parameter laws:forall (R:realType) (X:lmodType (ComplexScalars.C R)) (NX:X->R) (hNX:@is_real_norm R (restricted_space (ComplexScalars.embed R) X) NX)
  (I:set (@holomorphic_germ_ring R X NX hNX 0)),is_holomorphic_initial_ideal I (@value R X NX hNX I).
End HolomorphicInitialIdealSignature.
Module HolomorphicInitialIdeal:HolomorphicInitialIdealSignature.
(** Source for [value]: private selection from proved
    leading-ideal existence, supporting 3.4.11, p. 338. *)
Definition value (R:realType) (X:lmodType (ComplexScalars.C R)) (NX:X->R) (hNX:@is_real_norm R (restricted_space (ComplexScalars.embed R) X) NX)
  (I:set (@holomorphic_germ_ring R X NX hNX 0)):=
  projT1 (cid (@holomorphic_initial_ideal_exists R X NX hNX I)).
(** Source for [laws]: the selected ideal satisfies
    its independent original generator laws, 3.4.11, p. 338. *)
Lemma laws (R:realType) (X:lmodType (ComplexScalars.C R)) (NX:X->R) (hNX:@is_real_norm R (restricted_space (ComplexScalars.embed R) X) NX)
  (I:set (@holomorphic_germ_ring R X NX hNX 0)):is_holomorphic_initial_ideal I (@value R X NX hNX I).
Proof. exact:(projT2 (cid (@holomorphic_initial_ideal_exists R X NX hNX I))). Qed.
End HolomorphicInitialIdeal.
