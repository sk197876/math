(** Federer (1969), 3.4.8(8), p. 329:
    the coefficient field is the subfield
    generated by the original coefficient image.
    Independent inclusion and fraction laws precede
    its existence; the original coefficient map
    may have a kernel. *)
From mathcomp Require Import all_boot all_order all_algebra.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.

(** Source for [is_coefficient_fraction_field]: the
    original subfield M generated by p(Q_m)
    in 3.4.8(8), p. 329. Every member
    is a fraction of original coefficients
    with nonzero image denominator. No injectivity
    of the original coefficient map is assumed. *)
Record is_coefficient_fraction_field (A:comNzRingType) (L M:fieldType)
  (original:{rmorphism A->L}) (scalar:{rmorphism A->M}) (inclusion:{rmorphism M->L}):Prop:={
  (** Source for [coefficient_fraction_scalar_triangle]:
      the original coefficient inclusion into M
      agrees with its original image in L,
      3.4.8(8), p. 329. *)
  coefficient_fraction_scalar_triangle:forall a:A,inclusion (scalar a) = original a;
  (** Source for [coefficient_fraction_representation]: every
      member of M is a fraction of
      original coefficient images, as used to
      clear denominators in 3.4.8(8), p. 330. *)
  coefficient_fraction_representation:forall x:M,exists a b:A,
    original b<>0 /\inclusion x = original a/original b
}.
