(** Source for [compactly_supported_quotient]: "we define
    s, r_1, r_2 in K(X)+ so that ... r_j s = u_j and spt r_j = spt u_j",
    Federer 2.7.4, p. 124: the quotient u/s belongs to K(X) when s is
    continuous and does not vanish on an open set containing spt u. It
    is continuous on that open set, and vanishes on the open complement
    of spt u. Supporting lemma. *)
Lemma compactly_supported_quotient (u s : X -> R) (U : set X) : K u ->
  continuous (s : X -> real_line_metric R) -> open U -> real_function_support u `<=` U ->
  (forall x, U x -> s x != 0) -> K (fun x => u x / s x).
Proof.
move=> [huc huK] hsc hU hsub hs0; split; last first.
  apply: (compact_support_unary_operation huK)=> x ->; exact: mul0r.
move=> x; case: (pselect (U x))=> hx.
  apply: (@continuousM R X u (fun y => (s y)^-1) x (huc x)).
  exact: (@continuousV R X s x (hs0 x hx) (hsc x)).
have hnx : ~ real_function_support u x by move=> h; exact: hx (hsub _ h).
have hN : nbhs x (~` real_function_support u).
  apply: open_nbhs_nbhs; split=> //; apply: closed_openC; exact: real_function_support_closed.
move=> S hS; apply: (filterS _ hN)=> y hy /=.
rewrite (real_function_zero_off_support hy) mul0r.
have := nbhs_singleton hS; by rewrite /= (real_function_zero_off_support hnx) mul0r.
Qed.

Section Approximation.
Variables (E B : set_system (X * X)) (rho : (X -> R) -> (X -> R) -> R) (w : X -> R).
Hypothesis hE : is_uniformity E.
