(** Federer (1969), 2.7.4, printed pp. 123-125: "Theorem. If G acts
    uniformly on X, then there exists a nonzero monotone invariant integral
    on K(X)." Federer's proof is followed. A nonzero w in K(X)+ is chosen.
    The set P is the cartesian product of the compact intervals {t: 0 <= t
    <= (u:w)} corresponding to all u in K(X)+. Formally P is a subset of the
    product space of all real functions on the set of functions X -> R, with
    the factor {0} at every function outside K(X)+; it is compact by
    Tychonoff's theorem. For 0 <> v in K(X)+, p_v in P is given by p_v(u) =
    (u:v)/(w:v) for u in K(X)+. For beta in the invariant basis B, S(beta) =
    Closure {p_v: (spt v) x (spt v) subset beta}. "If beta_1, beta_2, beta_3
    in B and beta_1 cap beta_2 supset beta_3, then S(beta_1) cap S(beta_2)
    supset S(beta_3) <> empty. Accordingly, since P is compact, there exists
    a point lambda in cap_{beta in B} S(beta)." MathComp defines compactness
    through proper filters, so the finite intersection property enters
    through the proper filter generated by the sets {p_v: (spt v) x (spt v)
    subset beta}; a cluster point of this filter in P belongs to every
    S(beta). "The required properties of lambda (see 2.5.2, 2.5.13, 2.7.1)
    follow from like properties of the approximating functions p_v": each
    property is a closed condition on P which holds at every p_v with (spt
    v) x (spt v) subset beta for some beta in B, hence at lambda. The
    inequality lambda(u_1+u_2) >= lambda(u_1)+lambda(u_2) is proved as
    printed, with the correction of Federer's erratum p. 2, book p. 124 line
    30: "Whenever 0 <> v in K(X)+, (spt v) x (spt v) subset beta, a in spt
    v" replaces the printed "For any v in S(beta), a in spt v". Following
    the entries for book p. 125 lines 7-8, the estimate for p_v is stated
    for these v, and the conclusion reads "Since lambda in S(beta), we
    conclude". The function lambda is additive, positively homogeneous and
    nonnegative on K(X)+; it is extended to K(X) by lambda(f) = lambda(f+) -
    lambda(f-), a monotone Daniell integral by 2.5.13
    (compact_positive_difference_daniell), which is invariant and satisfies
    lambda(w) = 1. The hypotheses are those used in the proof: the group
    laws of G, X a homogeneous space of G (2.7.1, p. 121), X locally compact
    Hausdorff, X nonempty, and the uniform action. The topology of G enters
    only through the continuity of the maps A_g; local compactness and the
    Hausdorff property of G are not used. For empty X, K(X) = {0}, and no
    nonzero integral exists; the nonemptiness of X is a necessary hypothesis
    not stated in the book. *)
