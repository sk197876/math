(** Source for [haar_approximation]: "Whenever 0 <> v in K(X)+ we
    define p_v in P, p_v(u) = (u:v)/(w:v) for u in K(X)+", Federer
    2.7.4, p. 124. Definition; the value at functions outside K(X)+ is
    set to 0. *)
Definition haar_approximation (v : X -> R) : PT :=
  fun u => if pselect (Kp u) then rho u v / rho w v else 0.

(** Source for [haar_ratio_bound]: the right end (u:w) of the
    compact interval {t: 0 <= t <= (u:w)} of Federer 2.7.4, p. 124, for
    u in K(X)+, and 0 for the other functions. Definition. *)
Definition haar_ratio_bound (u : X -> R) : R := if pselect (Kp u) then rho u w else 0.

(** Source for [haar_product_space]: "the cartesian product P of the
    compact intervals {t: 0 <= t <= (u:w)} corresponding to all
    u in K(X)+", Federer 2.7.4, p. 124. Definition as a subset of the
    product space of all real functions on X -> R, with the factor {0}
    outside K(X)+. *)
Definition haar_product_space : set PT :=
  [set p | forall u, `[0, haar_ratio_bound u]%classic (p u)].

(** Source for [small_support_functions]: the functions v with
    0 <> v in K(X)+ and (spt v) x (spt v) subset beta, Federer 2.7.4,
    p. 124, and Federer's erratum p. 2, book p. 124 line 30.
    Definition. *)
Definition small_support_functions (beta : set (X * X)) : set (X -> R) :=
  [set v | [/\ Kp v, exists b, v b <> 0 &
    real_function_support v `*` real_function_support v `<=` beta]].

(** Source for [haar_approximation_set]: the set
    {p_v: (spt v) x (spt v) subset beta} of Federer 2.7.4, p. 124.
    Definition. *)
Definition haar_approximation_set (beta : set (X * X)) : set PT :=
  haar_approximation @` small_support_functions beta.

(** Source for [haar_closed_set]: "with each beta in B (see 2.7.3) we
    associate the closed set S(beta) = Closure {p_v: (spt v) x (spt v)
    subset beta}", Federer 2.7.4, p. 124. Direct definition. *)
Definition haar_closed_set (beta : set (X * X)) : set PT := closure (haar_approximation_set beta).

(** Source for [haar_approximation_value]: "p_v(u) = (u:v)/(w:v) for
    u in K(X)+", Federer 2.7.4, p. 124. Supporting lemma. *)
Lemma haar_approximation_value v u : Kp u -> haar_approximation v u = rho u v / rho w v.
Proof. by rewrite /haar_approximation; case: pselect. Qed.

(** Source for [haar_ratio_bound_value]: the bound (u:w) of the
    interval {t: 0 <= t <= (u:w)} for u in K(X)+, Federer 2.7.4,
    p. 124. Supporting lemma. *)
Lemma haar_ratio_bound_value u : Kp u -> haar_ratio_bound u = rho u w.
Proof. by rewrite /haar_ratio_bound; case: pselect. Qed.

(** Source for [haar_approximation_in_product]: "p_v in P",
    Federer 2.7.4, p. 124, by "(u:v)/(w:v) <= (u:w)" on p. 124.
    Direct formalisation. *)
Lemma haar_approximation_in_product v : Kp v -> (exists b, v b <> 0) ->
  haar_product_space (haar_approximation v).
Proof.
move=> hv hv0 u; rewrite /= in_itv /=.
case: (pselect (Kp u))=> hu; last first.
  by rewrite /haar_approximation /haar_ratio_bound; case: pselect=> [hu'|hnu]; [case: (hu hu')|rewrite lexx].
rewrite haar_approximation_value // haar_ratio_bound_value //.
have hwv := haar_ratio_positive hrho hw hv hw0 hv0.
apply/andP; split.
  by apply: divr_ge0; [exact: haar_ratio_nonnegative hrho hu hv hv0|exact: ltW].
have hq := haar_ratio_quotient_upper hA hrho hu hv hw hv0 hw0.
exact: hq.
Qed.

(** Source for [haar_product_space_compact]: "since P is compact",
    Federer 2.7.4, p. 124: a product of compact intervals, by
    Tychonoff's theorem. Direct formalisation. *)
Lemma haar_product_space_compact : compact haar_product_space.
Proof.
exact: (@tychonoff (X -> R) (fun _ => R) (fun u => `[0, haar_ratio_bound u]%classic)
  (fun u => @segment_compact R 0 (haar_ratio_bound u))).
Qed.

