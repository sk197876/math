Lemma coordinate_continuous (u : I) : continuous (fun p : PT => p u).
Proof. exact: proj_continuous. Qed.

(** Source for [continuous_add_real]: sums of continuous real
    functions on P are continuous, supporting "The required properties
    of lambda ... follow from like properties of the approximating
    functions p_v", Federer 2.7.4, p. 124. *)
Lemma continuous_add_real (f g : PT -> R) : continuous f -> continuous g ->
  continuous (fun p => f p + g p).
Proof. by move=> hf hg p; exact: (@continuousD R R^o PT f g p (hf p) (hg p)). Qed.

(** Source for [continuous_scale_real]: multiples of continuous real
    functions on P are continuous, supporting Federer 2.7.4, p. 124. *)
Lemma continuous_scale_real (c : R) (f : PT -> R) : continuous f -> continuous (fun p => c * f p).
Proof.
move=> hf p; apply: (@continuousM R PT (fun _ => c) f p); last exact: hf.
exact: (@cst_continuous PT R c p).
Qed.

(** Source for [closed_le_real]: {p: f(p) <= g(p)} is closed for
    continuous real f, g, supporting the passage from the p_v to their
    limit point lambda, Federer 2.7.4, pp. 124-125. *)
Lemma closed_le_real (f g : PT -> R) : continuous f -> continuous g -> closed [set p | f p <= g p].
Proof.
move=> hf hg.
have -> : [set p | f p <= g p] = (fun p => g p - f p) @^-1` [set x : R | 0 <= x].
  by apply/seteqP; split=> p /=; rewrite subr_ge0.
apply: preimage_closed; last exact: closed_ge.
by move=> p _; exact: (@continuousB R R^o PT g f p (hg p) (hf p)).
Qed.

(** Source for [closed_eq_real]: {p: f(p) = g(p)} is closed for
    continuous real f, g, supporting Federer 2.7.4, p. 124. *)
Lemma closed_eq_real (f g : PT -> R) : continuous f -> continuous g -> closed [set p | f p = g p].
Proof.
move=> hf hg.
have -> : [set p | f p = g p] = (fun p => g p - f p) @^-1` [set x : R | x = 0].
  by apply/seteqP; split=> p /= h; [rewrite h subrr|apply/eqP; rewrite eq_sym -subr_eq0; apply/eqP].
apply: preimage_closed; last exact: closed_eq.
by move=> p _; exact: (@continuousB R R^o PT g f p (hg p) (hf p)).
Qed.

