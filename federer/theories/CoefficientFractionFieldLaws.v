(** Federer (1969), 3.4.8(8), pp. 329–330:
    the original coefficient field has exactly
    the prescribed image fractions and is the
    least subfield containing the coefficient image.
    Prove these laws through the independent interface. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
From Federer Require Import CommutativeSubringUP CommutativeSubfieldUP CoefficientFractionFieldUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Section Laws.
Variable A:comNzRingType.
Variables L M:fieldType.
Variable original:{rmorphism A->L}.
Variable scalar:{rmorphism A->M}.
Variable inclusion:{rmorphism M->L}.
Hypothesis hField:is_coefficient_fraction_field original scalar inclusion.

(** Source for [coefficient_fraction_field_image]: the
    original M consists exactly of original
    coefficient fractions, as used to clear
    denominators in 3.4.8(8), p. 330. *)
Theorem coefficient_fraction_field_image (y:L):
  (exists x:M,inclusion x = y) <->exists a b:A,
    original b<>0 /\y = original a/original b.
Proof.
split.
- move=>[x <-];exact:coefficient_fraction_representation hField x.
- move=>[a [b [hB ->]]];exists (scalar a/scalar b).
  by rewrite fmorph_div !(coefficient_fraction_scalar_triangle hField).
Qed.

(** Source for [coefficient_fraction_field_minimal]: M
    is precisely the subfield generated by
    the original coefficient image, 3.4.8(8),
    p. 329. Fraction representation proves the
    least-subfield assertion without inspecting its construction. *)
Theorem coefficient_fraction_field_minimal (S:set L):
  is_commutative_subfield S ->(forall a:A,S (original a)) ->
  forall x:M,S (inclusion x).
Proof.
move=>hS hContains x.
have [a [b [hB hX]]]:=coefficient_fraction_representation hField x.
rewrite hX;apply:(@commutative_subring_multiply L S (commutative_subfield_ring hS));first exact:hContains a.
exact:(@commutative_subfield_inverse L S hS (original b) (hContains b)).
Qed.

(** Source for [coefficient_fraction_scalar_kernel]: the
    original coefficient map into M has
    the same kernel as its original image
    in L, supporting the nonzero denominators
    of 3.4.8(8), p. 330. *)
Lemma coefficient_fraction_scalar_kernel (a:A):scalar a = 0 <->original a = 0.
Proof.
split.
- move=>hZero;rewrite -(coefficient_fraction_scalar_triangle hField a) hZero;exact:rmorph0.
- move=>hZero;apply:(fmorph_inj inclusion).
  by rewrite (coefficient_fraction_scalar_triangle hField a) hZero rmorph0.
Qed.
End Laws.
