(** Federer (1969), 4.1.1, pp. 343–344: the original
    smooth-function topology generated by the exact finite
    derivative seminorms. All underlying spaces, derivatives,
    suprema and topology witnesses are already opaque. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets reals.
From Federer Require Import Hom RealNormUP ContinuousMultilinearSealed OpenFamilyTopologyUP
  OpenVectorTopologyUP DirectedSeminormFamilyUP DirectedSeminormTopologySealed
  DirectedSeminormTopology DirectedSeminormVectorTopology DirectedSeminormHausdorff
  SmoothCompactSet SmoothFunctionSpaceUP SmoothFunctionDerivativesUP
  SmoothDerivativeSeminormUP SmoothDerivativeSeminormSealed SmoothFunctionSeminormFamily.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.

Section SmoothTopology.
Variable R:realType.
Variables X Y:lmodType R.
Variables (NX:X->R) (NY:Y->R).
Hypothesis hNX:is_real_norm NX.
Hypothesis hNY:is_real_norm NY.
Variable U:set X.
Variable E:lmodType R.
Variable ev:E->X->Y.
Hypothesis hE:is_smooth_function_space hNX hNY U ev.
Local Notation Z := (fun k=>@ContinuousMultilinear.space R k X Y NX NY hNX hNY).
Variable D:forall k,X->Hom E (Z k).
Hypothesis hD:@is_smooth_function_derivatives R X Y NX NY hNX hNY U E ev D.

(** Source for [smooth_function_derivative_seminorm]: nu^i_K
    is the opaque least bound on the actual derivatives through
    order i, Federer 4.1.1, p. 343. *)
Definition smooth_function_derivative_seminorm :=
  @SmoothDerivativeSeminorm.value R X Y NX NY hNX hNY U E ev D hD.

(** Source for [smooth_function_derivative_seminorm_laws]: the
    independently specified exact finite derivative bound,
    Federer 4.1.1, pp. 343–344. *)
Lemma smooth_function_derivative_seminorm_laws K i :
  @is_smooth_derivative_seminorm R X Y NX NY hNX hNY U E D K i
    (smooth_function_derivative_seminorm K i).
Proof. exact:SmoothDerivativeSeminorm.laws. Qed.

Local Notation I := (nat * smooth_compact_set hNX U)%type.
Local Notation p := (fun j:I=>smooth_function_derivative_seminorm j.2 j.1).
Local Notation hp := (smooth_function_seminorms_directed smooth_function_derivative_seminorm_laws).

(** Source for [smooth_function_opens]: the topology generated
    by nu^i_K in Federer 4.1.1, p. 344. This calls the proved
    opaque topology constructor and exposes no witness. *)
Definition smooth_function_opens:set (set E) :=
  @DirectedSeminormTopology.opens R E I p hp.

(** Source for [smooth_function_topology_laws]: the printed
    translated positive seminorm balls form exactly a neighbourhood
    base, Federer 4.1.1, p. 344. *)
Theorem smooth_function_topology_laws :
  is_seminorm_family_topology p smooth_function_opens.
Proof. exact:DirectedSeminormTopology.laws. Qed.

(** Source for [smooth_function_topology_vector]: compatibility
    of the smooth-function topology with addition and scalar
    multiplication, Federer 4.1.1, p. 344. *)
Theorem smooth_function_topology_vector : is_open_vector_topology smooth_function_opens.
Proof. exact:seminorm_family_vector_topology hp smooth_function_topology_laws. Qed.

(** Source for [smooth_function_topology_locally_convex]: the
    local convexity asserted in Federer 4.1.1, p. 344. *)
Theorem smooth_function_topology_locally_convex :
  open_family_locally_convex smooth_function_opens.
Proof. exact:seminorm_family_locally_convex hp smooth_function_topology_laws. Qed.

(** Source for [smooth_function_topology_hausdorff]: the
    Hausdorff assertion in Federer 4.1.1, p. 344, using the
    original order-zero singleton seminorms. *)
Theorem smooth_function_topology_hausdorff : open_family_hausdorff smooth_function_opens.
Proof.
apply:(seminorm_family_hausdorff hp smooth_function_topology_laws).
exact:(smooth_function_seminorms_separate hE hD smooth_function_derivative_seminorm_laws).
Qed.

(** Source for [smooth_function_topology_translation]: the
    translation invariance asserted in Federer 4.1.1, p. 344. *)
Theorem smooth_function_topology_translation a :
  open_family_continuous smooth_function_opens smooth_function_opens (fun f=>f+a).
Proof. exact:(@seminorm_family_translation_continuous R E I p smooth_function_opens
  smooth_function_topology_laws a). Qed.
End SmoothTopology.
