(** Federer (1969), 4.1.22, p. 379: the fixed-K
    integral subgroup and its real algebraic span. Definitions
    use independently specified opaque generated objects. Prove
    the elementary algebra and compact-index inclusions from
    their public laws, without inspecting either construction. *)
From mathcomp Require Import all_boot all_order all_algebra
  classical_sets reals.
From Federer Require Import Hom ModuleQuotient RealNormUP NormDifferentialUP
  InnerNorm HilbertFormCompactness GrassmannAbbreviations EuclideanInnerProduct
  CurrentSpaces SmoothCompactSet PolyhedralCurrentGenerators TopologicalGroupUP
  GeneratedAdditiveSubgroupUP GeneratedAdditiveSubgroupSealed
  GeneratedLinearSubspaceUP GeneratedLinearSubspaceSealed.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

Section PolyhedralCurrentAlgebra.
Variable R:realType.
Hypothesis h2:(1+1:R)!=0.
Variables n m:nat.
Local Notation X := (R_n R n).
Local Notation NX := (inner_norm (@euclidean_inner_productP R n)).
Local Notation hNX := (inner_norm_real_norm
  (@euclidean_inner_productP R n)).
Variable U:set X.
Hypothesis hU:forall x,U x->norm_domain_interior NX U x.
Arguments hU : clear implicits.
Local Notation C := (@current_space R h2 n U hU m).
Local Notation Index := (smooth_compact_set hNX U).
Local Notation generators K := (@polyhedral_simplex_generators R h2 n m U hU K).

(** Source for [integral_polyhedral_current_class]: the
    original integral polyhedral subgroup P-script_(m,K)(U),
    generated by all admissible oriented simplexes, Federer
    4.1.22, p. 379. Generation is algebraic, with integer
    addition and inversion; arbitrary real scaling is not imposed. *)
Definition integral_polyhedral_current_class (K:Index):set C:=
  @GeneratedAdditiveSubgroup.value C (generators K).

(** Source for [integral_polyhedral_current_class_laws]: the
    original independent least-additive-subgroup laws,
    Federer 4.1.22, p. 379. *)
Theorem integral_polyhedral_current_class_laws (K:Index):
  is_generated_additive_subgroup (generators K) (integral_polyhedral_current_class K).
Proof. exact:GeneratedAdditiveSubgroup.laws. Qed.

(** Source for [integral_polyhedral_current_subgroup]: the
    fixed-K integral class is an additive subgroup of the
    actual current space, Federer 4.1.22, p. 379. *)
Theorem integral_polyhedral_current_subgroup (K:Index):
  is_subgroup (fun S T:C=>S+T) (fun T=>-T) 0 (integral_polyhedral_current_class K).
Proof.
exact:generated_additive_subgroup_subgroup (integral_polyhedral_current_class_laws K).
Qed.

(** Source for [integral_polyhedral_current_generator]: every
    original simplex with its full vertex hull in K belongs
    to the integral subgroup, Federer 4.1.22, p. 379. *)
Theorem integral_polyhedral_current_generator (K:Index)
    (v:'I_(m.+1)->X):
  @polyhedral_simplex_vertex_hull R n m v `<=` smooth_compact_carrier K->
  integral_polyhedral_current_class K
    (@open_oriented_simplex_current R h2 n m U hU v).
Proof.
move=>hHull;apply:(generated_additive_subgroup_contains
  (integral_polyhedral_current_class_laws K)).
exact:(@polyhedral_simplex_generator R h2 n m U hU K v hHull).
Qed.

(** Source for [integral_polyhedral_current_zero]: the zero
    current is integral polyhedral with every original compact
    index, including an empty one, Federer 4.1.22, p. 379. *)
Lemma integral_polyhedral_current_zero (K:Index):
  integral_polyhedral_current_class K (0:C).
Proof. exact:subgroup_unit (integral_polyhedral_current_subgroup K). Qed.

(** Source for [integral_polyhedral_current_add]: the original
    fixed-K integral subgroup is closed under addition,
    Federer 4.1.22, p. 379. *)
Lemma integral_polyhedral_current_add (K:Index) (S T:C):
  integral_polyhedral_current_class K S->integral_polyhedral_current_class K T->
  integral_polyhedral_current_class K (S+T).
Proof.
move=>hS hT.
exact:(@subgroup_mul C (fun A B:C=>A+B) (fun A:C=>-A) 0
  (integral_polyhedral_current_class K)
  (integral_polyhedral_current_subgroup K) S T hS hT).
Qed.

(** Source for [integral_polyhedral_current_negate]: the
    original fixed-K integral subgroup is closed under
    additive inversion, Federer 4.1.22, p. 379. *)
Lemma integral_polyhedral_current_negate (K:Index) (T:C):
  integral_polyhedral_current_class K T->integral_polyhedral_current_class K (-T).
Proof. move=>hT;exact:(subgroup_inv (integral_polyhedral_current_subgroup K) hT). Qed.

(** Source for [integral_polyhedral_current_monotone]: enlarging
    K retains the original integral subgroup, supporting the
    compact union in Federer 4.1.22, p. 379. *)
Theorem integral_polyhedral_current_monotone (K L:Index):
  smooth_compact_carrier K `<=` smooth_compact_carrier L->
  integral_polyhedral_current_class K `<=` integral_polyhedral_current_class L.
Proof.
move=>hKL.
apply:(generated_additive_subgroup_least (integral_polyhedral_current_class_laws K)
  (integral_polyhedral_current_subgroup L)).
move=>T hT;apply:(generated_additive_subgroup_contains
  (integral_polyhedral_current_class_laws L)).
exact:(@polyhedral_simplex_generators_monotone R h2 n m U hU K L hKL T hT).
Qed.

(** Source for [polyhedral_current_subspace]: the original
    real polyhedral space P_(m,K)(U) generated by the integral
    subgroup, Federer 4.1.22, p. 379. It is the algebraic
    real span, with no flat, mass or topological closure. *)
Definition polyhedral_current_subspace (K:Index):subspace C:=
  @GeneratedLinearSubspace.value R C (integral_polyhedral_current_class K).

(** Source for [polyhedral_current_subspace_laws]: the original
    independent real-span laws, Federer 4.1.22, p. 379. *)
Theorem polyhedral_current_subspace_laws (K:Index):
  is_generated_linear_subspace (integral_polyhedral_current_class K)
    (polyhedral_current_subspace K).
Proof. exact:GeneratedLinearSubspace.laws. Qed.

(** Source for [integral_polyhedral_current_is_polyhedral]:
    every original integral chain lies in its real span,
    Federer 4.1.22, p. 379. *)
Theorem integral_polyhedral_current_is_polyhedral (K:Index):
  integral_polyhedral_current_class K `<=` polyhedral_current_subspace K.
Proof. exact:generated_linear_subspace_contains (polyhedral_current_subspace_laws K). Qed.

(** Source for [polyhedral_current_monotone]: enlarging K
    retains the original real polyhedral space, supporting
    its compact union in Federer 4.1.22, p. 379. *)
Theorem polyhedral_current_monotone (K L:Index):
  smooth_compact_carrier K `<=` smooth_compact_carrier L->
  polyhedral_current_subspace K `<=` polyhedral_current_subspace L.
Proof.
move=>hKL.
apply:(generated_linear_subspace_least (polyhedral_current_subspace_laws K)).
move=>T hT;apply:integral_polyhedral_current_is_polyhedral.
exact:(@integral_polyhedral_current_monotone K L hKL T hT).
Qed.

(** Source for [integral_polyhedral_current_empty_index]: the
    original subgroup for empty K is exactly the zero group,
    a boundary case of Federer 4.1.22, p. 379. No zero
    simplex is mistaken for an admissible empty-hull generator. *)
Theorem integral_polyhedral_current_empty_index (T:C):
  integral_polyhedral_current_class (@smooth_compact_empty R X NX hNX U) T<->T=0.
Proof.
split;last by move=>->;exact:integral_polyhedral_current_zero.
have hZero:is_subgroup (fun S T:C=>S+T) (fun T=>-T) 0 [set T:C|T=0].
  constructor;first by [].
  - by move=>A B -> ->;rewrite addr0.
  - by move=>A ->;rewrite oppr0.
apply:(generated_additive_subgroup_least
  (integral_polyhedral_current_class_laws (@smooth_compact_empty R X NX hNX U)) hZero).
move=>S hS;exfalso.
exact:(@polyhedral_simplex_generators_empty R h2 n m U hU S hS).
Qed.
End PolyhedralCurrentAlgebra.
