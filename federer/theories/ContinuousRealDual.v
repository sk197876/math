(** Federer (1969), 4.1.1, pp. 344–345: opaque continuous
    real dual and its weak topology. The same interface applies
    to E' and D', preserving the different source topologies. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets reals.
From Federer Require Import Hom RealNormUP OpenFamilyTopologyUP ContinuousRealDualSubspace
  LinearSubspaceRepresentationUP LinearSubspaceRepresentationSealed
  WeakEvaluationTopologyUP WeakEvaluationTopologySealed NormOpenTopology.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.

Section ContinuousDual.
Variable R:realType.
Variable E:lmodType R.
Variable O:set (set E).
Hypothesis hO:is_open_family_topology O.

(** Source for [continuous_real_dual_space]: the vector space
    of all continuous real linear functions, E' or D' according
    to its source, Federer 4.1.1, pp. 344–345. *)
Definition continuous_real_dual_space:lmodType R:=
  @LinearSubspaceRepresentation.space R (Hom E R^o) (continuous_real_dual_subspace hO).

(** Source for [continuous_real_dual_evaluation]: the actual
    real linear functional represented by a dual member,
    Federer 4.1.1, pp. 344–345. *)
Definition continuous_real_dual_evaluation:Hom continuous_real_dual_space (Hom E R^o):=
  @LinearSubspaceRepresentation.inclusion R (Hom E R^o) (continuous_real_dual_subspace hO).

(** Source for [continuous_real_dual_model_laws]: the model
    represents exactly all continuous real linear functionals,
    Federer 4.1.1, pp. 344–345. *)
Lemma continuous_real_dual_model_laws:
  is_linear_subspace_representation (continuous_real_dual_subspace hO)
    continuous_real_dual_evaluation.
Proof. exact:LinearSubspaceRepresentation.laws. Qed.

(** Source for [continuous_real_dual_member_continuous]: every
    represented dual functional is continuous for the original
    source topology, Federer 4.1.1, pp. 344–345. *)
Lemma continuous_real_dual_member_continuous T:
  open_family_continuous O (norm_open_family (@scalar_absolute_value_norm R))
    (continuous_real_dual_evaluation T).
Proof. exact (@subspace_representation_member R (Hom E R^o) continuous_real_dual_space
  (continuous_real_dual_subspace hO) continuous_real_dual_evaluation
  continuous_real_dual_model_laws T). Qed.

(** Source for [continuous_real_dual_represents]: every continuous
    real linear functional has a representative, Federer 4.1.1,
    pp. 344–345. This is proved image fullness, not an axiom. *)
Theorem continuous_real_dual_represents (L:Hom E R^o):
  open_family_continuous O (norm_open_family (@scalar_absolute_value_norm R)) L ->
  exists T,continuous_real_dual_evaluation T=L.
Proof. move=>hL; exact (@subspace_representation_full R (Hom E R^o) continuous_real_dual_space
  (continuous_real_dual_subspace hO) continuous_real_dual_evaluation
  continuous_real_dual_model_laws L hL). Qed.

(** Source for [continuous_real_dual_weak_opens]: the weak
    topology generated by the real evaluations T(phi), Federer
    4.1.1, pp. 344–345. *)
Definition continuous_real_dual_weak_opens:set (set continuous_real_dual_space):=
  @WeakEvaluationTopology.opens R E continuous_real_dual_space
    (fun T f=>continuous_real_dual_evaluation T f).

(** Source for [continuous_real_dual_weak_laws]: maps into the
    weak dual are continuous exactly when all evaluations are,
    supporting Federer's generating strips, 4.1.1, pp. 344–345. *)
Theorem continuous_real_dual_weak_laws:
  is_weak_evaluation_topology (fun T f=>continuous_real_dual_evaluation T f)
    continuous_real_dual_weak_opens.
Proof. exact:WeakEvaluationTopology.laws. Qed.
End ContinuousDual.
