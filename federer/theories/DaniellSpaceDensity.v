Section Density.
Variable R : realType.
Variable X : Type.
Variable L : set (X -> R).
Hypothesis hL : is_function_lattice L.
Variable A : (X -> R) -> R.
Hypothesis hA : is_daniell_integral L A.

(** Source for [lattice_nonnegative_combination]: nonnegative linear
    combinations of members of L belong to L, by the addition and
    scaling clauses of Federer 2.5.1, p. 91; supporting the density
    argument of 2.5.19, p. 113. *)
Lemma lattice_nonnegative_combination (I : Type) (s : seq I) (c : I -> R) (f : I -> X -> R) :
  (exists g, L g) -> (forall i, 0 <= c i) -> (forall i, L (f i)) ->
  L (fun x => \sum_(i <- s) c i * f i x).
Proof.
move=> [g hg] hc hf; elim: s=> [|i s ih].
- have -> : (fun x : X => \sum_(i <- [::]) c i * f i x) = (fun _ => 0).
    by apply: funext=> x; rewrite big_nil.
  exact: (function_lattice_zero hL hg).
- have -> : (fun x : X => \sum_(j <- i :: s) c j * f j x)
    = (fun x => c i * f i x + \sum_(j <- s) c j * f j x).
    by apply: funext=> x; rewrite big_cons.
  apply: (function_lattice_add hL _ ih); exact: (function_lattice_scale hL (hc i) (hf i)).
Qed.

(** Source for [daniell_nonnegative_combination]: the value of a Daniell
    integral on a nonnegative combination of members of L, by the first
    two hypotheses of Federer 2.5.5, p. 96; supporting 2.5.19, p. 113. *)
Lemma daniell_nonnegative_combination (I : Type) (s : seq I) (c : I -> R) (f : I -> X -> R) :
  (exists g, L g) -> (forall i, 0 <= c i) -> (forall i, L (f i)) ->
  A (fun x => \sum_(i <- s) c i * f i x) = \sum_(i <- s) c i * A (f i).
Proof.
move=> hne hc hf; elim: s=> [|i s ih].
- have -> : (fun x : X => \sum_(i <- [::]) c i * f i x) = (fun _ => 0).
    by apply: funext=> x; rewrite big_nil.
  by rewrite big_nil; case: hne=> g hg; exact: (daniell_integral_zero hA hg).
- have -> : (fun x : X => \sum_(j <- i :: s) c j * f j x)
    = (fun x => c i * f i x + \sum_(j <- s) c j * f j x).
    by apply: funext=> x; rewrite big_cons.
  rewrite (daniell_integral_add hA (function_lattice_scale hL (hc i) (hf i))
    (lattice_nonnegative_combination s hne hc hf)).
  by rewrite (daniell_integral_scale hA (hc i) (hf i)) ih big_cons.
Qed.

(** Source for [daniell_vanishing_combination]: a linear relation
    sum_i c_i f_i = 0 on X among members of L forces
    sum_i c_i mu(f_i) = 0, supporting Federer 2.5.19, p. 113; the
    coefficients are split into positive and negative parts, since L is
    only closed under nonnegative multiples. *)
Lemma daniell_vanishing_combination (I : Type) (s : seq I) (c : I -> R) (f : I -> X -> R) :
  (forall i, L (f i)) -> (forall x, \sum_(i <- s) c i * f i x = 0) ->
  \sum_(i <- s) c i * A (f i) = 0.
Proof.
move=> hf h0.
case: s h0=> [|i0 s] h0; first by rewrite big_nil.
have hne : exists g, L g by exists (f i0).
pose cp := fun i => Order.max (c i) 0.
pose cm := fun i => Order.max (- c i) 0.
have hcp : forall i, 0 <= cp i by move=> i; rewrite /cp le_max lexx orbT.
have hcm : forall i, 0 <= cm i by move=> i; rewrite /cm le_max lexx orbT.
have hsplit : forall i, c i = cp i - cm i.
  move=> i; rewrite /cp /cm !maxEle.
  by case: (lerP (c i) 0)=> h1; case: (lerP (- c i) 0)=> h2 /=; lra.
have hfun : (fun x => \sum_(i <- i0 :: s) cp i * f i x)
    = (fun x => \sum_(i <- i0 :: s) cm i * f i x).
  apply: funext=> x; have := h0 x.
  rewrite (eq_bigr (fun i => cp i * f i x - cm i * f i x)); last first.
    by move=> i _; rewrite (hsplit i) mulrBl.
  by rewrite sumrB=> /eqP; rewrite subr_eq0=> /eqP.
have hAp := daniell_nonnegative_combination (i0 :: s) hne hcp hf.
have hAm := daniell_nonnegative_combination (i0 :: s) hne hcm hf.
rewrite hfun in hAp.
have heq : \sum_(i <- i0 :: s) cp i * A (f i) = \sum_(i <- i0 :: s) cm i * A (f i).
  by rewrite -hAp -hAm.
rewrite (eq_bigr (fun i => cp i * A (f i) - cm i * A (f i))); last first.
  by move=> i _; rewrite (hsplit i) mulrBl.
by rewrite sumrB heq subrr.
Qed.

(** Source for [point_evaluation_interpolation]: finitely many values of
    a Daniell integral on members of L are realised by a finite linear
    combination of point evaluations, the finite dimensional core of the
    density statement of Federer 2.5.19, p. 113. *)
Theorem point_evaluation_interpolation (n : nat) (f : 'I_n -> X -> R) :
  (forall i, L (f i)) ->
  exists s : seq (R * X), forall i, \sum_(p <- s) p.1 * f i p.2 = A (f i).
Proof.
case: n f=> [|n] f hf; first by exists [::]=> -[i hi]; exfalso; move: hi; rewrite ltn0.
pose v : X -> 'rV[R]_n.+1 := fun x => \row_i f i x.
pose m : 'rV[R]_n.+1 := \row_i A (f i).
pose Pb := fun k => `[< exists (r : nat) (M : 'M[R]_(r, n.+1)),
  (forall j, exists x, row j M = v x) /\ \rank M = k >].
have exP : exists k, Pb k.
  exists 0%N; apply/asboolP; exists 0%N, (0 : 'M[R]_(0, n.+1)).
  split; first by move=> j; exfalso; case: j=> j hj; move: hj; rewrite ltn0.
  by apply/eqP; rewrite -leqn0 rank_leq_row.
have ubP : forall k, Pb k -> (k <= n.+1)%N.
  by move=> k /asboolP [r [M [_ <-]]]; exact: rank_leq_col.
have [kmax hkmax hmax] := ex_maxnP exP ubP.
move/asboolP: hkmax=> [r [M [hrows hrank]]].
have hsub : forall x, (v x <= M)%MS.
  move=> x.
  have hrows' : forall j : 'I_(1 + r), exists y, row j (col_mx (v x) M) = v y.
    move=> j; case: (split_ordP j)=> [j0 -> | j1 ->].
    - by exists x; rewrite rowKu (ord1 j0); apply/rowP=> i; rewrite !mxE.
    - by rewrite rowKd; exact: hrows j1.
  have hP : Pb (\rank (col_mx (v x) M)).
    by apply/asboolP; exists (1 + r)%N, (col_mx (v x) M).
  have hle := hmax _ hP.
  have hMsub : (M <= col_mx (v x) M)%MS by rewrite -(addsmxE (v x) M); exact: addsmxSr.
  have [hr1 hr2] := mxrank_leqif_sup hMsub.
  have heq : (col_mx (v x) M <= M)%MS by rewrite -hr2 eqn_leq hr1 hrank hle.
  have hvsub : (v x <= col_mx (v x) M)%MS by rewrite -(addsmxE (v x) M); exact: addsmxSl.
  exact: submx_trans hvsub heq.
pose pt := fun j : 'I_r => sval (cid (hrows j)).
have hM : forall j i, M j i = f i (pt j).
  move=> j i; have h := svalP (cid (hrows j)).
  by move/(congr1 (fun N : 'rV[R]_n.+1 => N 0 i)): h; rewrite !mxE.
case: (boolP (m <= M)%MS)=> hmM.
- have [D hD] := submxP hmM.
  exists [seq (D 0 j, pt j) | j <- index_enum 'I_r]=> i.
  rewrite big_map.
  have := congr1 (fun N : 'rV[R]_n.+1 => N 0 i) hD.
  rewrite !mxE=> ->.
  by apply: eq_bigr=> j _; rewrite /= hM.
- exfalso.
  have hnz : m *m cokermx M != 0 by move: hmM; rewrite submxE.
  have [c hc] : exists c, (m *m cokermx M) 0 c != 0.
    apply: contrapT=> hno; move/negP: hnz; apply; apply/eqP/matrixP=> i j.
    rewrite (ord1 i) [RHS]mxE; apply/eqP; apply: contrapT=> hij; apply: hno.
    by exists j; apply/negP.
  pose co := fun i : 'I_n.+1 => cokermx M i c.
  have hrel : forall x, \sum_i co i * f i x = 0.
    move=> x.
    have h0 : v x *m cokermx M = 0 by apply/eqP; rewrite -submxE; exact: hsub.
    have := congr1 (fun N : 'rV[R]_n.+1 => N 0 c) h0; rewrite !mxE=> h.
    by apply: (eq_trans _ h); apply: eq_bigr=> i _; rewrite mxE mulrC.
  have hzero := daniell_vanishing_combination hf hrel.
  move/negP: hc; apply; apply/eqP; rewrite mxE.
  by apply: (eq_trans _ hzero); apply: eq_bigr=> i _; rewrite mxE mulrC.
Qed.

(** Source for [point_evaluation_span_dense]: the vector space generated
    by the image of delta is dense in L* for the weak topology, Federer
    2.5.19, p. 113. *)
Theorem point_evaluation_span_dense :
  closure (@point_evaluation_span R X : set (daniell_weak_space L)) A.
Proof.
pose S := fun fs : seq (X -> R) =>
  [set T : (X -> R) -> R | point_evaluation_span T /\ forall g, g \in fs -> T g = A g].
pose D := fun fs : seq (X -> R) => forall g, g \in fs -> L g.
have hS : forall fs, D fs -> S fs !=set0.
  move=> fs hfs.
  pose f := fun i : 'I_(size fs) => nth (fun _ : X => 0) fs i.
  have hf : forall i, L (f i) by move=> i; apply: hfs; exact: mem_nth.
  have [s hs] := point_evaluation_interpolation hf.
  exists (fun g => \sum_(p <- s) p.1 * g p.2); split; first by exists s.
  move=> g hg; have hlt : (index g fs < size fs)%N by rewrite index_mem.
  by have := hs (Ordinal hlt); rewrite /f /= nth_index.
have hF : Filter (filter_from D S).
  apply: filter_from_filter; first by exists [::].
  move=> fs gs hfs hgs; exists (fs ++ gs).
  - by move=> g; rewrite mem_cat=> /orP[/hfs|/hgs].
  - move=> T [hT hv]; split; split=> // g hg; apply: hv.
    + by rewrite mem_cat hg.
    + by rewrite mem_cat hg orbT.
have hP : ProperFilter (filter_from D S) by apply: filter_from_proper=> // fs; exact: hS.
have hcv : filter_from D S --> (A : daniell_weak_space L).
  apply/(daniell_weak_cvg L A hF)=> g hg U hU.
  exists [:: g]; first by move=> g'; rewrite inE=> /eqP ->.
  move=> T [_ hv]; rewrite /= (hv g (mem_head g [::])).
  exact: nbhs_singleton hU.
rewrite closureEcvg; exists (filter_from D S)=> //; split=> // B hB.
apply: filterS hB _; exists [::]; first by move=> g; rewrite in_nil.
by move=> T [hT _]; exact: hT.
Qed.

End Density.
