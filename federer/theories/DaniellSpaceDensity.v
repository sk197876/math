(** Federer (1969), 2.5.19, p. 113: the vector space generated by the image
    of delta is dense in L*. The statement is reduced to an interpolation
    lemma: for finitely many members f_1, ..., f_n of L and a Daniell
    integral mu on L there are finitely many points x_j and coefficients c_j
    with sum_j c_j f_i(x_j) = mu(f_i) for every i. The lemma follows from a
    finite dimensional rank argument: the vector (mu(f_i))_i lies in the row
    space of the vectors (f_i(x))_i, since otherwise some linear relation
    sum_i c_i f_i = 0 on X would give sum_i c_i mu(f_i) <> 0, contradicting
    the additivity and positive homogeneity of mu on L applied to the
    positive and negative parts of the coefficients. Row spaces of MathComp
    serve only as a device inside that proof; the statements are free of
    them. *)
