(** Federer (1969), 4.1.1, pp. 344–345; Menne (2016),
    Definition 2.13, p. 996: the compatible seminorms form a
    directed family, so the already proved seminorm-topology
    existence theorem constructs the locally convex topology. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets reals lra.
From Federer Require Import Hom RealNormUP DirectedSeminormFamilyUP
  InductiveLimitSeminormFamilyUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import Order.TTheory GRing.Theory Num.Theory.
Local Open Scope ring_scope.

Section InductiveSeminormFamily.
Variable R:realType.
Variable E:lmodType R.
Variable J:Type.
Variable W:J->lmodType R.
Variable I:J->Type.
Variable p:forall j,I j->W j->R.
Variable inc:forall j,Hom (W j) E.
Hypothesis hp:forall j,is_directed_seminorm_family (@p j).

(** Source for [zero_step_compatible_seminorm]: the zero
    seminorm belongs to the family, including empty or zero
    steps, supporting Menne (2016), Definition 2.13, p. 996. *)
Lemma zero_step_compatible_seminorm :
  is_step_compatible_seminorm p inc (fun _=>0).
Proof.
split.
- constructor; [by move=>x|by move=>c x; rewrite mulr0|by move=>x y; rewrite addr0].
- move=>j; have [i _]:=directed_seminorm_nonempty (hp j).
  exists i,0; split; first exact:lexx.
  by move=>w; rewrite mul0r.
Qed.

(** Source for [sum_step_compatible_seminorm]: sums of two
    compatible seminorms are compatible; this supplies a common
    dominating seminorm, supporting Menne (2016), p. 996. *)
Lemma sum_step_compatible_seminorm (q r:E->R) :
  is_step_compatible_seminorm p inc q ->
  is_step_compatible_seminorm p inc r ->
  is_step_compatible_seminorm p inc (fun x=>q x+r x).
Proof.
move=>[hq hqB] [hr hrB]; split.
- constructor.
  + move=>x; exact:addr_ge0 (real_seminorm_nonnegative hq x) (real_seminorm_nonnegative hr x).
  + move=>c x; by rewrite (real_seminorm_scale hq) (real_seminorm_scale hr) mulrDr.
  + move=>x y; have h:=lerD (real_seminorm_triangle hq x y) (real_seminorm_triangle hr x y).
    by rewrite addrACA in h.
- move=>j; have [i [C [hC hqC]]]:=hqB j.
  have [k [D [hD hrD]]]:=hrB j.
  have [l hl]:=directed_seminorm_upper_pair (hp j) i k.
  exists l,(C+D); split; first exact:addr_ge0 hC hD.
  move=>w; have h1:=hqC w; have h2:=hrD w.
  have [h3 h4]:=hl w; nra.
Qed.

(** Source for [inductive_compatible_seminorms_directed]: the
    topology generated by all compatible seminorms exists and
    is locally convex, supporting Menne (2016), Definition 2.13,
    p. 996, in comparison with Federer 4.1.1, p. 344. *)
Theorem inductive_compatible_seminorms_directed :
  is_directed_seminorm_family
    (fun q:@compatible_seminorm_index R E J W I p inc=>compatible_seminorm_value q).
Proof.
constructor.
- exists (@CompatibleSeminorm R E J W I p inc (fun _=>0) zero_step_compatible_seminorm); by [].
- move=>q; exact:(compatible_seminorm_laws q).1.
- move=>q r.
  exists (@CompatibleSeminorm R E J W I p inc
    (fun x=>compatible_seminorm_value q x+compatible_seminorm_value r x)
    (sum_step_compatible_seminorm (compatible_seminorm_laws q) (compatible_seminorm_laws r))).
  move=>x; split; [rewrite lerDl|rewrite lerDr];
    exact:real_seminorm_nonnegative (compatible_seminorm_laws _).1 x.
Qed.
End InductiveSeminormFamily.
