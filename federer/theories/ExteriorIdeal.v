(** Source for [mV_direct_sum]: Federer (1969), 1.3.1, p. 13, homogeneous
    ideal and component-quotient displays. In words: The square-generated
    ideal is homogeneous and begins in degree two, so the quotient inherits
    its grading and each component is the corresponding component quotient.
    Formalises the indicated part of the passage under the hypotheses in the
    statement below. *)
Lemma mV_direct_sum x : mV x ->
  (forall n, mV (tensor_degree n x)) /\
  (exists N, x = \sum_(i < N | (2 <= i)%N) tensor_degree i x).
Proof.
move=> hx; split; first by move=> n; exact: mV_homogeneous hx.
have [N hN] := tensor_degree_finite x; exists N.
rewrite {1}hN [RHS]big_mkcond; apply: eq_bigr => i _.
case: ifP => //; move: (val i) => [|[|n]] // _.
- exact: mV_degree_zero hx.
- exact: mV_degree_one hx.
Qed.
