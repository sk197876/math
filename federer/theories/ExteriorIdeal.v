Lemma exterior_relation_mulr x y :
  exterior_relation x -> exterior_relation (tensor_product x y).
Proof.
move=> hx; elim/tensor_word_induction: y => [|y y' hy hy'|a y hy|s].
- by rewrite (bil0r tb); exact: er_zero.
- rewrite (bilDr tb); exact: er_add hy hy'.
- rewrite (bilZr tb); exact: er_scale hy.
exact: exterior_relation_suffix hx.
Qed.

(** Source for [mV]: Federer (1969), 1.3.1, p. 13, opening paragraph
    defining the ideal mV. In words: The two-sided ideal generated by all x
    tensor x is homogeneous, with no degree-zero or degree-one component.
    Definition or construction used to formalise this passage. *)
Definition mV : two_sided_ideal (tensor_algebra V) :=
  @TwoSidedIdeal K (tensor_algebra V) exterior_subspace
    exterior_relation_mull exterior_relation_mulr.

(** Source for [mV_square]: Federer (1969), 1.3.1, p. 13, opening paragraph
    defining the ideal mV. In words: The two-sided ideal generated by all x
    tensor x is homogeneous, with no degree-zero or degree-one component.
    Formalises the indicated part of the passage under the hypotheses in the
    statement below. *)
Lemma mV_square v : mV (tensor_product (tensor_generator v) (tensor_generator v)).
Proof. rewrite tensor_product_words; exact: (er_square [::] [::] v). Qed.

(** Federer 1.3.1, third paragraph: the displayed polarisation identity in
    the tensor algebra, before passage to the quotient. *)
(** Source for [tensor_square_polarisation]: Federer (1969), 1.3.1, p. 13,
    polarisation identity and the concluding signed-interchange formula. In
    words: Expanding the square of x+y gives y wedge x = -x wedge y;
    interchanging blocks of p and q vectors gives the sign (-1)^(pq), hence
    graded anticommutativity. Formalises the indicated part of the passage
    under the hypotheses in the statement below. *)
Lemma tensor_square_polarisation (v w : V) :
  tensor_product (tensor_generator v) (tensor_generator w) +
    tensor_product (tensor_generator w) (tensor_generator v) =
  tensor_product (tensor_generator (v + w)) (tensor_generator (v + w)) -
    tensor_product (tensor_generator v) (tensor_generator v) -
    tensor_product (tensor_generator w) (tensor_generator w).
Proof.
rewrite linearD (bilDl tb) !(bilDr tb).
set a := tensor_product (tensor_generator v) (tensor_generator v).
set b := tensor_product (tensor_generator v) (tensor_generator w).
set c := tensor_product (tensor_generator w) (tensor_generator v).
set d := tensor_product (tensor_generator w) (tensor_generator w).
by rewrite -[a + b + (c + d)]addrA [b + (c + d)]addrA
  [a + (b + c + d)]addrC addrK addrK.
Qed.

(** Source for [mV_symmetric]: Federer (1969), 1.3.1, p. 13, polarisation
    identity and the concluding signed-interchange formula. In words:
    Expanding the square of x+y gives y wedge x = -x wedge y; interchanging
    blocks of p and q vectors gives the sign (-1)^(pq), hence graded
    anticommutativity. Formalises the indicated part of the passage under
    the hypotheses in the statement below. *)
Lemma mV_symmetric (v w : V) :
  mV (tensor_product (tensor_generator v) (tensor_generator w) +
    tensor_product (tensor_generator w) (tensor_generator v)).
Proof.
rewrite tensor_square_polarisation.
exact: subspace_sub (subspace_sub (mV_square (v + w)) (mV_square v)) (mV_square w).
Qed.

(** Source for [mV_minimal]: Federer (1969), 1.3.1, p. 13, opening paragraph
    defining the ideal mV. In words: The two-sided ideal generated by all x
    tensor x is homogeneous, with no degree-zero or degree-one component.
    Formalises the indicated part of the passage under the hypotheses in the
    statement below. *)
Lemma mV_minimal (I : two_sided_ideal (tensor_algebra V)) :
  (forall v, I (tensor_product (tensor_generator v) (tensor_generator v))) ->
  forall x, mV x -> I x.
Proof.
move=> hi x; elim=> [|u v hu ihu hv ihv|a u hu ihu|s t v].
- exact: subspace_zero.
- exact: subspace_add ihu ihv.
- exact: subspace_scale ihu.
have h := @ideal_mull K (tensor_algebra V) I (d s) _ (hi v).
have h' := @ideal_mulr K (tensor_algebra V) I _ (d t) h.
move: h'; change (I (tensor_product
  (tensor_product (d s) (tensor_product (tensor_generator v) (tensor_generator v)))
  (d t)) -> I (d (s ++ v :: v :: t))).
by rewrite !tensor_product_words -catA.
Qed.

(** Federer 1.3.1, first paragraph: mV is homogeneous and has no components
    of degree zero or one. Together with finite reconstruction these are
    precisely the stated direct-sum decomposition starting at degree two. *)
(** Source for [mV_homogeneous]: Federer (1969), 1.3.1, p. 13, homogeneous
    ideal and component-quotient displays. In words: The square-generated
    ideal is homogeneous and begins in degree two, so the quotient inherits
    its grading and each component is the corresponding component quotient.
    Formalises the indicated part of the passage under the hypotheses in the
    statement below. *)
Lemma mV_homogeneous n x : mV x -> mV (tensor_degree n x).
Proof.
elim=> [|u v hu ihu hv ihv|a u hu ihu|s t v].
- by rewrite linear0; exact: er_zero.
- rewrite linearD; exact: er_add ihu ihv.
- rewrite linearZ; exact: er_scale ihu.
rewrite tensor_degree_word; case: ifP => _; [exact: er_square | exact: er_zero].
Qed.

(** Source for [mV_degree_zero]: Federer (1969), 1.3.1, p. 13, homogeneous
    ideal and component-quotient displays. In words: The square-generated
    ideal is homogeneous and begins in degree two, so the quotient inherits
    its grading and each component is the corresponding component quotient.
    Formalises the indicated part of the passage under the hypotheses in the
    statement below. *)
Lemma mV_degree_zero x : mV x -> tensor_degree 0 x = 0.
Proof.
elim=> [|u v hu ihu hv ihv|a u hu ihu|s t v].
- exact: linear0.
- rewrite linearD; change (tensor_degree 0 u + tensor_degree 0 v = 0).
  by rewrite ihu ihv add0r.
- rewrite linearZ; change (a *: tensor_degree 0 u = 0).
  by rewrite ihu scaler0.
by rewrite tensor_degree_word size_cat /= !addnS.
Qed.

(** Source for [mV_degree_one]: Federer (1969), 1.3.1, p. 13, homogeneous
    ideal and component-quotient displays. In words: The square-generated
