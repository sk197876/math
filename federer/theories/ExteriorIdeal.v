(** Source for [exterior_relation_mull]: Federer (1969), 1.3.1, p. 13,
    opening paragraph defining the ideal mV. In words: The two-sided ideal
    generated by all x tensor x is homogeneous, with no degree-zero or
    degree-one component. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma exterior_relation_mull x y :
  exterior_relation y -> exterior_relation (tensor_product x y).
Proof.
move=> hy; elim/tensor_word_induction: x => [|x x' hx hx'|a x hx|s].
- by rewrite (bil0l tb); exact: er_zero.
- rewrite (bilDl tb); exact: er_add hx hx'.
- rewrite (bilZl tb); exact: er_scale hx.
exact: exterior_relation_prefix hy.
Qed.

(** Source for [exterior_relation_mulr]: Federer (1969), 1.3.1, p. 13,
    opening paragraph defining the ideal mV. In words: The two-sided ideal
