(** Federer 1.3.1, first paragraph. The ideal mV is the linear span of
    products containing adjacent equal generators. Its minimality below
    identifies it with Federer's two-sided ideal generated by x tensor x. *)
(** Source for [exterior_relation]: Federer (1969), 1.3.1, p. 13, opening
    paragraph defining the ideal mV. In words: The two-sided ideal generated
    by all x tensor x is homogeneous, with no degree-zero or degree-one
    component. Definition or construction used to formalise this passage. *)
Inductive exterior_relation : T -> Prop :=
| er_zero : exterior_relation 0
| er_add x y : exterior_relation x -> exterior_relation y -> exterior_relation (x + y)
| er_scale a x : exterior_relation x -> exterior_relation (a *: x)
| er_square s t v : exterior_relation (d (s ++ v :: v :: t)).

(** Source for [exterior_subspace]: Federer (1969), 1.3.1, p. 13, opening
    paragraph defining the ideal mV. In words: The two-sided ideal generated
    by all x tensor x is homogeneous, with no degree-zero or degree-one
    component. Definition or construction used to formalise this passage. *)
Definition exterior_subspace : subspace T :=
  @Subspace K T exterior_relation er_zero er_add er_scale.

(** Source for [exterior_relation_prefix]: Federer (1969), 1.3.1, p. 13,
    opening paragraph defining the ideal mV. In words: The two-sided ideal
    generated by all x tensor x is homogeneous, with no degree-zero or
    degree-one component. Supporting lemma for this passage; not separately
    stated in the book. *)
Lemma exterior_relation_prefix s x :
  exterior_relation x -> exterior_relation (tensor_product (d s) x).
Proof.
elim=> [|u w hu ihu hw ihw|a u hu ihu|u t v].
- by rewrite (bil0r tb); exact: er_zero.
- rewrite (bilDr tb); exact: er_add ihu ihw.
- rewrite (bilZr tb); exact: er_scale ihu.
by rewrite tensor_product_words catA; exact: er_square.
Qed.

