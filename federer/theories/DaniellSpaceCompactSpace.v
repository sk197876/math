(** Federer (1969), 2.5.19, p. 113, third paragraph: if X is a compact
    Hausdorff space, the weak topology of K(X)* coincides with the weak
    topology of 2.5.12(2), p. 103, of K(X)* as the conjugate space of K(X)
    with the norm nu(f) = sup im |f|. Two facts are proved. First, for every
    lattice L the open sets of the weak topology are the sets containing
    with each of their points A a set {B : |B(f) - A(f)| < e for f in F}
    with F a finite subset of L and e > 0; these sets and the strips {B : a
    < B(f) < b} of 2.5.12(2) generate the same topology. Second, for compact
    Hausdorff X the Daniell integrals on K(X) are exactly the linear
    functionals on K(X) which are bounded with respect to nu; the bound is
    stated through pointwise majorants of |f| so that no supremum needs to
    be chosen. *)
