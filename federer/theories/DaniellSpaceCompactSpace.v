Section WeakBoxes.
Variable R : realType.
Variable X : Type.
Variable L : set (X -> R).

(** Source for [daniell_weak_box]: the basic neighbourhood
    {B : |B(f) - A(f)| < e for f in F} of the weak topology, Federer
    2.5.19, p. 113, compared with 2.5.12(2), p. 103. *)
Definition daniell_weak_box (A : (X -> R) -> R) (fs : seq (X -> R)) (e : R) :
    set (daniell_weak_space L) :=
  [set B | forall f, f \in fs -> `|B f - A f| < e].

(** Source for [daniell_weak_box_nbhs]: a box around A with members of
    L is a neighbourhood of A in the weak topology, Federer 2.5.19,
    p. 113. *)
Lemma daniell_weak_box_nbhs (A : (X -> R) -> R) (fs : seq (X -> R)) (e : R) :
  0 < e -> (forall f, f \in fs -> L f) ->
  nbhs (A : daniell_weak_space L) (daniell_weak_box A fs e).
Proof.
move=> he; have hF := @nbhs_filter [the topologicalType of daniell_weak_space L] A.
elim: fs=> [|f fs ih] hfs.
- by apply: (filterS _ (@filterT _ _ hF))=> B _ f; rewrite in_nil.
- have hf : L f by apply: hfs; exact: mem_head.
  have h1 : nbhs (A : daniell_weak_space L) [set B : daniell_weak_space L | `|B f - A f| < e].
    exact (@daniell_weak_evaluation_continuous R X L f hf A _ (real_ball_nbhs (A f) he)).
  have h2 := ih (fun g hg => hfs g (@mem_behead _ (f :: fs) g hg)).
  apply: (filterS _ (@filterI _ _ hF _ _ h1 h2))=> B [hB1 hB2] g.
  by rewrite in_cons=> /orP[/eqP ->|hg]; [exact: hB1 | exact: hB2 hg].
Qed.

(** Source for [daniell_weak_open_iff]: the open sets of the weak
    topology of Federer 2.5.19, p. 113, are the sets containing a box
    around each of their points; hence the weak topology is generated by
    the strips {B : a < B(f) < b} for f in L, as the weak topology of
    2.5.12(2), p. 103. *)
Theorem daniell_weak_open_iff (U : set (daniell_weak_space L)) :
  open U <-> forall A, U A -> exists fs e, 0 < e /\ (forall f, f \in fs -> L f) /\
    daniell_weak_box A fs e `<=` U.
Proof.
split=> hU.
- move=> A hA; apply: contrapT=> hno.
  pose D := [set p : seq (X -> R) * R | (forall f, f \in p.1 -> L f) /\ 0 < p.2].
  pose S := fun p : seq (X -> R) * R => daniell_weak_box A p.1 p.2 `&` ~` U.
  have hS : forall p, D p -> S p !=set0.
    move=> [fs e] [hfs he]; apply: contrapT=> hn; apply: hno; exists fs, e.
    split=> //; split=> // B hB; apply: contrapT=> hBU; apply: hn; by exists B.
  have hFf : Filter (filter_from D S).
    apply: filter_from_filter; first by exists ([::], 1); split=> //; exact: ltr01.
    move=> [fs e] [gs e'] [hfs he] [hgs he']; exists (fs ++ gs, Order.min e e').
    + split; last by rewrite lt_min he he'.
      by move=> f; rewrite mem_cat=> /orP[/hfs|/hgs].
    + move=> B [hB hBU]; split; split=> //= f hf.
      * apply: lt_le_trans (hB f _) _; first by rewrite mem_cat hf.
        by rewrite ge_min lexx.
      * apply: lt_le_trans (hB f _) _; first by rewrite mem_cat hf orbT.
        by rewrite ge_min lexx orbT.
  have hP : ProperFilter (filter_from D S) by apply: filter_from_proper=> // p; exact: hS.
  have hcv : filter_from D S --> (A : daniell_weak_space L).
    apply/(daniell_weak_cvg L A hFf)=> g hg V hV.
    move/nbhs_ballP: hV=> [e he heV].
    exists ([:: g], e); first by split=> //= f; rewrite inE=> /eqP ->.
    move=> B [hB _]; apply: heV.
    by rewrite /ball /= distrC; exact: hB g (mem_head g [::]).
  have hUn : nbhs (A : daniell_weak_space L) U by apply: open_nbhs_nbhs; split.
  have h1 : filter_from D S U := hcv _ hUn.
  have h2 : filter_from D S (~` U).
    by exists ([::], 1); [split=> //; exact: ltr01 | move=> B [_ hB]].
  have [B [hB1 hB2]] := @filter_ex _ _ hP _ (@filterI _ _ hFf _ _ h1 h2).
  exact: hB2 hB1.
- rewrite openE=> A hA; have [fs [e [he [hfs hsub]]]] := hU A hA.
  exact (@filterS _ _ (@nbhs_filter [the topologicalType of daniell_weak_space L] A) _ _ hsub (daniell_weak_box_nbhs A he hfs)).
Qed.

End WeakBoxes.

Section CompactSpace.
Variable R : realType.
Variable X : topologicalType.
Hypothesis hh : hausdorff_space X.
Hypothesis hc : compact (@setT X).
Local Notation K := (@compactly_supported_continuous_functions R X).
(** Source for [hL]: the lattice laws of K(X), Federer 2.5.13, p. 106,
    used throughout 2.5.19, p. 113. *)
Let hL : is_function_lattice K := @compactly_supported_continuous_functions_lattice R X.

(** Source for [compact_space_constant_one]: the constant function 1
    belongs to K(X) for compact X, Federer 2.5.19, p. 113. *)
Lemma compact_space_constant_one : compactly_supported_continuous_functions (fun _ : X => (1 : R)).
Proof.
split; first by move=> x; exact: cvg_cst.
exact: (subclosed_compact (@real_function_support_closed R X _) hc (@subsetT _ _)).
Qed.

(** Source for [is_sup_norm_bounded]: boundedness with respect to the
    norm nu(f) = sup im |f| of Federer 2.5.19, p. 113, expressed through
    pointwise majorants: |A(f)| <= C c whenever |f| <= c on X. *)
Definition is_sup_norm_bounded (A : (X -> R) -> R) : Prop :=
  exists C, 0 <= C /\ forall f, compactly_supported_continuous_functions f ->
    forall c, 0 <= c -> (forall x, `|f x| <= c) -> `|A f| <= C * c.

(** Source for [daniell_sup_norm_bounded]: a Daniell integral on K(X) is
    nu bounded for compact X, with constant 2 [mu^+(1) + mu^-(1)], by the
    variation formulas of Federer 2.5.5, p. 96; supporting 2.5.19,
    p. 113. *)
Lemma daniell_sup_norm_bounded (A : (X -> R) -> R) :
  is_daniell_integral K A -> is_sup_norm_bounded A.
Proof.
move=> hA.
have hP := daniell_positive_variation_specification hL hA.
have hQ := daniell_negative_variation_specification hL hA.
pose P := daniell_positive_variation hL hA.
pose Q := daniell_negative_variation hL hA.
have hPm := positive_variation_monotone_daniell hL hA hP.
have hQm := negative_variation_monotone_daniell hL hA hQ.
have h1 : positive_function_lattice K (fun _ : X => (1 : R)).
  by split; [exact: compact_space_constant_one | move=> x; exact: ler01].
have hP1 := daniell_positive_variation_nonnegative hL hA hP h1.
have hQ1 := daniell_positive_variation_nonnegative hL (daniell_integral_negate hL hA) hQ h1.
have hpos : forall u c, positive_function_lattice K u -> 0 <= c -> (forall x, u x <= c) ->
    `|A u| <= c * (P (fun _ => 1) + Q (fun _ => 1)).
  move=> u c hu hc0 huc.
  have hcu : positive_function_lattice K (fun x : X => c * (fun _ : X => (1 : R)) x).
    split; first exact: (function_lattice_scale hL hc0 compact_space_constant_one).
    by move=> x; rewrite mulr1.
  have hle : function_le u (fun x : X => c * (fun _ : X => (1 : R)) x) by move=> x; rewrite mulr1.
  have hPu := daniell_positive_variation_monotone hP hu hcu hle.
  have hQu := daniell_positive_variation_monotone hQ hu hcu hle.
  rewrite (monotone_daniell_integral_scale hPm hc0 h1) in hPu.
  rewrite (monotone_daniell_integral_scale hQm hc0 h1) in hQu.
  have hid := daniell_positive_negative_identity hL hA hP hQ hu.
  have hPu0 := daniell_positive_variation_nonnegative hL hA hP hu.
  have hQu0 := daniell_positive_variation_nonnegative hL (daniell_integral_negate hL hA) hQ hu.
  rewrite hid mulrDr; apply: le_trans (ler_normB _ _) _.
  rewrite !ger0_norm //; exact: lerD hPu hQu.
exists (2 * (P (fun _ => 1) + Q (fun _ => 1))); split; first by rewrite /P /Q; apply: mulr_ge0=> //; lra.
move=> f hf c hc0 hfc.
have hfp : positive_function_lattice K (fun x => Order.max (f x) 0).
  by split; [exact: (function_lattice_positive_part hL hf) | move=> x; rewrite le_max lexx orbT].
have hfm : positive_function_lattice K (fun x => Order.max (- f x) 0).
  by split; [exact: (function_lattice_negative_part hL hf) | move=> x; rewrite le_max lexx orbT].
have hsplit : A (fun x => Order.max (f x) 0) = A f + A (fun x => Order.max (- f x) 0).
  rewrite -(daniell_integral_add hA hf hfm.1); congr A; apply: funext=> x.
  by rewrite !maxEle; case: (lerP (f x) 0)=> h1'; case: (lerP (- f x) 0)=> h2 /=; lra.
have hp := hpos _ c hfp hc0.
have hm := hpos _ c hfm hc0.
have hpc : forall x, Order.max (f x) 0 <= c.
  move=> x; have := hfc x; rewrite ler_norml ge_max=> /andP[h3 h4]; by rewrite h4 hc0.
have hmc : forall x, Order.max (- f x) 0 <= c.
  move=> x; have := hfc x; rewrite ler_norml ge_max=> /andP[h3 h4]; rewrite hc0 andbT; lra.
have -> : A f = A (fun x => Order.max (f x) 0) - A (fun x => Order.max (- f x) 0) by lra.
apply: le_trans (ler_normB _ _) _.
have := lerD (hp hpc) (hm hmc); lra.
Qed.

(** Source for [sup_norm_bounded_daniell]: a linear functional on K(X)
    bounded with respect to nu is a Daniell integral for compact X, by
    the first assertion of Federer 2.5.13, p. 106; supporting 2.5.19,
    p. 113. *)
Lemma sup_norm_bounded_daniell (A : (X -> R) -> R) :
  is_linear_functional_on_functions K A -> is_sup_norm_bounded A -> is_daniell_integral K A.
Proof.
move=> hlin [C [hC hb]].
apply: (compact_support_order_bounded_daniell hh (compact_space_locally_compact hc) hlin)=> u hu.
have [c [hc0 huc]] : exists c, 0 <= c /\ forall x, u x <= c.
  case: (pselect (exists x : X, True))=> [[x0 _]|hne].
  - have hcu : continuous (u : X -> R^o) := hu.1.1.
    have [x [_ hx]] := continuous_compact_maximum (ex_intro _ x0 I : setT !=set0) hc hcu.
    exists (u x); split; first exact: hu.2 x.
    by move=> y; exact: hx y I.
  - by exists 0; split=> // x; exfalso; apply: hne; exists x.
exists (C * c)=> k [hk [hk0 hku]].
apply: le_trans (ler_norm (A k)) _; apply: (hb k hk c hc0)=> x.
by rewrite ger0_norm ?hk0 //; exact: le_trans (hku x) (huc x).
Qed.

(** Source for [compact_space_daniell_iff]: for compact Hausdorff X the
    set K(X)* of Daniell integrals on K(X) is the conjugate space of K(X)
    with the norm nu of Federer 2.5.19, p. 113, and 2.5.12(2), p. 103. *)
Theorem compact_space_daniell_iff (A : (X -> R) -> R) :
  is_daniell_integral K A <-> is_linear_functional_on_functions K A /\ is_sup_norm_bounded A.
Proof.
split.
- move=> hA; split; first exact: daniell_compact_support_linear hA.
  exact: daniell_sup_norm_bounded hA.
- by move=> [hlin hb]; exact: sup_norm_bounded_daniell hlin hb.
Qed.

End CompactSpace.
