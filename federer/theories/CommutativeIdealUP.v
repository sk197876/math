(** Federer (1969), 3.4.5, pp. 320–321:
    ideals, finite generation, primeness and the Noetherian
    hypothesis used for analytic variety germs. These are
    independent algebraic laws; no geometric conclusion is
    included in their definitions. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [is_commutative_ideal]: the ideal of a
    set germ in 3.4.5, p. 320, is closed
    under addition, negatives and multiplication by ring
    elements and contains zero. *)
Record is_commutative_ideal (A:comNzRingType) (I:set A):Prop:={
  (** Source for [commutative_ideal_zero]: zero belongs to
      an ideal, 3.4.5, p. 320. *)
  commutative_ideal_zero:I 0;
  (** Source for [commutative_ideal_add]: additive closure,
      3.4.5, p. 320. *)
  commutative_ideal_add:forall x y,I x ->I y ->I (x+y);
  (** Source for [commutative_ideal_opp]: additive inverses,
      3.4.5, p. 320. *)
  commutative_ideal_opp:forall x,I x ->I (-x);
  (** Source for [commutative_ideal_mul]: absorption of
      multiplication, 3.4.5, p. 320. *)
  commutative_ideal_mul:forall x y,I y ->I (x*y)
}.

(** Source for [is_generated_commutative_ideal]: the ideal
    generated by original germs in 3.4.5, p. 320,
    is specified by its least-ideal property. This
    definition does not select a representation by sums. *)
Record is_generated_commutative_ideal (A:comNzRingType) (F I:set A):Prop:={
  (** Source for [generated_commutative_ideal_laws]: a
      generated ideal is an ideal, 3.4.5, p. 320. *)
  generated_commutative_ideal_laws:is_commutative_ideal I;
  (** Source for [generated_commutative_ideal_contains]: it
      contains the original generators, 3.4.5, p. 320. *)
  generated_commutative_ideal_contains:F `<=` I;
  (** Source for [generated_commutative_ideal_minimal]: it
      lies in every ideal containing those generators,
      3.4.5, p. 320. *)
  generated_commutative_ideal_minimal:forall J:set A,
    is_commutative_ideal J ->F `<=` J ->I `<=` J
}.

(** Source for [is_finitely_generated_commutative_ideal]:
    finite generation in 3.4.5, p. 320. A
    finite list may contain repetitions and may be empty. *)
Definition is_finitely_generated_commutative_ideal (A:comNzRingType) (I:set A):=
  exists F:seq A,is_generated_commutative_ideal [set x|x \in F] I.

(** Source for [is_prime_commutative_ideal]: prime ideals
    in 3.4.5, p. 320, are proper ideals
    containing a product only when they contain a factor. *)
Definition is_prime_commutative_ideal (A:comNzRingType) (I:set A):=
  is_commutative_ideal I /\ ~I 1 /\forall x y,I (x*y) ->I x \/I y.

(** Source for [is_noetherian_commutative_ring]: the
    Noetherian hypothesis of 3.4.5, p. 321;
    every ideal has a finite set of generators. The
    finite-dimensional analytic-ring theorem is due in 3.4.7. *)
Definition is_noetherian_commutative_ring (A:comNzRingType):=
  forall I:set A,is_commutative_ideal I ->is_finitely_generated_commutative_ideal I.
