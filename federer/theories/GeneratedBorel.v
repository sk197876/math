(** Federer (1969), 2.2.1, pp. 59-60: public generated Borel family
    interface. All results use the opaque least-family specification, never
    the intersection construction. *)
From mathcomp Require Import all_boot boolp classical_sets.
From Federer Require Import BorelFamilyUP GeneratedBorelSealed.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope classical_set_scope.

(** Source for [generated_borel_family]: Federer 2.2.1,
    pp. 59-60, the Borel family generated by S relative to X.
    The argument hS records the printed hypothesis S contained
    in the powerset of X. *)
Definition generated_borel_family (I : choiceType) (X : set I) (S : set (set I))
    (hS : forall A, S A -> A `<=` X) := GeneratedBorel.value hS.

(** Source for [generated_borel_family_specification]: Federer
    2.2.1, pp. 59-60, the generated family is precisely the
    smallest Borel family containing S. *)
Lemma generated_borel_family_specification (I : choiceType) (X : set I)
    (S : set (set I)) (hS : forall A, S A -> A `<=` X) :
  is_generated_borel_family X S (generated_borel_family hS).
Proof. exact: GeneratedBorel.laws. Qed.

(** Source for [generated_borel_family_is_borel]: Federer
    2.2.1, pp. 59-60, the generated family obeys all Borel
    closure laws. This consequence uses only the sealed specification. *)
Lemma generated_borel_family_is_borel (I : choiceType) (X : set I)
    (S : set (set I)) (hS : forall A, S A -> A `<=` X) :
  is_borel_family X (generated_borel_family hS).
Proof. exact: generated_borel_family_laws (generated_borel_family_specification hS). Qed.

(** Source for [generated_borel_family_generator]: Federer
    2.2.1, pp. 59-60, each generating set belongs to the
    generated Borel family. *)
Lemma generated_borel_family_generator (I : choiceType) (X : set I)
    (S : set (set I)) (hS : forall A, S A -> A `<=` X) :
  S `<=` generated_borel_family hS.
Proof. exact: generated_borel_family_contains (generated_borel_family_specification hS). Qed.

(** Source for [generated_borel_family_minimal]: Federer
    2.2.1, pp. 59-60, any Borel family containing the generators
    contains the generated family. *)
Lemma generated_borel_family_minimal (I : choiceType) (X : set I)
    (S : set (set I)) (hS : forall A, S A -> A `<=` X) (F : set (set I)) :
  is_borel_family X F -> S `<=` F -> generated_borel_family hS `<=` F.
Proof. exact: (@generated_borel_family_least I X S _ (generated_borel_family_specification hS) F). Qed.
