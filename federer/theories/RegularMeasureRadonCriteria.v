Let hL := @compactly_supported_continuous_functions_lattice R X.

(** Source for [regular_vanishing_compact_null]: if the integral A
    vanishes on K(X), then phi(C) = 0 for every compact C, because
    C subset {h > 1/2} for a cutoff h equal to 1 on C and
    (1/2) phi{h > 1/2} <= A(h) (2.5.3, p. 94). Supporting lemma for the
    form of the hypothesis of Federer 2.7.14–2.7.15, pp. 131–133, used
    with covariant measures, and for the counterexample showing that it
    is needed. *)
Lemma regular_vanishing_compact_null :
  (forall u, K u -> A u = 0) -> forall C, compact C -> mu C = 0%E.
Proof.
move=> hz C hC.
have [hhK hhr hh1] := @compact_cutoff_specification R X C hX hlX hC.
pose h := @compact_cutoff R X C hX hlX hC.
have hhalf : (0 < 2^-1 :> R) by rewrite invr_gt0 ltr0n.
have hb := represented_lattice_strict_level_bound hm hA (conj hhK (fun x => proj1 (andP (hhr x)))) hhalf.
rewrite hz // in hb.
have hlev : mu [set x | 2^-1 < h x] = 0%E.
  apply/eqP; rewrite eq_le measure_nonnegative // andbT.
  by rewrite -(@lee_pmul2l _ (2^-1)%:E) ?lte_fin // mule0.
apply: (measure_null_subset hm _ hlev)=> x hx; rewrite /= /h hh1 //.
by rewrite invf_lt1 ?ltr1n // ltr0n.
Qed.

(** Source for [regular_open_measurable]: "In view of 2.5.3, 2.5.14 we
    need to show that, if U is any nonempty open subset of G with
    compact closure, then U is alpha measurable", Federer 2.7.14,
    p. 131: by the fourth condition of 2.5.3, p. 94, an open set V is
    measurable when every V cap {f >= 1}, f in K(X)+, is; and
    V cap {f >= 1} = (V cap {f > 1/2}) cap {f >= 1}, where V cap {f > 1/2}
    is open with compact closure. Supporting theorem. *)
Theorem regular_open_measurable :
  (forall V, open V -> compact (closure V) -> measure_measurable mu V) ->
  forall V, open V -> measure_measurable mu V.
Proof.
move=> hrc V hV; apply/(regular_daniell_measurability_iff hL hm hA hr)=> f [hf hf0].
have [hfc hfs] := hf.
have hhalf : (0 < 2^-1 :> R) by rewrite invr_gt0 ltr0n.
have ho : open (V `&` [set x | 2^-1 < f x]).
  exact: (openI hV (@real_strict_upper_level_open _ _ f 2^-1 hfc)).
have hcl : compact (closure (V `&` [set x | 2^-1 < f x])).
  apply: (subclosed_compact (@closed_closure _ _) hfs); apply: closureS=> x [_ hx] hz.
  by move: hx; rewrite /= hz ltNge ltW.
have h1 := hrc _ ho hcl.
have h2 := @represented_lattice_closed_upper_level_measurable R X K A mu hm hA f 1 hf.
have -> : V `&` [set x | 1 <= f x] = (V `&` [set x | 2^-1 < f x]) `&` [set x | 1 <= f x].
  apply/seteqP; split=> x [hx hx1]; last by case: hx.
  split=> //; split=> //; apply: lt_le_trans hx1; rewrite invf_lt1 ?ltr1n // ltr0n.
exact: (measure_measurable_intersection hm h1 h2).
Qed.

(** Source for [regular_inner_finite]: "in case A is phi measurable and
    phi(A) < oo, then also phi(A) = sup{phi(K): K subset A, K is compact
    and phi measurable}", Federer 2.5.14, p. 107, for an open
    measurable set. Supporting lemma. *)
Lemma regular_inner_finite V c : measure_measurable mu V -> (mu V < +oo)%E ->
  (forall C, compact C -> C `<=` V -> (mu C <= c)%E) -> (mu V <= c)%E.
Proof.
move=> hVm hVf hc.
have hs := compact_support_regular_compact_supremum hm hA hr hVm hVf.
apply: (extended_real_supremum_least hs)=> a [C [hC [_ [hCV ->]]]]; exact: hc.
Qed.

(** Source for [regular_inner_sigma_compact]: inner regularity
    phi(V) = sup{phi(K): K compact, K subset V} of the definition of a
    Radon measure (2.2.5, p. 62), required in "alpha is a Radon measure",
    Federer 2.7.14, p. 131, for an open set V contained in a countable
    union of compact sets C_n, when all open sets are measurable: the
    open sets V cap (U_0 cup ... cup U_m), with U_n = {h_n > 1/2} for a
    cutoff h_n equal to 1 on C_n, have finite measure and increase to V
    (2.1.5(1), p. 57). Supporting lemma. *)
Lemma regular_inner_sigma_compact (hop : forall V, open V -> measure_measurable mu V)
    V c (C : nat -> set X) : open V -> (forall n, compact (C n)) -> V `<=` \bigcup_n C n ->
  (forall D, compact D -> D `<=` V -> (mu D <= c)%E) -> (mu V <= c)%E.
Proof.
move=> hV hC hVC hc.
pose h n := @compact_cutoff R X (C n) hX hlX (hC n).
have hh n : is_compact_cutoff (C n) (h n) := @compact_cutoff_specification R X (C n) hX hlX (hC n).
pose O n := [set x | 2^-1 < h n x].
have hOo n : open (O n).
  by have [[hc' _] _ _] := hh n; exact: (@real_strict_upper_level_open _ _ (h n) 2^-1 hc').
have hOs n : O n `<=` real_function_support (h n).
  move=> x hx; apply: subset_closure=> hz; move: hx; rewrite /O /= hz ltNge ltW //.
  by rewrite invr_gt0 ltr0n.
pose Q m := V `&` \bigcup_(n < m.+1) O n.
have hQo m : open (Q m).
  by apply: (openI hV); apply: bigcup_open=> n _; exact: hOo.
have hQf m : (mu (Q m) < +oo)%E.
  have hcomp : compact (\bigcup_(n < m.+1) real_function_support (h n)).
    by apply: prefix_union_compact=> n; have [[_ hs] _ _] := hh n.
  apply: le_lt_trans (compact_support_representing_measure_compact_finite hm hA hX hlX hcomp).
  apply: (measure_mono hm)=> x [_ [n hn hx]]; exists n=> //; exact: hOs.
have hQc m : (mu (Q m) <= c)%E.
  apply: regular_inner_finite (hop _ (hQo m)) (hQf m) _=> D hD hDQ.
  by apply: hc hD _=> x hx; have [] := hDQ x hx.
have hinc : forall n m, (n <= m)%N -> Q n `<=` Q m.
  by move=> n m hnm x [hx [i hi hxi]]; split=> //; exists i=> //=; apply: leq_trans hi _; rewrite ltnS.
have hcont := measure_continuity_below hm (fun m => hop _ (hQo m)) hinc.
have -> : V = \bigcup_m Q m.
  apply/seteqP; split=> x hx; last by have [m _ []] := hx.
  have [n _ hn] := hVC x hx.
  exists n=> //; split=> //; exists n=> //=.
  by have [_ _ h1] := hh n; rewrite /O /= h1 // invf_lt1 ?ltr1n // ltr0n.
exact: extended_increasing_limit_le hcont hQc.
Qed.

(** Source for [regular_outer]: "phi(A) = inf{phi(V): A subset V, V is
    open and phi measurable} for every A subset X", Federer 2.5.14,
    p. 107, in the form of the outer regularity law of a Radon measure
    (2.2.5, p. 62). Supporting lemma. *)
Lemma regular_outer S c : (forall V, open V -> S `<=` V -> (c <= mu V)%E) -> (c <= mu S)%E.
Proof.
move=> hc; rewrite (compact_support_regular_open_infimum hm hA hr S).
apply: extended_real_inf_greatest=> a [V [hV [_ [hSV ->]]]]; exact: hc V hV hSV.
Qed.

(** Source for [regular_radon_sigma_compact]: "alpha is a Radon
    measure", Federer 2.7.14, p. 131, by the reduction "In view of 2.5.3,
    2.5.14 we need to show that ... U is alpha measurable", when X is
    contained in a countable union of compact sets. Supporting theorem;
    the hypothesis supplies the inner regularity of open sets of
    infinite measure, which 2.5.3 and 2.5.14 do not give. *)
Theorem regular_radon_sigma_compact (C : nat -> set X) :
  (forall V, open V -> compact (closure V) -> measure_measurable mu V) ->
  (forall n, compact (C n)) -> [set: X] `<=` \bigcup_n C n -> is_radon_measure mu.
Proof.
move=> hrc hC hXC.
have hop := regular_open_measurable hrc.
constructor=> //.
- exact: (compact_support_representing_measure_compact_finite hm hA hX hlX).
- move=> V hV c hc; apply: (regular_inner_sigma_compact hop hV hC _ hc).
  by move=> x _; exact: hXC.
- move=> S c hc; exact: regular_outer.
Qed.

Section Partition.
Variable cell : X -> set X.
Hypothesis hco : forall x, open (cell x).
Hypothesis hcx : forall x, cell x x.
Hypothesis hcc : forall x y, cell x y -> cell y = cell x.
Hypothesis hcs : forall x, exists C : nat -> set X, (forall n, compact (C n)) /\ cell x `<=` \bigcup_n C n.
Hypothesis hpos : forall V, open V -> (exists x, V x) -> (0 < mu V)%E.

(** Source for [cell_disjoint]: distinct members of the partition are
    disjoint, supporting the cosets in the inner regularity argument for
    Federer 2.7.14, p. 131. Supporting lemma. *)
Lemma cell_disjoint x y z : cell x z -> cell y z -> cell x = cell y.
Proof. by move=> hx hy; rewrite -(hcc hx) -(hcc hy). Qed.

(** Source for [cell_union_sigma_compact]: a finite union of members of
    the partition lies in a countable union of compact sets, supporting
    the inner regularity argument for Federer 2.7.14, p. 131.
    Supporting lemma. *)
Lemma cell_union_sigma_compact (u : nat -> set X) :
  (forall n, u n = set0 \/ exists x, u n = cell x) ->
  exists C : nat -> set X, (forall n, compact (C n)) /\ \bigcup_n u n `<=` \bigcup_n C n.
Proof.
move=> hu.
have hC n : exists C : nat -> set X, (forall m, compact (C m)) /\ u n `<=` \bigcup_m C m.
  case: (hu n)=> [->|[x ->]]; last exact: hcs.
  by exists (fun _ => set0); split=> // m; exact: compact0.
pose C n := projT1 (cid (hC n)).
have hCs n : (forall m, compact (C n m)) /\ u n `<=` \bigcup_m C n m := projT2 (cid (hC n)).
exists (fun k => \bigcup_(i < k.+1) \bigcup_(j < k.+1) C i j); split.
- move=> k; apply: prefix_union_compact=> i; apply: prefix_union_compact=> j; exact: (hCs i).1.
- move=> x [n _ hx]; have [m _ hm'] := (hCs n).2 x hx.
  exists (maxn n m)=> //; exists n; first by rewrite /= ltnS leq_maxl.
  by exists m; first by rewrite /= ltnS leq_maxr.
Qed.

(** Source for [regular_inner_partition]: inner regularity
    phi(V) = sup{phi(K): K compact, K subset V} for every open set V,
    required in "alpha is a Radon measure", Federer 2.7.14, p. 131. If
    phi(K) <= c < oo for all compact K subset V, then the disjoint open
    sets V cap Z, Z a member of the partition meeting V, have measures
    with finite subsums <= c, so that there are only countably many of
    them (2.1.1(12), p. 53); all of them have positive measure, hence V
    lies in a countable union of compact sets. Supporting lemma. *)
Lemma regular_inner_partition (hop : forall V, open V -> measure_measurable mu V) V c :
  open V -> (forall D, compact D -> D `<=` V -> (mu D <= c)%E) -> (mu V <= c)%E.
Proof.
move=> hV hc.
have hc0 : (0 <= c)%E.
  by apply: le_trans (hc set0 compact0 (sub0set _)); rewrite (measure_empty hm).
case: c hc hc0=> [r| |] hc hc0; [|by rewrite leey|by move: hc0; rewrite leeNy_eq].
pose D := [set Z : set X | exists2 x, V x & Z = cell x].
pose F := fun Z : set X => V `&` Z.
have hFm Z : D Z -> measure_measurable mu (F Z).
  by move=> [x _ ->]; apply: hop; exact: (openI hV (hco x)).
have hfin (B : {fset (set X)}) : (forall Z, Z \in B -> D Z) ->
    (\sum_(Z <- B) mu (F Z) <= r%:E)%E.
  move=> hB.
  have hdis Z Z' : Z \in B -> Z' \in B -> Z != Z' -> forall x, F Z x -> F Z' x -> False.
    move=> hZ hZ' /eqP hne x [_ hx] [_ hx'].
    have [y _ hy] := hB Z hZ; have [y' _ hy'] := hB Z' hZ'.
    by apply: hne; rewrite hy hy'; apply: (@cell_disjoint y y' x); [rewrite -hy|rewrite -hy'].
  rewrite -(measure_finite_disjoint_additivity hm (fun Z hZ => hFm Z (hB Z hZ)) hdis).
  have hcov : \bigcup_(Z in [set` B]) F Z `<=` V by move=> x [Z _ [hx _]].
  have hw n : nth set0 B n = set0 \/ exists x, nth set0 B n = cell x.
    case: (ltnP n (size B))=> hn.
    - right; have [y _ hy] := hB _ (mem_nth set0 hn); by exists y.
    - by left; exact: nth_default.
  have [C [hC hCw]] := cell_union_sigma_compact hw.
  apply: (regular_inner_sigma_compact hop _ hC).
  - apply: bigcup_open=> Z hZ; have [y _ ->] := hB Z hZ; exact: (openI hV (hco y)).
  - move=> x [Z hZ [_ hx]]; apply: hCw; exists (index Z B)=> //; by rewrite nth_index.
  - move=> E hE hEs; apply: (hc E hE); exact: subset_trans hEs hcov.
have hsum : (nonnegative_sum D (fun Z => mu (F Z)) < +oo)%E.
  apply: le_lt_trans (_ : (_ <= r%:E)%E) (ltry _).
  by apply: nonnegative_sum_least=> B hB; exact: hfin B hB.
have hcnt := nonnegative_sum_countable_support (fun Z _ => measure_nonnegative hm (F Z)) hsum.
have hDc : countable D.
  apply: sub_countable _ hcnt; apply: subset_card_le=> Z hZ; split=> //.
  have [x hx ->] := hZ; rewrite /= gt_eqF //; apply: hpos; first exact: (openI hV (hco x)).
  by exists x; split.
have [u [hu1 hu2]] := countable_default_enumeration set0 hDc.
have hu n : u n = set0 \/ exists x, u n = cell x.
  by case: (hu1 n)=> [[x _ ->]|->]; [right; exists x|left].
have [C [hC hCs]] := cell_union_sigma_compact hu.
apply: (regular_inner_sigma_compact hop hV hC _ hc)=> x hx.
apply: hCs; have [n hn] := hu2 (cell x) (ex_intro2 _ _ x hx erefl).
by exists n=> //; rewrite hn.
Qed.

(** Source for [regular_radon_partition]: "alpha is a Radon measure",
    Federer 2.7.14, p. 131, by the reduction "In view of 2.5.3, 2.5.14
    we need to show that ... U is alpha measurable", when X is
    partitioned into open sets contained in countable unions of compact
    sets and nonempty open sets have positive measure. Supporting
    theorem; the hypotheses supply the inner regularity of open sets of
    infinite measure, which 2.5.3 and 2.5.14 do not give. *)
Theorem regular_radon_partition :
  (forall V, open V -> compact (closure V) -> measure_measurable mu V) -> is_radon_measure mu.
Proof.
move=> hrc; have hop := regular_open_measurable hrc.
constructor=> //.
- exact: (compact_support_representing_measure_compact_finite hm hA hX hlX).
- move=> V hV c hc; exact: (@regular_inner_partition hop V c hV hc).
- move=> S c hc; exact: regular_outer.
Qed.

