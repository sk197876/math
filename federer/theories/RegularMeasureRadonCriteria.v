(** Source for [prefix_union_compact]: a finite union of compact sets
    is compact, supporting the countable unions of compact sets in the
    proof of Federer 2.7.14, p. 131. Supporting lemma. *)
Lemma prefix_union_compact (X : topologicalType) (F : nat -> set X) n :
  (forall i, compact (F i)) -> compact (\bigcup_(i < n) F i).
Proof. by move=> hF; rewrite bigcup_mkord; apply: bigsetU_compact=> i _; exact: hF. Qed.

(** Source for [extended_increasing_limit_le]: if u_n increases to l
    and u_n <= c for every n, then l <= c, supporting the passage from
    the sets V cap U_m to V in the proof of Federer 2.7.14, p. 131
    (2.1.5(1), p. 57). Supporting lemma. *)
Lemma extended_increasing_limit_le (R : realType) (u : nat -> \bar R) l c :
  extended_increases_to u l -> (forall n, (u n <= c)%E) -> (l <= c)%E.
Proof.
move=> [_ [hlim _]] hc; rewrite leNgt; apply/negP=> hlt.
have [N hN] := hlim c hlt.
by have := hN N (leqnn N); rewrite ltNge hc.
Qed.

Section RegularMeasureRadonCriteria.
Variable R : realType.
Variable X : topologicalType.
Hypothesis hX : hausdorff_space X.
Hypothesis hlX : locally_compact [set: X].
Local Notation K := (@compactly_supported_continuous_functions R X).
Variable mu : set X -> \bar R.
Hypothesis hm : is_measure mu.
Variable A : (X -> R) -> R.
Hypothesis hA : is_real_integral_functional mu K A.
Hypothesis hr : is_function_lattice_regular K mu.

(** Source for [hL]: K(X) is a lattice of functions, Federer 2.5.13,
