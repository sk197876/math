(** Federer (1969), 2.7.14, printed p. 131, proof: "In view of 2.5.3, 2.5.14
    we need to show that, if U is any nonempty open subset of G with compact
    closure, then U is alpha measurable." Here X is a locally compact
    Hausdorff space and phi is the K(X) regular measure associated with a
    monotone Daniell integral on K(X) (2.5.3, p. 94). By 2.5.14, p. 107,
    phi(A) = inf{phi(V): A subset V, V open and phi measurable} for every A,
    phi(K) < oo for compact K, and phi(A) = sup{phi(K): K subset A, K
    compact and phi measurable} for phi measurable A with phi(A) < oo. If
    every open set with compact closure is phi measurable, every open set is
    phi measurable by the fourth condition of 2.5.3, p. 94 ("B is phi
    measurable if and only if B cap {x: f(x) >= 1} is phi measurable for
    every f in L+"). The definition of a Radon measure (2.2.5, p. 62)
    requires in addition phi(V) = sup{phi(K): K compact, K subset V} for
    every open set V, also when phi(V) = oo, and this does not follow from
    2.5.3 and 2.5.14: for the zero integral on an uncountable discrete group
    the K(X) regular measure is 0 on countable sets and oo on the others,
    all sets are measurable, and inner regularity fails for X itself. This
    module therefore proves two criteria. The first assumes that X is
    contained in a countable union of compact sets. The second assumes that
    X is partitioned into open sets each contained in a countable union of
    compact sets, and that phi(V) > 0 for every nonempty open V; then an
    open set V with sup{phi(K): K compact, K subset V} < oo meets only
    countably many members of the partition (2.1.1(12), p. 53, as in
    2.1.6(2), p. 59), hence lies in a countable union of compact sets. For a
    locally compact group the cosets of an open subgroup generated by a
    compact neighbourhood of e supply the partition
    (OpenSigmaCompactSubgroup.v); positivity holds for nonzero covariant
    integrals (CovariantCompactRightInvariance.v). The local erratum has no
    entry for p. 107; its entry for p. 131 adds "nonzero" to 2.7.14. *)
