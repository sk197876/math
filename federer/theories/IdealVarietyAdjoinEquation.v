(** Source for [ideal_variety_adjoin_equation]:
    var(J) is the part of var(I_g)
    on delta's zero set, where J
    is generated by I_g and delta,
    3.4.8(10), p. 331. *)
Theorem ideal_variety_adjoin_equation (R:realType) (X:lmodType R)
    (NX:X->R) (hNX:is_real_norm NX) (a:X)
    (I J:set [the comNzRingType of (@analytic_germ_ring R X NX hNX a)])
    (hI:is_finitely_generated_commutative_ideal I)
    (hJ:is_finitely_generated_commutative_ideal J) delta:
  is_generated_commutative_ideal (I `|` [set alpha|alpha = delta]) J ->
  @IdealVarietyGerm.value R X NX hNX a J hJ =
    @SetGerms.meet (Topological.clone (real_norm_metric_space hNX) _) a
      (@IdealVarietyGerm.value R X NX hNX a I hI)
      (@AnalyticZeroGerm.value R X NX hNX a delta).
Proof.
move=>hGenerated.
pose T:=Topological.clone (real_norm_metric_space hNX) _.
pose varI:=@IdealVarietyGerm.value R X NX hNX a I hI.
pose varJ:=@IdealVarietyGerm.value R X NX hNX a J hJ.
pose zero:=@AnalyticZeroGerm.value R X NX hNX a delta.
pose sigma:=@SetGerms.meet T a varI zero.
have hIJ:I `<=` J.
  move=>alpha hAlpha;apply:(generated_commutative_ideal_contains hGenerated);by left.
have hDeltaJ:J delta.
  apply:(generated_commutative_ideal_contains hGenerated);right;by [].
have hDeltaZero:=@analytic_zero_germ_ideal_equivalence R X NX hNX a varJ delta.
apply:set_germ_subset_antisymmetric.
- apply:set_germ_subset_meet_bound.
  + exact:(@ideal_variety_germ_antitone R X NX hNX a I J hI hJ hIJ).
  + apply:hDeltaZero.1;exact:(@ideal_in_vanishing_ideal_of_variety R X NX hNX a J hJ delta hDeltaJ).
- apply:ideal_variety_germ_contains_vanishing_set.
  apply:(generated_commutative_ideal_minimal hGenerated
    (@analytic_set_ideal_ring_laws R X NX hNX a sigma))=>alpha [hAlpha|->].
  + apply:(@analytic_set_ideal_antitone R X NX hNX a sigma varI
      (set_germ_meet_subset_left varI zero)).
    exact:(@ideal_in_vanishing_ideal_of_variety R X NX hNX a I hI alpha hAlpha).
  + apply:(@analytic_zero_germ_ideal_equivalence R X NX hNX a sigma delta).2.
    exact:set_germ_meet_subset_right.
Qed.
