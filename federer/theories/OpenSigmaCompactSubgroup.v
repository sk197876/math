(** Federer (1969), 2.7.14 and 2.7.15, printed pp. 131–133: "Every left
    (right) chi covariant measure over G is a Radon measure", "Every chi
    covariant measure over X is a Radon measure". The definition of a Radon
    measure (2.2.5, p. 62) requires phi(V) = sup{phi(K): K compact, K subset
    V} for every open set V, also when phi(V) = oo. Federer's reduction "In
    view of 2.5.3, 2.5.14" leaves this case open. It is supplied here by a
    partition of X into open sets each contained in a countable union of
    compact sets (RegularMeasureRadonCriteria.v). This module constructs the
    partition from the standing hypotheses of 2.7.1, p. 121: G is a locally
    compact Hausdorff topological group, and X is a homogeneous space of G.
    If N is a compact symmetric neighbourhood of e, then H = Union_{n >= 1}
    N^n is an open subgroup of G which is a countable union of compact sets,
    and the orbits {h y: h in H}, y in X, form the required partition of X;
    for X = G with left multiplication they are the cosets H y. This is
    supporting general topology, not printed by Federer. The local erratum
    has no entry for pp. 131–133. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets functions reals
  topology normedtype.
From Federer Require Import TopologicalGroupUP TopologicalGroupLaws HomogeneousSpaceUP
  HomogeneousSpaceLaws.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope classical_set_scope.

Section OpenSigmaCompactSubgroup.
Variable G : topologicalType.
Variables (mul : G -> G -> G) (inv : G -> G) (e : G).
Hypothesis hGc : is_locally_compact_hausdorff_group mul inv e.

(** Source for [hT]: G is a topological group, Federer 2.7.1, p. 121,
    used in this section. *)
Let hT := lch_group_topological hGc.
(** Source for [hgl]: the group laws of G, Federer 2.7.1, p. 121, used
    in this section. *)
Let hgl := topological_group_laws hT.

(** Source for [compact_symmetric_neighbourhood]: a compact
    neighbourhood N of e with N^{-1} = N exists in G, supporting the
    inner regularity in "alpha is a Radon measure", Federer 2.7.14,
    p. 131: N cap N^{-1} for a compact neighbourhood N of e (2.7.1,
    p. 121, G locally compact Hausdorff). Supporting lemma. *)
Lemma compact_symmetric_neighbourhood :
  exists N : set G, [/\ nbhs e N, compact N & forall x, N x -> N (inv x)].
Proof.
have [N hN [hNc _]] := @lch_group_locally_compact _ _ _ _ hGc e I; rewrite withinET in hN.
have hic : continuous inv := topological_group_inv_continuous hT.
have himg : compact (inv @` N) by apply: continuous_compact hNc; exact: continuous_subspaceT.
have hpre : inv @^-1` N = inv @` N.
  apply/seteqP; split=> x hx; first by exists (inv x)=> //; rewrite (group_invK hgl).
  by have [y hy <-] := hx; rewrite /= (group_invK hgl).
exists (N `&` inv @^-1` N); split.
- have hie : nbhs e (inv @^-1` N) by apply: (hic e); rewrite /= (group_inv1 hgl).
  exact: filterI hN hie.
- rewrite hpre; exact: compact_closedI hNc (compact_closed (lch_group_hausdorff hGc) himg).
- by move=> x [h1 h2]; split=> //=; rewrite (group_invK hgl).
Qed.

Section Generated.
Variable N : set G.
Hypothesis hNe : nbhs e N.
Hypothesis hNc : compact N.
Hypothesis hNs : forall x, N x -> N (inv x).

(** Source for [neighbourhood_power]: the sets N^{n+1} = N ... N, used
    for the open subgroup generated by N, supporting Federer 2.7.14,
    p. 131. Definition by recursion: N^1 = N, N^{n+2} = N^{n+1} N. *)
Fixpoint neighbourhood_power (n : nat) : set G :=
  if n is m.+1 then (fun p : G * G => mul p.1 p.2) @` (neighbourhood_power m `*` N) else N.

(** Source for [generated_subgroup]: H = Union_n N^{n+1}, supporting
    Federer 2.7.14, p. 131. Definition. *)
Definition generated_subgroup : set G := \bigcup_n neighbourhood_power n.

(** Source for [neighbourhood_power_compact]: each N^{n+1} is compact,
    as a continuous image of a product of compact sets, supporting
    Federer 2.7.14, p. 131. Supporting lemma. *)
Lemma neighbourhood_power_compact n : compact (neighbourhood_power n).
Proof.
elim: n=> [|n ih] //=.
apply: continuous_compact; last exact: compact_setX ih hNc.
apply: continuous_subspaceT; exact: topological_group_mul_continuous hT.
Qed.

(** Source for [neighbourhood_power_mul]: N^{n+1} N^{m+1} is contained
    in N^{n+m+2}, supporting Federer 2.7.14, p. 131. Supporting lemma,
    by induction on m. *)
Lemma neighbourhood_power_mul m n a b :
  neighbourhood_power n a -> neighbourhood_power m b -> neighbourhood_power (n + m).+1 (mul a b).
Proof.
elim: m b=> [|m ih] b ha hb; first by rewrite addn0; exists (a, b).
have [[b' y] [hb' hy] <-] := hb.
rewrite addnS (group_mulA hgl); exists (mul a b', y)=> //; split=> //; exact: ih.
Qed.

(** Source for [neighbourhood_power_inv]: (N^{n+1})^{-1} = N^{n+1} for
    symmetric N, supporting Federer 2.7.14, p. 131. Supporting lemma,
    by induction on n. *)
Lemma neighbourhood_power_inv n a : neighbourhood_power n a -> neighbourhood_power n (inv a).
Proof.
elim: n a=> [|n ih] a /=; first exact: hNs.
move=> [[a' y] [ha' hy] <-] /=; rewrite (group_invM hgl).
have h := @neighbourhood_power_mul n 0 (inv y) (inv a') (hNs hy) (ih a' ha').
by rewrite add0n in h.
Qed.

(** Source for [generated_subgroup_subgroup]: H is a subgroup of G,
    supporting Federer 2.7.14, p. 131. Supporting lemma. *)
Lemma generated_subgroup_subgroup : is_subgroup mul inv e generated_subgroup.
Proof.
constructor.
- by exists 0%N=> //=; exact: nbhs_singleton hNe.
- move=> a b [n _ ha] [m _ hb]; exists (n + m).+1=> //; exact: neighbourhood_power_mul.
- move=> a [n _ ha]; exists n=> //; exact: neighbourhood_power_inv.
Qed.

(** Source for [generated_subgroup_open]: H is open, since a N^{n+1}
    is contained in N^{n+2} and is a neighbourhood of a whenever a is in
    N^{n+1}, supporting Federer 2.7.14, p. 131. Supporting lemma. *)
Lemma generated_subgroup_open : open generated_subgroup.
Proof.
rewrite openE=> a [n _ ha].
have hW : nbhs a [set h | N (mul (inv a) h)].
  have hc := left_translation_continuous hT (inv a) a.
  by apply: hc; rewrite /= (group_mulVg hgl).
apply: filterS hW=> h hh; exists n.+1=> //=.
by exists (a, mul (inv a) h)=> //=; rewrite (group_mulKVg hgl).
Qed.

End Generated.

(** Source for [open_sigma_compact_subgroup]: G has an open subgroup H
    which is the union of a sequence of compact sets, supporting the
    inner regularity in "alpha is a Radon measure", Federer 2.7.14,
    p. 131. Supporting theorem. *)
Theorem open_sigma_compact_subgroup : exists H : set G, [/\ is_subgroup mul inv e H, open H &
  exists C : nat -> set G, (forall n, compact (C n)) /\ H = \bigcup_n C n].
Proof.
have [N [hNe hNc hNs]] := compact_symmetric_neighbourhood.
exists (generated_subgroup N); split.
- exact: generated_subgroup_subgroup.
- exact: generated_subgroup_open.
- by exists (neighbourhood_power N); split=> // n; exact: neighbourhood_power_compact.
Qed.

Section Orbits.
Variable X : topologicalType.
Variable A : G -> X -> X.
Hypothesis hA : is_homogeneous_space mul A.
Variable H : set G.
Hypothesis hH : is_subgroup mul inv e H.
Hypothesis hHo : open H.
Variable C : nat -> set G.
Hypothesis hC : forall n, compact (C n).
Hypothesis hHC : H = \bigcup_n C n.

(** Source for [subgroup_orbit]: the orbit {h y: h in H} of y under the
    subgroup H, supporting the inner regularity in Federer 2.7.14 and
    2.7.15, pp. 131–133. Definition. *)
Definition subgroup_orbit (y : X) : set X := [set A h y | h in H].

(** Source for [subgroup_orbit_open]: the orbit H y is open, because
    A^y is an open map ("for each x in X the map A^x ... is open",
    Federer 2.7.1, p. 121) and H is open. Supporting lemma. *)
Lemma subgroup_orbit_open y : open (subgroup_orbit y).
Proof. exact: (homogeneous_orbit_open hA y) hHo. Qed.

(** Source for [subgroup_orbit_self]: y belongs to its orbit, since
    A(e,y) = y (2.7.1, p. 121). Supporting lemma. *)
Lemma subgroup_orbit_self y : subgroup_orbit y y.
Proof. by exists e; [exact: (subgroup_unit hH)|exact: (homogeneous_unit_action hgl hA y)]. Qed.

(** Source for [subgroup_orbit_eq]: z in H y implies H z = H y, by
    A(g h, x) = A[g, A(h, x)] (2.7.1, p. 121). Supporting lemma. *)
Lemma subgroup_orbit_eq y z : subgroup_orbit y z -> subgroup_orbit z = subgroup_orbit y.
Proof.
move=> [h hh <-]; apply/seteqP; split=> x [k hk <-].
- by exists (mul k h); [exact: (subgroup_mul hH hk hh)|rewrite (homogeneous_action_compatible hA)].
- exists (mul k (inv h)); first exact: (subgroup_mul hH hk (subgroup_inv hH hh)).
  by rewrite -(homogeneous_action_compatible hA) (group_mulgKV hgl).
Qed.

(** Source for [subgroup_orbit_sigma_compact]: the orbit H y lies in
    the union of the compact sets A^y(C_n), supporting the inner
    regularity in Federer 2.7.14 and 2.7.15, pp. 131–133. Supporting
    lemma. *)
Lemma subgroup_orbit_sigma_compact y :
  exists D : nat -> set X, (forall n, compact (D n)) /\ subgroup_orbit y `<=` \bigcup_n D n.
Proof.
exists (fun n => orbit_map A y @` C n); split.
- move=> n /=; apply: (@continuous_compact _ _ (orbit_map A y) (C n)); last exact: hC.
  apply: continuous_subspaceT; exact: (orbit_map_continuous hA).
- move=> _ [h hh <-]; rewrite hHC in hh; have [n _ hn] := hh.
  by exists n=> //; exists h.
Qed.

End Orbits.

End OpenSigmaCompactSubgroup.
