(** Federer (1969), 4.1.1, pp. 343–344: existence of the topology
    generated by the derivative seminorms. This supporting construction
    proves the independent neighbourhood laws without choosing any
    representation for smooth functions. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets reals lra.
From Federer Require Import RealNormUP OpenFamilyTopologyUP DirectedSeminormFamilyUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import Order.TTheory GRing.Theory Num.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

Section SeminormTopologyExistence.
Variable R : realType.
Variable E : lmodType R.
Variable I : Type.
Variable p : I -> E -> R.
Hypothesis hp : is_directed_seminorm_family p.

(** Source for [directed_seminorm_open_witness]: a private open-set
    witness for the seminorm neighbourhood base of Federer 4.1.1,
    p. 344. Downstream results use its abstract specification. *)
Definition directed_seminorm_open_witness (A : set E) :=
  forall x, A x -> exists i r, 0 < r /\
    forall y, p i (y-x) < r -> A y.

(** Source for [directed_seminorm_open_whole]: supporting whole-space
    topology law for Federer 4.1.1, p. 344. *)
Lemma directed_seminorm_open_whole : directed_seminorm_open_witness setT.
Proof.
move=> x _; have [i _] := directed_seminorm_nonempty hp.
exists i,1; split; first exact: ltr01.
by move=> y hy.
Qed.

(** Source for [directed_seminorm_open_intersection]: supporting
    intersection law for the single-ball neighbourhood base of
    Federer 4.1.1, p. 344. Directedness supplies one common index. *)
Lemma directed_seminorm_open_intersection A B :
  directed_seminorm_open_witness A -> directed_seminorm_open_witness B ->
  directed_seminorm_open_witness (A `&` B).
Proof.
move=> hA hB x [hAx hBx].
have [i [r [hr hAr]]] := hA x hAx.
have [j [s [hs hBs]]] := hB x hBx.
have [k hk] := directed_seminorm_upper_pair hp i j.
exists k,(Num.min r s); split; first by rewrite lt_min hr hs.
move=> y; rewrite lt_min=> /andP [hyr hys]; split.
- apply: hAr; exact: le_lt_trans (hk (y-x)).1 hyr.
- apply: hBs; exact: le_lt_trans (hk (y-x)).2 hys.
Qed.

(** Source for [directed_seminorm_open_union]: supporting arbitrary
    union law for the topology of E(U,Y), Federer 4.1.1, p. 344. *)
Lemma directed_seminorm_open_union (J : Type) (A : J -> set E) :
  (forall j, directed_seminorm_open_witness (A j)) ->
  directed_seminorm_open_witness (\bigcup_j A j).
Proof.
move=> hA x [j _ hx].
have [i [r [hr hB]]] := hA j x hx.
exists i,r; split=> // y hy; exists j=> //; exact: hB.
Qed.

(** Source for [directed_seminorm_topology_exists]: supporting proved
    existence of the seminorm-generated topology in Federer 4.1.1,
    p. 344. The defining laws were stated independently. *)
Theorem directed_seminorm_topology_exists :
  exists O, is_seminorm_family_topology p O.
Proof.
exists directed_seminorm_open_witness; split.
- constructor.
  + exact: directed_seminorm_open_whole.
  + exact: directed_seminorm_open_intersection.
  + exact: directed_seminorm_open_union.
- by move=> A.
Qed.
End SeminormTopologyExistence.

(** Source for [seminorm_family_topology_unique]: uniqueness from
    the specified neighbourhood base, supporting the topology in
    Federer 4.1.1, p. 344. *)
Lemma seminorm_family_topology_unique (R : realType) (E : lmodType R)
    (I : Type) (p : I -> E -> R) (O P : set (set E)) :
  is_seminorm_family_topology p O -> is_seminorm_family_topology p P -> O = P.
Proof.
move=> hO hP; apply: funext=> A; apply: propext; split=> hA.
- apply: (hP.2 A).2; exact: (hO.2 A).1.
- apply: (hO.2 A).2; exact: (hP.2 A).1.
Qed.
