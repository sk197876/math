(** Source for [holomorphic_reduction_C_next_coordinate_primitive]:
    C_m implies that L is generated by
    M and the original next coordinate,
    3.4.8(10), p. 330. Original B_j relations
    provide the simple prefix quotient; the
    C_m denominators express every remaining coordinate
    in its scalar extension. No primitive
    generation conclusion is a premise. *)
Theorem holomorphic_reduction_C_next_coordinate_primitive:
  @holomorphic_reduction_actual_C R X Herm hHerm n e he omega I m g ->
  is_generated_commutative_subring
    (fun y:L=>y = inclusion (pi (gamma m)) \/exists a:M,y = phi a) setT.
Proof.
move=>hC.
have hTriangle a:inclusion (scalar a) = phi (eta a).
  exact:esym (coefficient_fraction_scalar_triangle hCoefficient a).
have hLoci:=@holomorphic_reduction_actual_laws R X Herm hHerm n e he omega I.
have hRelations:=(holomorphic_reduction_C_membership hLoci m g).1 hC.
have hQ:=@HolomorphicCoordinateSubringFamily.laws R X NX hNXR n e he omega.
constructor.
- by constructor.
- by move=>y _.
- move=>N hN hGenerators.
  pose image:set C:=fun y=>exists beta:A1,y = pi (E1 beta).
  pose original:{rmorphism A1->C}:=GRing.RMorphism.clone A1 C (pi \o E1) _.
  have hImageRing:is_commutative_subring image:=commutative_ring_image_subring original.
  pose D:=@CommutativeSubringRealisation.space C image hImageRing.
  pose lift:=@CommutativeSubringRealisation.inclusion C image hImageRing.
  have hImage:=@CommutativeSubringRealisation.laws C image hImageRing.
  have [coefficient [coordinate [hScalar [hCoordinate [_ hSimple]]]]]:=
    @holomorphic_reduction_prefix_image_step R X NX hNX n e he omega hDual
      (@holomorphic_rotated_germ_ideal R X Herm hHerm (n+n) eR heR I g)
      (@holomorphic_rotated_germ_ideal_is_ideal R X Herm hHerm (n+n) eR heR I g hI)
      (@holomorphic_rotated_germ_ideal_proper R X Herm hHerm (n+n) eR heR I g hProper)
      C pi hPi m D lift hImage
      ((holomorphic_reduction_B_membership hLoci m g).1 (@hAllB m (leqnn m))).
  pose composite:{rmorphism D->L}:=GRing.RMorphism.clone D L (inclusion \o lift) _.
  have hPrefix:forall beta:A1,N (inclusion (pi (E1 beta))).
    move=>beta.
    have hPre:=commutative_subring_ring_preimage composite hN.
    have hContains:setT `<=` composite @^-1` N.
      apply:(generated_commutative_subring_minimal hSimple hPre)=>d [->|[a ->]].
      + change (N (inclusion (lift coordinate)));rewrite hCoordinate.
        apply:hGenerators;by left.
      + change (N (inclusion (lift (coefficient a))));rewrite hScalar
          (bool_irrelevance (leq_trans (leqnSn (m:nat)) (ltn_ord m)) hMN).
        change (N (inclusion (scalar a))).
        rewrite hTriangle.
        apply:hGenerators;right;by exists (eta a).
    have hMember:image (pi (E1 beta)) by exists beta.
    have [d hD]:=(commutative_subring_inclusion_image hImage _).1 hMember.
    have hResult:=hContains d Logic.I.
    change (N (inclusion (lift d))) in hResult;by rewrite hD in hResult.
  have hOriginal:=@holomorphic_reduction_original_fraction_generators R X Herm hHerm n e he omega hDual
    I hI hProper g C pi hPi m hMN hAllB L inclusion hFraction M eta phi hCoefficient.
  apply:(generated_commutative_subring_minimal hOriginal hN).
  move=>y [[i ->]|[a ->]];last by apply:hGenerators;right;exists a.
  pose j:=ordinal_coordinate_tail_index hMN i.
  have hMJ:(m<=j)%N by rewrite /j ordinal_coordinate_tail_value leq_addr.
  have [delta [numerator [hDelta [hOutside [hNumerator hRelation]]]]]:=@hRelations j hMJ.
  rewrite (holomorphic_coordinate_subring_family_member hQ hMN) in hDelta.
  have [a hA]:=(@holomorphic_prefix_germ_subring_membership R X NX hNXR n e he omega m hMN delta).1 hDelta.
  rewrite (holomorphic_coordinate_subring_family_member hQ (ltn_ord m)) in hNumerator.
  have [beta hBeta]:=(@holomorphic_prefix_germ_subring_membership R X NX hNXR n e he omega
    (m:nat).+1 (ltn_ord m) numerator).1 hNumerator.
  have hNonzero:eta a!=0.
    apply/eqP=>hZero;apply:hOutside.
    apply:(commutative_quotient_kernel hPi _).1.
    apply:(fraction_field_embedding_injective hFraction).
    rewrite rmorph0 -hA.
    change (inclusion (scalar a) = 0).
    by rewrite hTriangle hZero rmorph0.
  have hDeltaField:inclusion (pi delta) = phi (eta a).
    rewrite -hA;exact:esym (coefficient_fraction_scalar_triangle hCoefficient a).
  have hEquation:inclusion (pi delta)*inclusion (pi (gamma j)) = inclusion (pi numerator).
    have hZero:=(commutative_quotient_kernel hPi _).2 hRelation.
    have hEqual:pi delta*pi (gamma j) = pi numerator.
      apply/eqP;by rewrite -subr_eq0 -rmorphM -rmorphB hZero eqxx.
    by rewrite -rmorphM hEqual.
  have hInverse:phi ((eta a)^-1)*inclusion (pi delta) = 1.
    by rewrite hDeltaField -rmorphM (mulVf hNonzero) rmorph1.
  have hRepresent:inclusion (pi (gamma j)) = phi ((eta a)^-1)*inclusion (pi numerator).
    by rewrite -hEquation mulrA hInverse mul1r.
  change (N (inclusion (pi (gamma j))));rewrite hRepresent.
  apply:(@commutative_subring_multiply L N hN).
  + apply:hGenerators;right;by exists ((eta a)^-1).
  + rewrite -hBeta;exact:hPrefix beta.
Qed.
End OriginalPrimitive.
