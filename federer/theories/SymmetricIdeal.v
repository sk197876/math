(** Source for [commutator_ideal_direct_sum]: Federer 1.9.1, p. 41,
    commutator ideal and homogeneous decomposition. Supporting construction
    for this passage, in words: The ideal is the direct sum of its
    homogeneous components of degrees at least two. *)
Lemma commutator_ideal_direct_sum x : commutator_ideal x ->
  (forall n, commutator_ideal (tensor_degree n x)) /\
  (exists N, x = \sum_(i < N | (2 <= i)%N) tensor_degree i x).
Proof.
move=> hx; split; first by move=> n; exact: commutator_ideal_homogeneous hx.
have [N hN] := tensor_degree_finite x; exists N.
rewrite {1}hN [RHS]big_mkcond; apply: eq_bigr => i _.
case: ifP => //; move: (val i) => [|[|n]] // _.
- exact: commutator_ideal_degree_zero hx.
- exact: commutator_ideal_degree_one hx.
Qed.
