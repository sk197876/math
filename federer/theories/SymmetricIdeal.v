Lemma commutator_ideal_degree_zero x : commutator_ideal x -> tensor_degree 0 x = 0.
Proof.
elim=> [|u v hu ihu hv ihv|a u hu ihu|s t v w].
- exact: linear0.
- rewrite linearD; change (tensor_degree 0 u + tensor_degree 0 v = 0).
  by rewrite ihu ihv add0r.
- rewrite linearZ; change (a *: tensor_degree 0 u = 0).
  by rewrite ihu scaler0.
by rewrite linearB !tensor_degree_word !size_cat /= !addnS subrr.
Qed.

