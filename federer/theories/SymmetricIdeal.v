Variable K : fieldType.
Variable V : lmodType K.
Local Notation T := (tensor_algebra_space V).
Local Notation d := (@tensor_word K V).
Local Notation tb := (tensor_product_bilinear V).

(** Source for [symmetric_relation]: Federer 1.9.1, p. 41, commutator ideal
    and homogeneous decomposition. Supporting construction for this passage,
    in words: Span of adjacent-swap differences with arbitrary prefix and
    suffix words. *)
Inductive symmetric_relation : T -> Prop :=
| sr_zero : symmetric_relation 0
| sr_add x y : symmetric_relation x -> symmetric_relation y -> symmetric_relation (x + y)
| sr_scale a x : symmetric_relation x -> symmetric_relation (a *: x)
| sr_swap s t v w : symmetric_relation
    (d (s ++ v :: w :: t) - d (s ++ w :: v :: t)).

(** Source for [symmetric_subspace]: Federer 1.9.1, p. 41, commutator ideal
    and homogeneous decomposition. Supporting construction for this passage,
    in words: The span of the adjacent-swap differences is a vector
    subspace. *)
Definition symmetric_subspace : subspace T :=
  @Subspace K T symmetric_relation sr_zero sr_add sr_scale.

(** Source for [symmetric_relation_prefix]: Federer 1.9.1, p. 41, commutator
    ideal and homogeneous decomposition. Supporting construction for this
    passage, in words: The relation subspace is closed under multiplication
    by a prefix word. *)
Lemma symmetric_relation_prefix s x :
  symmetric_relation x -> symmetric_relation (tensor_product (d s) x).
Proof.
elim=> [|u w hu ihu hw ihw|a u hu ihu|u t v w].
- by rewrite (bil0r tb); exact: sr_zero.
- rewrite (bilDr tb); exact: sr_add ihu ihw.
- rewrite (bilZr tb); exact: sr_scale ihu.
by rewrite (bilBr tb) !tensor_product_words !catA; exact: sr_swap.
Qed.

(** Source for [symmetric_relation_suffix]: Federer 1.9.1, p. 41, commutator
    ideal and homogeneous decomposition. Supporting construction for this
    passage, in words: The relation subspace is closed under multiplication
    by a suffix word. *)
Lemma symmetric_relation_suffix s x :
  symmetric_relation x -> symmetric_relation (tensor_product x (d s)).
Proof.
elim=> [|u w hu ihu hw ihw|a u hu ihu|u t v w].
- by rewrite (bil0l tb); exact: sr_zero.
- rewrite (bilDl tb); exact: sr_add ihu ihw.
- rewrite (bilZl tb); exact: sr_scale ihu.
by rewrite (bilBl tb) !tensor_product_words -!catA /=; exact: sr_swap.
Qed.

(** Source for [symmetric_relation_mull]: Federer 1.9.1, p. 41, commutator
    ideal and homogeneous decomposition. Supporting construction for this
    passage, in words: The relation subspace is closed under arbitrary left
    multiplication. *)
Lemma symmetric_relation_mull x y :
  symmetric_relation y -> symmetric_relation (tensor_product x y).
Proof.
move=> hy; elim/tensor_word_induction: x => [|x x' hx hx'|a x hx|s].
- by rewrite (bil0l tb); exact: sr_zero.
- rewrite (bilDl tb); exact: sr_add hx hx'.
- rewrite (bilZl tb); exact: sr_scale hx.
exact: symmetric_relation_prefix hy.
Qed.

(** Source for [symmetric_relation_mulr]: Federer 1.9.1, p. 41, commutator
    ideal and homogeneous decomposition. Supporting construction for this
    passage, in words: The relation subspace is closed under arbitrary right
    multiplication. *)
Lemma symmetric_relation_mulr x y :
  symmetric_relation x -> symmetric_relation (tensor_product x y).
Proof.
move=> hx; elim/tensor_word_induction: y => [|y y' hy hy'|a y hy|s].
- by rewrite (bil0r tb); exact: sr_zero.
- rewrite (bilDr tb); exact: sr_add hy hy'.
- rewrite (bilZr tb); exact: sr_scale hy.
exact: symmetric_relation_suffix hx.
Qed.

(** Source for [commutator_ideal]: Federer 1.9.1, p. 41, commutator ideal
    and homogeneous decomposition. Supporting construction for this passage,
    in words: The two-sided ideal generated by the generator commutators. *)
Definition commutator_ideal : two_sided_ideal (tensor_algebra V) :=
  @TwoSidedIdeal K (tensor_algebra V) symmetric_subspace
    symmetric_relation_mull symmetric_relation_mulr.

(** Source for [commutator_ideal_generator]: Federer 1.9.1, p. 41,
    commutator ideal and homogeneous decomposition. Supporting construction
    for this passage, in words: Each generator commutator belongs to the
    ideal. *)
Lemma commutator_ideal_generator v w : commutator_ideal
  (tensor_product (tensor_generator v) (tensor_generator w) -
   tensor_product (tensor_generator w) (tensor_generator v)).
Proof. rewrite !tensor_product_words; exact: (sr_swap [::] [::] v w). Qed.

(** Source for [commutator_ideal_minimal]: Federer 1.9.1, p. 41, commutator
    ideal and homogeneous decomposition. Supporting construction for this
    passage, in words: Every two-sided ideal containing the generator
    commutators contains this ideal. *)
Lemma commutator_ideal_minimal (I : two_sided_ideal (tensor_algebra V)) :
  (forall v w, I (tensor_product (tensor_generator v) (tensor_generator w) -
    tensor_product (tensor_generator w) (tensor_generator v))) ->
  forall x, commutator_ideal x -> I x.
Proof.
move=> hi x; elim=> [|u v hu ihu hv ihv|a u hu ihu|s t v w].
- exact: subspace_zero.
- exact: subspace_add ihu ihv.
- exact: subspace_scale ihu.
have h := @ideal_mull K (tensor_algebra V) I (d s) _ (hi v w).
have h' := @ideal_mulr K (tensor_algebra V) I _ (d t) h.
move: h'; change (I (tensor_product
  (tensor_product (d s) (tensor_product (tensor_generator v) (tensor_generator w) -
    tensor_product (tensor_generator w) (tensor_generator v))) (d t)) ->
  I (d (s ++ v :: w :: t) - d (s ++ w :: v :: t))).
by rewrite (bilBr tb) (bilBl tb) !tensor_product_words -!catA.
Qed.

(** Source for [commutator_ideal_homogeneous]: Federer 1.9.1, p. 41,
    commutator ideal and homogeneous decomposition. Supporting construction
    for this passage, in words: Each homogeneous component of an ideal
    element still lies in the ideal. *)
Lemma commutator_ideal_homogeneous n x : commutator_ideal x -> commutator_ideal (tensor_degree n x).
Proof.
elim=> [|u v hu ihu hv ihv|a u hu ihu|s t v w].
- by rewrite linear0; exact: sr_zero.
- rewrite linearD; exact: sr_add ihu ihv.
- rewrite linearZ; exact: sr_scale ihu.
rewrite linearB !tensor_degree_word !size_cat /= !addnS.
case: ifP => _; first exact: sr_swap.
by rewrite subrr; exact: sr_zero.
Qed.

(** Source for [commutator_ideal_degree_zero]: Federer 1.9.1, p. 41,
    commutator ideal and homogeneous decomposition. Supporting construction
    for this passage, in words: The degree-zero component of every ideal
