(** Federer (1969), 3.4.7, p. 325: the least-degree
    argument for ideals in a field polynomial ring,
    supporting prime factorization in the Gauss argument.
    Every generator is a local existence witness. *)
From mathcomp Require Import all_boot all_order ssralg boolp classical_sets ring.
From Federer Require Import CommutativeIdealUP CommutativeFactorizationUP
  CommutativePolynomialUP CommutativePolynomialDegreeUP CommutativePolynomialDegree
  PolynomialFieldDivision.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.

(** Source for [polynomial_field_principal_ideals]: an ideal
    in the field polynomial ring is generated by
    a polynomial of least degree, or by zero
    when it is the zero ideal. This supporting
    assertion expands Gauss's lemma in 3.4.7, p. 325. *)
Theorem polynomial_field_principal_ideals (K:fieldType) (B:comNzRingType)
    (embed:{rmorphism K->B}) (variable:B) (coefficient:B->nat->K)
    (hP:is_commutative_polynomial_ring embed variable coefficient) (I:set B):
  is_commutative_ideal I ->exists G:B,I G /\forall P:B,I P <->commutative_divides G P.
Proof.
move=>hI;case:(pselect (exists P,I P /\P<>0))=>[[P0 [hIP0 hP0]]|hZero].
- have [n0 hDegree0]:=@polynomial_degree_exists K B embed variable coefficient hP P0 hP0.
  have hDegrees:exists n,`[<exists G:B,I G /\is_polynomial_degree coefficient G n>].
    exists n0;apply/asboolP;by exists P0.
  have [n /asboolP [G [hIG hDegreeG]] hMinimal]:=ex_minnP hDegrees.
  exists G;split;first exact:hIG.
  move=>P;split.
  + move=>hIP.
    have [q [r [hDivision hRemainder]]]:=
      @polynomial_field_division K B embed variable coefficient hP G n hDegreeG P.
    have hIR:I r.
      have hRExpression:r = P-q*G by rewrite hDivision;ring.
      rewrite hRExpression.
      apply:(@commutative_ideal_add B I hI);first exact:hIP.
      apply:(@commutative_ideal_opp B I hI).
      exact:(@commutative_ideal_mul B I hI q G hIG).
    case:hRemainder=>[hRZero|[d [hSmaller hDegreeR]]].
    * exists q;by rewrite hDivision hRZero addr0.
    * have hCandidate:`[<exists H:B,I H /\is_polynomial_degree coefficient H d>].
        apply/asboolP;by exists r.
      have hBound:=hMinimal d hCandidate.
      have hContradiction:=leq_ltn_trans hBound hSmaller.
      by rewrite ltnn in hContradiction.
  + move=>[q ->];exact:(@commutative_ideal_mul B I hI q G hIG).
- exists 0;split;first exact:commutative_ideal_zero hI.
  move=>P;split.
  + move=>hIP;have hPZero:P = 0.
      apply:contrapT=>hNonzero;apply:hZero;by exists P.
    exists 0;by rewrite hPZero mul0r.
  + move=>[q ->];rewrite mulr0;exact:commutative_ideal_zero hI.
Qed.
