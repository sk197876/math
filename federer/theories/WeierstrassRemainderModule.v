(** Federer (1969), 3.4.7, p. 325: every
    original directional polynomial remainder belongs to
    the transverse module generated by 1, xi, ..., xi^(k-1).
    The actual divided fields and the proved division
    representation supply its coefficients. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets reals.
From Federer Require Import Hom RealNormUP NormDifferentialUP NormOpenDomainLaws
  NormAnalyticUP NormAnalyticLinear AnalyticGermRepresentatives AnalyticGermUP
  AnalyticGermSealed AnalyticGermRingLaws AnalyticGermRing AnalyticGermFiniteSum AnalyticGermPowers
  AnalyticPullbackRepresentative AnalyticPullbackSealed AnalyticPullbackRingMorphism
  RingScalarRestriction RingSubmoduleUP RingSubmoduleFiniteSums TransverseAnalyticCoefficients
  WeierstrassTransverseUP WeierstrassTransversePullback WeierstrassDivisionUP WeierstrassCoefficientUP
  WeierstrassCoefficientExistence WeierstrassPolynomialHighCoefficients
  WeierstrassFiniteRemainderRepresentation.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import GRing.Theory.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.
Section RemainderModule.
Variable R:realType.
Variables X K:lmodType R.
Variables (NX:X->R) (NK:K->R).
Variables (hNX:is_real_norm NX) (hNK:is_real_norm NK).
Variable v:X.
Variable xi:Hom X R^o.
Variables (inclusion:Hom K X) (projection:Hom X K).
Variable hSplit:is_weierstrass_transverse_space NX NK v xi inclusion projection.
(** Source for [projection_at_origin]: the actual
    projection is analytic at zero, 3.4.7, p. 325. *)
Let projection_at_origin:=@weierstrass_transverse_projection_analytic R X K NX NK hNX hNK
  v xi inclusion projection hSplit.
(** Source for [coefficient_ring]: the original transverse
    germ ring, centred at projection of zero, which
    is zero by linearity, 3.4.7, p. 325. *)
Let coefficient_ring:comNzRingType:=
  [the comNzRingType of (@analytic_germ_ring R K NK hNK (projection 0))].
(** Source for [ambient_ring]: the original ambient
    germ ring in 3.4.7, p. 325. *)
Let ambient_ring:comNzRingType:=
  [the comNzRingType of (@analytic_germ_ring R X NX hNX 0)].
(** Source for [transverse_embed]: the original pullback
    giving the scalar action, 3.4.7, p. 325. *)
Let transverse_embed:{rmorphism coefficient_ring->ambient_ring}:=
  @analytic_germ_ring_pullback R X K NX NK hNX hNK setT projection 0 projection_at_origin.

(** Source for [weierstrass_remainder_in_transverse_module]:
    the remainder in 3.4.7, p. 325, lies
    in the actual finite power module. The only
    module premises are its independent closure and
    generator laws; neither remainder membership nor any
    Noetherian conclusion is supplied as a premise. *)
Theorem weierstrass_remainder_in_transverse_module k
    (fXi:@analytic_representative_type R X NX hNX 0)
    (M:set (ring_restricted_space transverse_embed ambient_ring^o))
    (rho:ambient_ring):
  norm_bounded_linear NX (fun t:R^o=>`|t|) xi ->
  (forall x,analytic_representative_value fXi x = xi x) ->
  @is_ring_submodule coefficient_ring
    [the lmodType coefficient_ring of (ring_restricted_space transverse_embed ambient_ring^o)] M ->
  (forall i,(i<k)%N ->M ((analytic_germ fXi:ambient_ring)^+i)) ->
  @is_directional_polynomial_germ R X NX hNX k v rho ->M rho.
Proof.
move=>hXi hXiValues hM hGenerators hPolynomial.
have [r hR]:=@weierstrass_split_coefficients_exist R X K NX hNX rho v inclusion.
have hHigh:=@weierstrass_polynomial_high_coefficients R X K NX hNX k v inclusion rho r
  hPolynomial hR.
have [g [hGRho [C [hC [_ hValues]]]]]:=@weierstrass_finite_remainder_representation
  R X K NX NK hNX hNK v xi inclusion projection k rho r hSplit hXi hR hHigh.
have hPower i:=@analytic_representative_power_exists R X NX hNX 0 fXi i.
have [powers hPowers]:=choice hPower.
have hCoefficient i:exists c:@analytic_representative_type R K NK hNK (projection 0),
    forall z,analytic_representative_value c z = C i (inclusion z).
  exact:(@transverse_analytic_coefficient_representative R X K NX NK hNX hNK
    v xi inclusion projection (C i) hSplit (hC i)).
have [coefficients hCoefficients]:=choice hCoefficient.
pose pullback i:=@analytic_pullback_representative R X K NX NK hNX hNK setT
  projection 0 projection_at_origin (coefficients i).
pose terms (i:'I_k):=@analytic_multiply_representatives R X NX hNX 0 (powers i) (pullback i).
have hTerm i:(analytic_germ (terms i):ambient_ring) =
    transverse_embed (analytic_germ (coefficients i))*(analytic_germ fXi:ambient_ring)^+i.
  rewrite /terms -(@analytic_germ_multiply_equation _ _ _ _ _ _ _ _ (@AnalyticGerms.laws R X NX hNX 0)).
  have hPullback:(analytic_germ (pullback i):ambient_ring) =
      transverse_embed (analytic_germ (coefficients i)).
    exact:esym (@AnalyticPullback.laws R X K NX NK hNX hNK setT projection 0
      projection_at_origin (coefficients i)).
  change ((analytic_germ (powers i):ambient_ring)*analytic_germ (pullback i) =
    transverse_embed (analytic_germ (coefficients i))*(analytic_germ fXi:ambient_ring)^+i).
  by rewrite hPullback (hPowers i).2 mulrC.
have hTermMembership i:M (analytic_germ (terms i):ambient_ring).
  rewrite hTerm.
  exact:(@ring_submodule_scale coefficient_ring
    [the lmodType coefficient_ring of (ring_restricted_space transverse_embed ambient_ring^o)]
    M hM (analytic_germ (coefficients i)) ((analytic_germ fXi:ambient_ring)^+i)
    (hGenerators i (ltn_ord i))).
pose F:=map terms (enum 'I_k).
have hFiniteValues x:analytic_representative_value g x =
    \sum_(term<-F) analytic_representative_value term x.
  rewrite hValues /F big_map -big_enum.
  apply:eq_bigr=>i _.
  change ((xi x)^+i*C i (inclusion (projection x)) =
    analytic_representative_value (powers i) x*analytic_representative_value (pullback i) x).
  by rewrite (hPowers i).1 hXiValues /pullback /= (hCoefficients i).
have hGermSum:=@analytic_germ_finite_sum_equation R X NX hNX 0 F g hFiniteValues.
rewrite -hGRho hGermSum.
apply:(@ring_submodule_mapped_sum coefficient_ring
  [the lmodType coefficient_ring of (ring_restricted_space transverse_embed ambient_ring^o)]
  M hM (@analytic_representative_type R X NX hNX 0) F
  (fun term=>(analytic_germ term:ambient_ring)))=>term.
rewrite /F;move/mapP=>[i _ ->];exact:hTermMembership i.
Qed.
End RemainderModule.
