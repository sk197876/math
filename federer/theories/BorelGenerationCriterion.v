(** Federer (1969), 2.2.1, p. 60: the two generation criteria, with the
    required empty-generator hypothesis from Federer's May 1987 erratum, p.
    1, book p. 60 line 4. Source context: BorelFamilyUP.v. The boolean
    parameter covers both printed cases. *)
From mathcomp Require Import all_boot boolp classical_sets.
From Federer Require Import BorelFamilyUP CountablyClosedFamilyUP
  CountablyClosedFamilyBasic BorelComplementCore.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope classical_set_scope.

(** Source for [generated_closed_family_borel_criterion]: Federer
    2.2.1, p. 60, both generation criteria. With the correction
    empty set in S (erratum p. 1, book p. 60 line 4), if the
    complements of generators lie in the generated closure family,
    that family is the Borel family generated by S. *)
Theorem generated_closed_family_borel_criterion (d : bool) (I : choiceType)
    (X : set I) (S F : set (set I)) (hF : is_generated_closed_family d X S F) :
  S set0 -> (forall A, S A -> F (X `\` A)) -> is_generated_borel_family X S F.
Proof.
move=> h0 hc; have hl := generated_closed_family_laws hF.
have hX : F X by have h := hc set0 h0; rewrite setD0 in h.
pose H := [set A | F A /\ F (X `\` A)].
have hH : is_borel_family X H := countably_closed_complement_core_borel hl hX.
have hSH : S `<=` H.
  move=> A hA; split; last exact: hc.
  exact: (@generated_closed_family_contains d I X S F hF A hA).
have hFH : F `<=` H.
  exact: (@generated_closed_family_least d I X S F hF H
    (@borel_family_countably_closed d I X H hH) hSH).
have he : F = H by apply/seteqP; split=> // A [hA _].
constructor.
- by rewrite he.
- exact: generated_closed_family_contains hF.
- move=> G hG hS; exact: (@generated_closed_family_least d I X S F hF G
    (@borel_family_countably_closed d I X G hG) hS).
Qed.

(** Source for [borel_generation_by_countable_closure]: Federer 2.2.1, p.
    60, first criterion, using (2) and (3), with the empty-generator
    correction. *)
Corollary borel_generation_by_countable_closure (I : choiceType)
    (X : set I) (S F : set (set I)) :
  is_generated_closed_family false X S F -> S set0 ->
  (forall A, S A -> F (X `\` A)) -> is_generated_borel_family X S F.
Proof. exact: generated_closed_family_borel_criterion. Qed.

(** Source for [borel_generation_by_disjoint_closure]: Federer 2.2.1, p. 60,
    second criterion, using (2)' and (3), with the same empty-generator
    correction. *)
Corollary borel_generation_by_disjoint_closure (I : choiceType)
    (X : set I) (S F : set (set I)) :
  is_generated_closed_family true X S F -> S set0 ->
  (forall A, S A -> F (X `\` A)) -> is_generated_borel_family X S F.
Proof. exact: generated_closed_family_borel_criterion. Qed.
