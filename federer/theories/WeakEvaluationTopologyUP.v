(** Federer (1969), 4.1.1, pp. 344–345: the weak topology
    on each continuous dual is the topology generated by its
    real evaluations. Its independent universal property is
    stated before any product-topology witness is selected. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets reals.
From Federer Require Import RealNormUP OpenFamilyTopologyUP NormOpenTopology.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.

(** Source for [is_weak_evaluation_topology]: the weakest topology
    making every real evaluation continuous, equivalently the
    universal mapping property for the strips a<T(phi)<b in
    Federer 4.1.1, pp. 344–345. This specification neither assumes
    linearity nor identifies distinct evaluation families. *)
Definition is_weak_evaluation_topology (R:realType) (E D:choiceType)
    (ev:D->E->R) (O:set (set D)) :=
  is_open_family_topology O /\ forall (Z:choiceType) (P:set (set Z)),
    is_open_family_topology P -> forall f:Z->D,
      (open_family_continuous P O f <-> forall e,
        open_family_continuous P (norm_open_family (@scalar_absolute_value_norm R))
          (fun z=>ev (f z) e)).
