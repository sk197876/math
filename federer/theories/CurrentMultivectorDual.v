(** Federer (1969), 4.1.7, p. 357: apply
    the original integration representation theorem
    with Y the comass-normed covectors and Y* the
    actual mass-normed multivectors. All dual laws
    are discharged for these actual spaces. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets reals.
From Federer Require Import Hom RealNormUP RealFunctionalNormUP ContinuousRealFunctional
  ContinuousDualUP LinearBasis ExteriorGrading ExteriorIndices FiniteExteriorPowers GrassmannAbbreviations
  FiniteCoordinates AlternatingForms CurrentCoefficientNorms CurrentDualNorm
  MultivectorDualSealed FiniteMultivectorDual WeakEvaluationTopologyUP WeakEvaluationTopologySealed.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.
Section CurrentMultivectorDual.
Variable R:realType.
Hypothesis h2:(1+1:R)!=0.
Variables n m:nat.
Local Notation V := (R_n R n).
Local Notation Y := (A_m V R^o m).
Local Notation NY := (@current_form_comass R h2 n m).
Local Notation hNY := (@current_form_comass_real_norm R h2 n m).
Local Notation DN := (@current_vector_mass R h2 n m).
Local Notation E := (@MultivectorDual.evaluation R V m).

(** Source for [current_multivector_continuous_dual]:
    the whole actual multivector space with mass
    satisfies the original continuous-dual laws,
    Federer 4.1.7, p. 357. *)
Theorem current_multivector_continuous_dual:is_continuous_dual hNY E DN.
Proof.
pose I:finType:=Finite.clone (Lambda n m) _.
pose b:I->exterior_power V m:=fun lambda=>e_lambda (@coordinate_basis R n) (val lambda).
have hb:is_basis b:=@finite_e_lambda_basis R n V (@coordinate_basis R n)
  (@coordinate_basisP R n) h2 m.
constructor.
- exact:(@finite_multivector_dual_injective R V m I b hb).
- move=>xi; have h:=@current_multivector_dual_norm R h2 n m xi.
  exact:(@bounded_real_functional_continuous R Y NY hNY (hom_as_linear (E xi)) (DN xi)
    (real_functional_norm_nonnegative h) (real_functional_norm_bound h)).
- move=>a _; exact:(@finite_multivector_dual_surjective R V m I b hb a).
- move=>xi; exact:(@current_multivector_dual_norm R h2 n m xi).
Qed.

(** Source for [current_multivector_weak_opens]: the
    weak dual topology generated by the original
    covector evaluations, Federer 4.1.7, p. 357,
    using the topology of 4.1.5. *)
Definition current_multivector_weak_opens:set (set (exterior_power V m)):=
  @WeakEvaluationTopology.opens R Y (exterior_power V m) (fun xi phi=>E xi phi).

(** Source for [current_multivector_weak_laws]: the
    actual multivector topology has precisely the
    original weak evaluation law, supporting Federer
    4.1.7, p. 357. *)
Lemma current_multivector_weak_laws:
  is_weak_evaluation_topology (fun xi phi=>E xi phi) current_multivector_weak_opens.
Proof. exact:WeakEvaluationTopology.laws. Qed.
End CurrentMultivectorDual.
