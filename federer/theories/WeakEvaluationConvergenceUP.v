(** Federer (1969), 4.1.1, pp. 344–345: the independent
    pointwise convergence characterization of the real-evaluation
    weak topology. *)
From mathcomp Require Import all_boot all_order all_algebra classical_sets reals topology.
From Federer Require Import RealNormUP NormOpenTopology OpenFamilyConvergence.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope classical_set_scope.

(** Source for [is_weak_evaluation_convergence]: a filter
    converges weakly exactly when every real evaluation converges,
    supporting the weak topology generated by the strips in
    Federer 4.1.1, pp. 344–345. *)
Definition is_weak_evaluation_convergence (R:realType) (E D:choiceType)
    (ev:D->E->R) (O:set (set D)):=
  forall (F:set_system D),Filter F -> forall d,
    (open_family_converges O F d <-> forall e,
      open_family_converges (norm_open_family (@scalar_absolute_value_norm R))
        ((fun x=>ev x e) @ F) (ev d e)).
