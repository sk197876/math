(** Federer (1969), 3.4.12, p. 339, extending 3.4.11, p. 338:
    the leading polynomial germs generate an actual
    ideal. Reuse the existing least-ideal existence theorem;
    no representation by holomorphic combinations is exposed. *)
From mathcomp Require Import all_boot all_order all_algebra boolp classical_sets reals.
From Federer Require Import ScalarRestriction ComplexScalarSealed RealNormUP HolomorphicGermRing CommutativeIdealUP CommutativeIdealSealed
  HolomorphicInitialPolynomialGermUP.
Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Local Open Scope ring_scope.
Local Open Scope classical_set_scope.

(** Source for [holomorphic_initial_ideal_exists]: existence
    of the ideal generated by the original leading
    homogeneous polynomials in 3.4.11, p. 338.
    Its independent least-ideal laws precede this witness. *)
Theorem holomorphic_initial_ideal_exists (R:realType) (X:lmodType (ComplexScalars.C R))
    (NX:X->R) (hNX:@is_real_norm R (restricted_space (ComplexScalars.embed R) X) NX)
    (I:set (@holomorphic_germ_ring R X NX hNX 0)):
  exists J,is_holomorphic_initial_ideal I J.
Proof.
exists (@GeneratedCommutativeIdeal.value
  [the comNzRingType of (@holomorphic_germ_ring R X NX hNX 0)]
  (holomorphic_initial_polynomial_generators I)).
exact:GeneratedCommutativeIdeal.laws.
Qed.
