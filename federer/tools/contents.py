"""Generate docs/contents.md: Federer item numbers -> Rocq files.

Usage (from the repository root): python3 tools/contents.py

Every named declaration is preceded by a comment
(** Source for [name]: ... *) whose first Federer item number
(chapter.section.item) is taken as the item the declaration serves.
For each item the script lists the files containing such declarations,
with links to the principal declarations.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECL = re.compile(
    r'\(\*\*\s*Source for \[([^\]]+)\]:(.*?)\*\)\s*\n\s*'
    r'(?:Local\s+|Global\s+|#\[[^\]]*\]\s*)?'
    r'(Definition|Fixpoint|Lemma|Theorem|Corollary|Proposition|Record|Inductive|'
    r'Example|Parameter|Fact|Remark|Let)\s+([A-Za-z0-9_\']+)', re.S)
ITEM = re.compile(r'(?<![\d.])([123])\.(\d{1,2})\.(\d{1,2})(?!\d)')
RANK = {'Theorem': 0, 'Corollary': 0, 'Proposition': 0, 'Definition': 1, 'Record': 1,
        'Inductive': 1, 'Fixpoint': 1, 'Parameter': 2, 'Lemma': 3, 'Fact': 3,
        'Remark': 3, 'Example': 4, 'Let': 5}
SHOWN = 6
SECTIONS = {
    '1.1': 'Tensor products', '1.2': 'Graded algebras',
    '1.3': 'The exterior algebra of a vectorspace', '1.4': 'Alternating forms and duality',
    '1.5': 'Interior multiplications', '1.6': 'Simple m-vectors', '1.7': 'Inner products',
    '1.8': 'Mass and comass', '1.9': 'The symmetric algebra of a vectorspace',
    '1.10': 'Symmetric forms and polynomial functions',
    '2.1': 'Measures and measurable sets', '2.2': 'Borel and Suslin sets',
    '2.3': 'Measurable functions', '2.4': 'Lebesgue integration', '2.5': 'Linear functionals',
    '2.6': 'Product measures', '2.7': 'Invariant measures', '2.8': 'Covering theorems',
    '2.9': 'Derivates', '2.10': "Carathéodory's construction",
    '3.1': 'Differentials and tangents',
    '3.2': 'Area and coarea of Lipschitzian maps',
}


def key(item):
    return tuple(int(x) for x in item.split('.'))


def titles():
    result = {}
    section_files = list((ROOT / 'docs').glob('chapter[123]/*.md'))
    section_files += list((ROOT / 'docs').glob('[123].*.md'))
    for p in sorted(section_files):
        for line in p.read_text().splitlines():
            m = re.match(r'^## (\d+\.\d+\.\d+) — (.*)$', line)
            if m and m.group(1) not in result:
                result[m.group(1)] = (m.group(2), p.relative_to(ROOT / 'docs').as_posix())
    return result


def collect():
    """Map item -> file -> list of (rank, line, name, kind)."""
    files = [l for l in (ROOT / '_CoqProject').read_text().split() if l.endswith('.v')]
    files += sorted(str(p.relative_to(ROOT)) for p in (ROOT / 'tests').glob('*Examples.v'))
    files = list(dict.fromkeys(files))
    items = {}
    for f in files:
        s = (ROOT / f).read_text()
        for m in DECL.finditer(s):
            it = ITEM.search(m.group(2))
            if not it:
                continue
            line = s.count('\n', 0, m.start(4)) + 1
            items.setdefault(it.group(0), {}).setdefault(f, []).append(
                (RANK.get(m.group(3), 5), line, m.group(4), m.group(3)))
    return items


def main():
    items = collect()
    names = titles()
    out = ['# Contents: Federer items and Rocq files', '',
           'This map lists, for each numbered item of',
           '[Federer1969](bibliography.md#federer1969), the Rocq files whose declarations',
           'serve it. A declaration',
           'is attributed to the first item number in its `Source for [...]`',
           'comment, so an item may be spread over several files, and supporting',
           'lemmas appear under the item they were written for. Up to six',
           'principal declarations per file are linked, theorems first. The map is',
           'generated by `tools/contents.py`; regenerate it after adding modules.',
           'The mathematical account of each item is in the section files listed in',
           '[toc.md](toc.md).', '']
    chapter = section = None
    for it in sorted(items, key=key):
        c, s_, _ = it.split('.')
        if c != chapter:
            chapter = c
            out += ['## Chapter ' + c, '']
        if (c, s_) != section:
            section = (c, s_)
            out += ['### ' + c + '.' + s_ + ' ' + SECTIONS.get(c + '.' + s_, ''), '']
        title, doc = names.get(it, ('', ''))
        head = '#### ' + it
        if title:
            head += ' — ' + title
        out.append(head)
        out.append('')
        if doc:
            out.append('Account: [' + doc + '](' + doc + ').')
            out.append('')
        for f in sorted(items[it], key=lambda f: Path(f).name):
            seen, decls = set(), []
            for d in sorted(items[it][f]):
                if d[2] not in seen:
                    seen.add(d[2])
                    decls.append(d)
            shown = ', '.join('[`%s`](../%s#L%d)' % (n, f, l) for _, l, n, _ in decls[:SHOWN])
            more = len(decls) - SHOWN
            if more > 0:
                shown += ', and %d more' % more
            out.append('- [%s](../%s): %s' % (Path(f).name, f, shown))
        out.append('')
    (ROOT / 'docs' / 'contents.md').write_text('\n'.join(out).rstrip('\n') + '\n')
    print('items:', len(items), 'files:', sum(len(v) for v in items.values()))


if __name__ == '__main__':
    main()
